 On this day the two saints Atrasis
and Yoana (Junia), were martyred. Atrasis was the daughter of the pagan
Emperor Hadrian. Because of his great love for her, he built a special
small room where she could be away from people. Atrasis thought always
about the vanity of the world and the end of life. Day and night she asked
for guidance towards the right way. In a vision at night, she saw a person
who told her, &quot;Bring Yoana (Junia), the virgin, the daughter of Philospheron,
and she will teach you the way of the Lord.&quot; When Atrasis woke from her
sleep, her soul rejoiced and she sent for Yoana, who came to her at once.
Princess Atrasis met Yoana, bowed down before her and embraced her. Yoana
started to tell her the reason for the incarnation of the Son of God, starting
with the creation of Adam and how he was expelled from paradise, the coming
down of the flood and the renewal of the creation once more, the reason
for worshipping idols, the appearance of God to Abraham, the exodus of
the Israelites from Egypt, how the prophets proclaimed the coming of the
Son of God, His coming down from Heaven and His incarnation through the
Virgin and the salvation of the world from the hand of Satan. She made
clear to Atrasis what the godly people will receive; and that is, heavenly
grace in eternal life. When the virgin princess heard that, her soul rejoiced
exceedingly. The words of Yoana were sweeter than honey to her ears and
she immediately believed in the Lord Jesus Christ, to Whom be the Glory.
The two virgins worshipped day and night with fasting and prayers. One
night they saw the Lord Christ and the Virgin Lady, His Mother, in a dream.
The Lord placed His hand over their heads and blessed them.</p>
