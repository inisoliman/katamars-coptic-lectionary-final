 On this day also, of the
year 80 A.D., St. Philip the Apostle, one of the Twelve Disciples, was
martyred. His lot fell to go to Africa and the surrounding regions. He
went and preached there in the Name of the Lord Christ. There, he performed
many miracles and wonders which astounded the people. After he led the
people to the knowledge of God, confirming them in the faith, he went to
Herapolis, where he also led the people to the knowledge of God. The non-believers
took counsel together to kill him, accusing him of disobeying the king's
order that no stranger was allowed to enter their city. They jumped him
and seized him, but he smiled at them saying, &quot;Why do you keep yourselves
away from everlasting life and why don't you think about the salvation
of your souls?&quot; But they did not pay any attention to his words, instead
they tortured him severely, then they crucified him head down. During the
crucifixion an earthquake took place; the people were terrified and ran
away. Some believers arrived and wanted to untie him from the cross, but
he asked them to leave him, so he might finish his strife and receive his
crown. He delivered his soul to the hands of Christ and received the crown
of eternal glory in the year 80 A.D. and was buried there. In the sixth
century A.D., his body was transferred to Rome. The Lord manifested many
signs and great wonders through the body of St. Philip.
