 Meanwhile, her father, the Emperor
had gone to war. When he came back his daughter was betrothed to be married.
Before the wedding ceremony, her father asked her to offer incense to the
god Apollo, before getting ready for her bridegroom. She told him, &quot;Father,
how could you forsake the God of heaven and earth and worship defiled idols?
Turn, O my father, to the God Who created you and in Whose hand is your
life and death.&quot; When her father heard these words, which he had never
heard from her before, he asked who taught her that. They told him it was
Yoana, the daughter of Philospheron, who corrupted her mind. He ordered
them both to be burned. They took them outside the city, arrayed in their
beautiful garments and their jewelry. Their slaves and handmaidens were
crying. All the people of the city were sorry for the youth of these two
saints and they asked them to submit to the Emperor's wish by offering
incense to the idols, but they would not turn from their decision. When
they dug the pit and lit the fire, the two saints held each other's hands
and they cast themselves into the fire. They stood in the fire, turned
their faces towards the east and prayed, and many had seen them. After
the fire was out, some of the believers who were present went forward to
take their bodies. They found them stuck to each other; their garments
and their jewelry were not burned. They placed their bodies in a safe place
until the end of the persecution era, then they
 built a great church for them.
