 They had Arius brought before
them and asked him to state his faith. He blasphemed saying, &quot;The Father
was when the Son was not.&quot; When they explained to him his error and he
did not change his opinion, they excommunicated him and all those who shared
his opinion and belief. Then they wrote the Canon of the Christian faith
which is known as the &quot;Nicene Creed&quot;. It states:
<br /> <b>1.</b> Truly we believe in one God, God the Father, the
Pantocrator, Who created heaven and earth, and all things, seen and unseen.
<br /> <b>2.</b> We believe in one Lord, Jesus Christ, the Only-Begotten Son
of God, begotten of the Father before all ages; Light of Light; True God
of True God; Begotten not created, of One Essence with the Father, by Whom
all things were made.
<br /> <b>3.</b> Who, for us men and for our salvation, came down from heaven,
and was incarnate of the Holy Spirit and of the Virgin Mary and became
Man.
<br /> <b>4.</b> And He was crucified for us under Pontius Pilate; suffered
and was buried.
<br /> <b>5.</b> And the third day He arose from the dead, according to the
Scriptures.
<br /> <b>6.</b> Ascended into the heavens; He sits at the right hand of His
Father.
<br /> <b>7.</b> And He is coming again in His glory to judge the living and
the dead, Whose kingdom shall have no end.
