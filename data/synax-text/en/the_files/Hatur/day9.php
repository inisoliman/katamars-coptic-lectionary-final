 Also on this day, of the
year 325 A.D., 318 fathers assembled in the city of Nicea, in the days
of Emperor Constantine, the righteous Emperor. Among them were the heads
of the four Sees and they were: Anba Alexandros, the 19th Pope of Alexandria,
who was accompanied by Athanasius, his Archdeacon and private secretary;
Estasius, archbishop of Antioch; Macarius, Archbishop of Jerusalem. Sylvestros,
archbishop of Rome, because of his old age did not attend and sent two
priests in his place. The reason for their assembly2was to judge Arius
who was a priest in Alexandria. He blasphemed against the Son of God, the
Lord Jesus Christ by saying that he was not equal in essence to God, His
Father, and there was a time when the Son did not exist. Among those who
attended this council were holy fathers, who were, in the rank of the Apostles,
able to raise the dead, heal the sick and work great wonders. Among them
also were those who were tortured for the sake of their faith, lost their
eyes, or had their hands or feet cut off, or had their teeth smashed or
their nails pulled out or their ribs broken. One of them was the fighter
St.Bephnotius, the confessor, one of the bishops of upper Egypt who was
tortured much during the days of Diocletian. They plucked out his right
eye, burnt the flesh of his left leg, bound him in chains and took him
to cut marble in a stone quarry. He was called the martyr among priests.
He was a holy old man, loved by God and the people. The Lord worked many
wonders through his supplications and prayers. When the fathers convened,
they sat on the chairs prepared for them. Then the righteous Emperor Constantine
came and greeted them, starting with St.Bephnotius, the Bishop, whom he
respected much. The Emperor kissed with honor the scars of his wounds.
