 <p <?php echo $text_2; ?>>Departure of the Holy Father Anba Isaac,
the Forty-First Pope of Alexandria</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
  On this
day, of the year 679 A.D., the great holy father Anba Isaac, 41st Pope
of Alexandria, departed. This father was born in El-Borolos from rich,
God-fearing parents. They begot him long after their marriage. When they
took him for baptism, the bishop who baptized him saw a cross of light
over his head. The bishop laid the boy's hand over his head and prophesied
concerning him saying, &quot;The church of God will be entrusted to him.&quot; Then
he told his parents, &quot;Take care of him, for he is a chosen vessel of God.&quot;
When he grew they taught him writing, the Christian doctrine and church
subjects. He read extensively in the biography of saints and he was filled
with their pure life. He longed for the monastic life, so he left his parents
and went to the desert of St. Macarius. He became a monk and disciple of
Anba Zacharias, the Hegumen. The angel of the Lord had informed the elder
father beforehand of his coming and the father received him with joy. One
day, one of the holy elders saw him in the church and prophesied about
him saying, &quot;The church of Christ will be entrusted to him.&quot; Pope John,
the Patriarch of that time, asked for a monk to be his scribe and private
secretary. The people who were present recommended this honorable father
Isaac. The Pope had father Isaac brought to him. He gave him a book to
scribe. Anba Isaac made mistakes in his writing deliberately, hoping that
the Pope might send him back, for he had forsaken the glory of men.
</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 When the father knew his
intention he said to him, &quot;You have written well, do not leave this place.&quot;
When Fr. Isaac realized that the Patriarch would not let him return, he
used all his knowledge and writing ability and his virtues became known.
The Patriarch rejoiced in him exceedingly. Nevertheless, because Fr. Isaac
was still longing for solitary life, the Patriarch allowed him to return
to the desert. When the departure of Pope John drew near, he asked the
Lord Christ to let it be known to him who would be his successor. In a
vision, he was told that his disciple Isaac would sit on the chair after
him. The Pope commanded the people that, with a divine revelation and by
the order of the Lord, Isaac would sit on the chair after him. When this
father was enthroned to the See of St. Mark, the church was illumined.
He restored many churches, especially the church of St. Mark the Evangelist,
and the patriarchal cell. He suffered many tribulations and sat upon the
throne for three and a half years, then departed in peace.
