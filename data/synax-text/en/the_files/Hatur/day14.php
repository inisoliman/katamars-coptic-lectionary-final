 On this day, the great St. Martinus,
Bishop of Tours (Thrace, in France), departed. He was born to Christian
parents in a city called Sorpeia. He grew up to be gentle and a worshipper
who kept the Orthodox faith. He did not spare any effort in resisting the
followers of Arius, who were enraged by him. Consequently, they waited
for him on a road several times and beat him. When they continued chasing
him, he left the city. He went to live in a cave near the shore of the
Mediterranean Sea. There, he sustained himself by eating plants. When his
reputation spread throughout the country, he was chosen to be Bishop of
Tours (Thrace). He lived an apostolic life, and grew in charity and mercy
towards many people. The Lord performed many miracles through him. Once
when he was passing by, he saw a person stopping a funeral and preventing
the deceased person's family from burying him, claiming that the deceased
owed him 400 dinars. This holy father entreated him to release the dead
body, but the man refused. St. Martinus prayed and entreated God to make
the truth known. The dead man was raised immediately and he rebuked the
man who falsely accused him, exposing his lies before those present. Subsequently,
the unjust man died and the man who was raised up from death through the
prayers of St. Martinus, went back to his home and lived many years. This
holy father completed his distinguished life and departed in peace.
