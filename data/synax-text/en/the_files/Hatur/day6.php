 On this day, the holy father
St. Felix, Pope of Rome, departed. He was born of Christian parents in
Rome in the year 210 A.D. They raised him with high principles and he gradually
advanced in the clerical ranks. Astasius, Pope of Rome, ordained him a
deacon. Pope Justus, seeing his righteousness and virtues, ordained him
a priest. When Abba Dionysius, Pope of Rome, (who was contemporary of St.
Thaouna, Pope of Alexandria) departed, this father was chosen for the Roman
See. He shepherded the flock of Christ with the best of care. When Aurelianus
Caesar reigned, he incited persecution against the believers of the Lord
Christ. He tortured them using very painful methods, and many of them were
martyred by his hands. Since great tribulation befell St. Felix from the
Emperor, he entreated God to take these tribulations away from His people.
Because of his prayers, the Emperor died in the second year of his reign.
When Diocletian reigned, he also persecuted the Christians and started
torturing them. Pope Felix prayed to the Lord to spare him from witnessing
the torture of the Christians. So, he departed in the first year of the
reign of Diocletian, after he had sat upon the Apostolic throne for five
years. He left many sayings and discourses, some of which were useful teachings
and others were about the doctrines.
