 On this day, Sts. John and
James, Bishops of Persia, were martyred by the hands of Shapur, the son
of Hormuzd (Hermez), King of Persia. When the King demanded them to worship
the sun and fire, and to offer sacrifices to them, they did not obey him.
Instead, they continued teaching and confirming the people in the faith
of the Lord Christ, to Whom is the glory. Therefore, the King ordered them
be tortured severely. When they would not turn from the faith, and would
not cease from teaching the people and strengthening them, in spite of
their torture, he ordered them be cast into the fire. They gave up their
souls into the hand of the Lord Christ, thus received the crown of glory
with all the saints.
