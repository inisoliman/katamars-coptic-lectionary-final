 On this day also, Sts. Epimachus
and Azarianus, who were from the city of Rome, were martyred. Some people
accused them of being Christians to the Governor, who was appointed by
Maximianus the Emperor. He brought them and questioned them about their
belief. They confessed that they were Christians. Then they reproved him
for having forsaken the worship of God, who created the Heaven, the Earth,
and all that is therein. They also admonished him for worshipping man-made
idols which could neither see nor hear and wherein dwelt Satan, who led
men astray by worshipping these idols. The Governor marvelled at their
audacity and commanded their necks to be cut off. Thus they received the
crown of martyrdom.
