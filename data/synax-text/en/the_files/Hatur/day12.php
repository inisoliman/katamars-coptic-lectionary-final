coins were for the sheep, the fish and the flour, and the 300 dinars were
for him and his children. God had remembered them and their oblations and
had rewarded them here, in this world and in the kingdom of heaven on the
last day. As Dorotheus and his wife were astonished at this matter, the
Archangel Michael said to them, &quot;I am Michael the Archangel who delivered
you from all your tribulations and I have taken your oblations and alms
up to God, you shall lack no good thing whatsoever in this world.&quot; They
prostrated themselves before him and he disappeared and went up into heaven.
This was one of the innumerable miracles of this honored Angel.
