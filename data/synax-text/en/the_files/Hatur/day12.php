 An example of one of his wonders: A God-fearing
man whose name was Dorotheus and his wife Theopista, held a festival of
commemoration for the honored angel Michael on the twelfth day of each
month. It happened that this righteous family fell on hard times and had
nothing to celebrate with for the commemoration of the honored Michael.
They took their clothes to sell so that they might have a feast. Michael
the Archangel appeared to Dorotheus and commanded him not to sell his clothes,
but to go to a sheep-master and to take from him a sheep worth one-third
of a dinar. He was also to go to a fisherman and to take from him a fish
worth one-third of a dinar but Dorotheus was not to slit open the fish
until he came back to him. Finally, he was to go to a flour merchant and
to take from him as much flour as he needed. Dorotheus did as the Angel
commanded him. He invited the people, as was his custom, to the feast honoring
the Archangel Michael. When he went into his storeroom looking for wine
for the offering, he found that all the containers had been filled with
wine and many other good things. He marvelled and was astonished.</p>
