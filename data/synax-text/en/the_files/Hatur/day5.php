 On this day was the appearance
     of the head of St. Longinus the Soldier who pierced the side of our Savior,
     when He was on the Cross. Emperor Tiberius Caesar sent a soldier to Cappadocia
     to cut off the head of this saint, as it is written in the 23rd day of
     the month of Abib. The soldier fulfilled the order and brought the head
     to Jerusalem, and handed it to Pontius Pilate. Pilate showed the head to
     the Jews, who rejoiced at his deed. Pilate commanded that the head be buried
     in some of the piles of dirt outside Jerusalem. There was a woman who
     had believed at the hands of St. Longinus when he preached in Cappadocia.
     During his execution, she stood, weeping, and witnessed his martyrdom.
     Later on she became blind. So, she took her son and departed to Jerusalem
     to be blessed by the holy places, and the holy sepulchre, hoping that she might regain her sight.
     When she arrived in Jerusalem, her son died. She became very sad and grieved
     because of her condition and there was no one to take her back to her own
     country.</p>
