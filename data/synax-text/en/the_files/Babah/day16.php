 On this day of the year
673 A.D., the holy father, the Patriarch Abba Agathon, 39th Pope of Alexandria,
departed. He was a disciple to the holy father Abba Benjamin, 38th Pope.
Abba Benjamin disappeared for a period of time from the face of his Chalcedonian
persecutors and left Agathon to preach to the believers and establish them
in the Orthodox faith. Agathon went around the streets and markets in the
daytime wearing a carpenter's apparel, and during the night wearing a priest's
uniform. He went around the houses also preaching and instructing the believers.
He kept doing this till the Arab conquest of Egypt and the return of the
father the Patriarch Abba Benjamin to his chair. When Pope Benjamin departed,
this saint was chosen to the honorable rank of Patriarch. He faced great
tribulations for the sake of keeping the Orthodox faith. For example, a
man whose name was Theodosius, a Malachite, went to the city of Damascus
and came before Yazeed-Eben-Moawia, the Arab Governor of Damascus. He gave
him much money and took from him an order to appoint him the Governor of
Alexandria, Behira and Marriot. When he became in charge of this position,
he afflicted our father the Patriarch and levied great taxes on him. Because
of the excessive evil of the Governor, and what he did to the father the
Patriarch, the people hated and avoided him. He put forth an order that
any man who might find the Patriarch on his way should slay him. The Patriarch
remained in his cell until God destroyed that evil Governor. In the days
of this father, the building of St. Macarius' church in his monastery at
Wadi-El Natroun was completed.</p>
