this day was the martyrdom of the old man St. Metra. He was a native of
Alexandria, a believing Christian. When Decius reigned, he established
the worship of idols, and afflicted the Christian people in every place,
and his edict reached Alexandria whose people began to be persecuted. Some
calumniated against the saint, and the governor had him brought to Alexandria
to question him about his faith. St. Metra confessed that the Lord Christ
is the true God. The governor ordered him to worship the idols and promised
him much money, but he refused and so he threatened to punish him, but
he did not give up his faith. He said to the governor, &quot;I do not worship
but to the Lord Christ, the creator of heaven and earth.&quot; The governor
was wroth with him, and ordered that he be beaten; so he was beaten very
severely and then hanged up by his arms. Then they imprisoned him and slit
his face and his temples with a red hot rod. Finally because he insisted
on not giving up his faith, they cut off his head outside of the city.
