<p <?php echo $text_2; ?>>Departure of St.Freig
</p>

<?php  if(file_exists("icons/Babah21-4.jpg")){ echo "<p $text_3m > <img src=\"./icons/Babah21-4.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On
this day also in the year 1405 A.D. (1121 of martyrs) St. Freig, who is
known as Abba Roweiss, departed. This saint was from a village called Miniet-Yamin
(about 130 kilometers north of Cairo). His father's name was Isaac and
his mother's name was Sarah. When he was born, they called him Freig. He
worked with his father in farming and he had a small camel on which he
carried salt and sold it. He called the camel &quot;Roweiss&quot; (i.e. small head).
The camel used to put his head against his cheek as if he was kissing him.
Because of his humility, he called himself after his camel. Persecutions
befell the Christians, so he came to Cairo and not having a house or shelter,
he went from one place to another. He spent most of his nights in prayers
and wailing. He did not own a coat or any clothes or a cover for his head.
He was naked except for that with which he covered his loins, and his head
was uncovered. He looked like the hermits of the desert; his eyes were
red because of much weeping and he never cut the hair of his head. He was
a man of few words -once an evil man smote him severely but he did not
open his mouth. St. Marcus El-Antoni was present at that time and he rebuked
the evil man. During the later part of his life, he used to say, &quot;O Virgin,
take me because my burden is heavy.&quot; He meant the burden of carrying the
sin of the people for which he often rebuked them though they did not listen
to him. He lived in the days of the holy father Pope Mattheos, 87th Patriarch,
and St. Marcus El-Antoni, in the days of the Sultan El-Zaher Barkuk. He
shut himself up in a small storeroom at the place of his disciple Michael
the builder, in Meniet Syreg. He stayed in that place for 9 years until
his departure on the twenty-first of Babah of the year 1121 of the martyrs.
He was buried in the church of the Virgin, in Deir El-Khandaq. He performed
many wonders such as healing the sick, prophesying and saving many from
their troubles.
</p>

