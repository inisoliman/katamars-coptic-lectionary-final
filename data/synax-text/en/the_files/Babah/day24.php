 Shortly after, he learned
     that his parents had died, so he went back to his city and took whatever
     they had left and gave it to the poor and needy. Then he joined one of
     the monasteries of Syria and followed the path of asceticism with great
     devotion. He fasted for the whole week, eating grass and legumes. God enlightened
     his mind, gave him the gift of prophecy, and of working signs. Later on,
     St. Epiphanius became a monk in the same monastery, and the abbot handed
     him to St.Hilarion. St.Hilarion taught him the ways of the monastic
     life and the doctrines of the church and prophesied that St.Epiphanius
     would become the bishop of Cyprus. The days of this father were eighty
     years: ten years were spent in the house of his father, seven years in
     the city of Alexandria and sixty-three years in worship. He pleased God
     and departed at a good old age. St. John Chrysostom (of the Golden Mouth)
     praised him in some of his articles and St. Basil mentioned him in some
     of his homilies.
