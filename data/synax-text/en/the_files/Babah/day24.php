 On
     this day in the year 472 A.D. the righteous father, Saint Hilarion, the
     Anchorite, departed. He was a native of Gaza, the son of pagan parents.
     They taught him the Greek literature and culture. He excelled and surpassed
     his peers, but he wished still to master it. Since there was no one in
     his city who could help him to fulfill his desire, he went to the city
     of Alexandria and joined its school. There he acquired many kinds of knowledge.
     The divine zeal moved him to learn also the Christian doctrines and books.
     He asked for the books of the church and read them, and Abba Alexandros
     explained to him what was difficult for him to understand. In a short time
     Abba Hilarion believed in the Lord Christ, to Whom is the Glory, and the
     father, the Patriarch, baptized him and he received the Divine Grace. Abba
     Hilarion stayed with Abba Alexandros for a short time, then went to the
     great St. Anthony. When Abba Hilarion saw St. Anthony, he marvelled at
     his profound reverence and his fair appearance that was shining with the
     grace of the Holy Spirit. His heart was deeply moved and he desired to
     join the monastic life. He took off his worldly clothes and put on the
     monastic garb. He started practicing the monastic works with a diligent
     devotion, following the footsteps of his teacher.</p>
