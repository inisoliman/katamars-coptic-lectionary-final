 When the Emperor sought
for him and did not find him, he sent soldiers after him. But God hid St.
Severus from the soldiers and they did not see him although he was close
to them. When he came to Egypt, he went disguised from place to place and
from monastery to monastery, and God made many signs and wonders by his
hands. One day, he went to the desert of Scete, at Wadi-El Natroun, and
he entered the church in the uniform of a stranger monk and a great miracle
happened at that moment. It came to pass that after the priests had placed
the bread (Kourban) on the altar and gone around the church censing, and
after the reading of the epistles and the gospels, he lifted off the Ebrospharin
(covering), and did not fin the Kourban in the paten; so, he was disturbed
and wept. He turned towards the worshippers saying, &quot;O my brethren, i did
not find El Kourban in the paten, and I know not whether this thing has
happened because of my sin or because of your sin.&quot; The people wept; and,
straightaway the angel of the Lord appeared to the priest and told him,
&quot;This has not happened because of your sin or the sin of the worshippers
but because you offered El Kourban in the presence of the Patriarch. The
priest replied, &quot;And where is he, my Lord?&quot; The angel pointed towards him.
St. Severus was standing in a corner of the church and the priest recognized
by the grace of the holy spirit. When the priest came to Abba Severus,
he commanded him to continue the liturgy after they brought him to the
altar with great honor. When the priest had gone up to the altar he found
the offering on the paten as before. They all praised God and glorified
His Holy name. St. Severus went forth from that place and came to the city
of Sakha where he dwelt with a rich man named Dorotheus, who was a lover
of God, and he remained there until his departure.
