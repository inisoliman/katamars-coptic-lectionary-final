 On this day St. Severus
the Patriarch of Antioch came to Egypt in the days of Eustinos the Emperor
who opposed the Orthodox belief, following that of the council of Chalcedon.
Queen Theodora, his wife, was an Orthodox and she loved St. Severus because
of his Christian virtues and his true faith. The Emperor issued his orders
to slay St. Severus. The Queen besought the saint to escape to save himself
but he refused saying, &quot;I am ready to die holding the Orthodox faith&quot; however,
as the Queen and the God-loving brethren insisted, he and some brethren
came to Egypt.</p>
