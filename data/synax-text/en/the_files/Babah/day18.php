 When Abba Theophilus became
Patriarch, he remembered that saying and he talked about it often. In the
city of Rome, the husband of a rich woman died and left her with two sons.
She took them and much money and an icon of the Archangel Raphael and came
to Alexandria. When she heard about the interest of the father the Patriarch
in removing those hills, she went to him with true zeal and gave him enough
money to fulfill his desire. After the work was done, a treasure appeared
under the hills and was covered with a slab of stone engraved in Coptic,
with three characters of theta, 0. When Abba Theophilus saw them, he knew,
guided by the Holy Spirit, the secret of these three letters and said,
&quot;Behold the time has come for this treasure to be uncovered because these
three thetas were gathered together at the same time and they are: Thoes,
that of God; and Theodosius the Emperor, son of Arcadius, son of Theodosius
the Great; and Theophilus
 the Patriarch - meaning himself. He found that this treasure dated
to the Era of Alexander, the son of Philip the Macedonian which was seven
hundred years before. The Patriarch sent to the Emperor to inform him about
the treasure and asked him to come. The Emperor came and saw the treasure,
and gave a large sum of money to Abba Theophilus. He built many churches.
He began by building a church in the name of St. John the Baptist and Elisha
the Prophet, and he transferred their relics that church. That church was
known at that time by the Demas. Then he built a church by the name of
our Lady the Virgin Mary, then a church in the
 name of the Archangel Raphael at El-Gizira and seven other churches.
As for the two sons of the woman who came from Rome, he ordained them bishops.
When the Emperor saw the love of the Abba the Patriarch for building churches,
he gave him all the houses of idols and Abba Theophilus changed them to
churches and lodging houses for strangers, and endowed them with land.
Having fulfilled his days in a life pleasing to God, he departed from this
world in peace.
