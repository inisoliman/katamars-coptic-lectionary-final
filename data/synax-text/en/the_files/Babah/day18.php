 On
this day of the year 404 A.D., the holy father Abba Theophilus, twenty-third
Pope of Alexandria, departed. He was a disciple of St. Athanasius the Apostolic.
He was brought up by him and learned all the spiritual doctrine from him.
When Pope Timothy departed, this father was chosen to take his place.
Abba Theophilus was knowledgeable, well read in the church books with full
understanding of their interpretation. He wrote many discourses and works
of exhortation urging on the works of charity and mercy, and warnings to
the people about receiving the Divine Mysteries without being prepared,
and concerning the Resurrection and the punishment which is prepared for
sinners and many other useful teachings. The holy father Abba Kyrillos
was his nephew and Abba Theophilus took care of his education by sending
him to Abba Serapion in the desert of Scete. There he studied the books
of the church and all its subjects and stayed there five years, then went
back to his uncle. When Abba Theophilus was with Abba Athanasius the Apostolic,
he heard him one day saying while looking at the hills before his cell,
&quot;If I find time, I will clear away these hills and build a church in their
place for St. John the Baptist and Elisha the prophet.&quot;</p>
