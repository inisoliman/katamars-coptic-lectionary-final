 On
this day was the departure of Abba Paula who was from Tamouh. Because he
was inclined since his young age to his solitary life, he went to Ansena
Mountain where he lived with his disciple Ezekiel, who was the witness
of his virtues. Living in his exceeding love to the Lord Christ, to whom
is the glory, he exhausted his body with asceticism, forsaking early things,
fasting and prayer in a way that exceeds human endurance. For this, he
deserved that the Lord appear to him and bless him for his conduct in this
life, for such is the behavior of those who are perfect and who fight against
the flesh, the world and the devil till they overcome them. St. Paula said
to the Lord, &quot;All that is due to Your care, You have created us and redeemed
us by Your death for us the undeserving sinners.&quot; The Lord Christ comforted
him and strengthened him.</p>
