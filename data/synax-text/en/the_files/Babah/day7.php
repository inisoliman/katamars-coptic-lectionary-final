 When our father St.
Bishoy went to Mount Ansena, he was joined by the saint Abba Paula. The
Lord Christ told Abba Paula, &quot;Your body will be buried with that of my
chosen Bishoy.&quot; When Abba Paula departed, his body was placed with the
body of St. Bishoy. When they wanted to move the body of St. Bishoy to
the wilderness of St. Macarius in Scete, they carried it onto a boat, and
left St. Paula's behind; however the boat would not move, until they finally
brought the body of St. Paula and placed it beside St. Bishoy's body. Then
they brought them to the wilderness of Sheheat (Scete).
