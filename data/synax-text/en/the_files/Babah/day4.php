 On this day was the martyrdom
     of St. Bacchus the companion of St. Serguis. When the Emperor Maximianus
     seized these saints, he tortured them with severe tortures after having
     stripped them from their army ranks. After this he sent them to Antiochus,
     King of Syria, who imprisoned St. Serguis, but ordered that St. Bacchus
     be stoned and slain, then cast into the river of Euphrates. God protected
     the body and the water waves brought it to the coast near two anchorites,
     ascetic holy men who were brothers. The angel of the Lord appeared and
     commanded them to go and carry away the body of the Saint. When they came
     to where the body was, they found an eagle and a lion protecting it, having
     spent the whole day and night guarding it without harming it although they
     were flesh eating beasts, for they had been commanded by God to protect
     the body. The two holy men took the body with great honor, singing hymns
     until they came to their cave where they buried it.
