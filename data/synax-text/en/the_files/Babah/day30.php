 On this day also, the great
 saint, the worshipper and fighter St. Ibrahim, the hermit, departed. This
 father was from the city of Menuf, a son of rich, Christian parents. When
 he grew up he longed for the monastic life. He went to Akhmeem and from
 there he came to St. Pachomius, who put the monastic garb on him. St. Ibrahim
 exhausted his body with ascetic practices and worship. He stayed with St.
 Pachomius for 23 years, then he wished for the solitary life in some of
 the caves. St. Pachomius allowed him to do so. He made nets to catch fish.
 One of the laymen used to come, take the work of his hands to sell it,
 buy beans for him, and give the rest of the money as alms on his behalf.
 He led this life for 13th years; his food each evening was a handful of
 salted beans soaked in water. Because the apparel that he went forth with
 from the monastery was worn out, he covered himself with a piece of sackcloth
 (Khaish). He went to the monastery every two or three years to partake
 of the Holy Communion. The devil fought with him much at the beginning
 of his dwelling in that cave. They disturbed him with strange voices and
 terrified him with fearful images. But with the grace of God he used to
 overcome them and drive them away. When his departure drew near, he sent
 the lay brother who used to serve him to the monastery to bring Abba Tadros,
 the disciple of St. Pachomius. When Abba Tadros came to him, he bowed down
 and asked him to remember him in his prayers. Then St. Ibrahim rose up
 and prayed with St. Tadros. He laid down facing the east and gave up his
 soul. When St. Tadros sent the news to the monastery the monks came and
 carried him. Then they all prayed over him, were blessed by him and laid
 him with the bodies of the saints.
