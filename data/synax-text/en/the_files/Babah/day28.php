 On this
day of the year 351 A.D., the great saints Marcianus and Mercurius became
martyrs. They were disciples of St. Paul the Martyr, Patriarch of Constantinople.
When Emperor Constantine II, the son of Constantine the Great, adopted
the belief of Arius, Abba Paul the Patriarch opposed him - so he exiled
him to Armenia, where he was killed by strangulation. These two saints
cried over St. Paul on the day he was exiled. They characterized the Emperor,
 saying that he was a follower of the belief of Arius the Infidel. A
certain Arian man made an accusation against them to the Emperor when he
was on one of the plantations. He had them brought to him and ordered them
slain with the sword. They were killed and buried, and their bodies remained
there until the time of St. John Chrysostom (of the Golden Mouth). When
he heard their history, he sent and brought their honorable bodies to the
city of Constantinople. He built a church for them and transferred their
bodies to it and celebrated a feast for them.
