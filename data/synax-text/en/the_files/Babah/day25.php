 On this
day departed the righteous saints Abba Apollo, who was like the angels,
and Abba Abib, the fighter and worshipper. Abba Apollo was born in the
city of Akhmim. His father's name was Amone and his mother's name was Eyse.
They were righteous before God, walking in His way, and loving to the strangers
and saints. They did not have a son. One night Abba Apollo's mother saw
in a dream a shining man, who had a tree with him. He planted it in her
house and it grew and bore fruit. He told her, &quot;Whosoever shall eat of
this fruit shall live forever.&quot; She ate from it and found it sweet and
she said, &quot;I wonder if I would have a fruit?&quot; When she awoke from her sleep,
she told her husband about what she had seen. He told her that he had seen
the same vision, and they glorified the Lord. They added to their works
of righteousness and to their striving. They fasted for two days on only
bread and salt. After a while she conceived, and she prayed fervently until
the child was born. They called him Apollo and they advanced in their piety.
When the boy had grown up and studied theology, he longed for the monastic
life. This longing grew when he met a friend called Abib. They went together
to one of the monasteries and became monks there. They practiced many ascetic
works. They lived a good life that was pleasing to God. The saint Abba
Abib departed on the 25th of Babah. Thereupon St. Apollo went to Ablug
Mountain and many gathered around him. He taught them the fear of God and
the acceptable worship. On the 25th of Babah they celebrated the commemoration
of the saint Abba Abib to fulfill the saying of the Holy Bible, &quot;The righteous
shall be in everlasting remembrance.&quot; <?php echo "<a $bible_links href=\"$go_bible_search=psalms112:6-6\">"; ?><i>(Psalms 112:6)</i></a> Abba Apollo lived for
