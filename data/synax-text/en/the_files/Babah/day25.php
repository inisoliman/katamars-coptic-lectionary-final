 On
this day also was the consecration of the church of St. Julius El-Akfehas.
This saint was martyred in the city of Tewa. This took place after the
perishing of Diocletian and during the reign of Constantine, a short while
before he was baptized. When Constantine was baptized, the Christian kingdom
spread and the churches were built in the names of the martyrs that were
slain by the infidel Emperors. Emperor Constantine heard the reports of
St. Julius and how the Lord had chosen St. Julius and preserved him along
with his men to care for the bodies of the martyrs. He carried their bodies,
shrouded them, wrote their biographies and how they were finally martyred.
He sent each martyr to his home town. The Emperor praised the strife of
this saint and blessed his work. He sent much money to Egypt, and commanded
that a church be built for him in Alexandria. The church was built and
his body was transferred to it. The church was consecrated by the Patriarch
Abba Alexandros with some bishops. A feast was arranged on this day.
