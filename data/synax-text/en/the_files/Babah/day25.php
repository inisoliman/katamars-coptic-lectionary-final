 He was a contemporary of
St. Macarius the Great who, when heard about St. Apollo, rejoiced. St.
Macarius wrote him a letter to comfort him and the brothers and to confirm
them in their obedience to the Lord. Abba Apollo knew by the spirit that
St. Macarius was writing them a letter. There were many around him speaking
the Word of God. He said to them &quot;Listen my brethren, behold the great
Abba Macarius is writing to us a letter full of comforting and spiritual
teachings.&quot; When the brother arrived with the letter, they received him
with joy then read it and their hearts were consoled. St. Apollo was the
one who went to St.Ammonius and saw the holy woman who stood in the middle
of the fire but did not burn. When the Lord Christ wished to relieve him
from the labor of this world, he departed in peace.
