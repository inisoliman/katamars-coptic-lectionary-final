 On this day was the martyrdom
of St.Anastasia. This fighter was a native of Rome, the daughter of Christian
parents who raised her well and taught her the Christian manners and doctrines
of the church. When she grew up, her parents her parents wanted her to
get married, but she did not agree with them because she had forsaken the
worthless world and its lusts. She instead had chosen to lead a spiritual
life and had longed for the heavenly glories since her young age. She entered
one of the convents of the virgins in Rome and she put on the monastic
garb. She subdued her body with asceticism and absteniousness, and she
did not eat food except once every two days. During the holy fast of the
forty days she ate only on Saturdays and Sundays after the prayer of the
sixth hour of the day. Her food during all the days of the monastic life
was dry bread and salt.</p>
