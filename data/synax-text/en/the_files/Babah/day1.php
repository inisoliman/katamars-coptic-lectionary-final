 It came to pass that
some of the convent virgins nearby the monastery where this saint was staying
were celebrating a feast. The abbess took her with some of the virgins,
and went to join the celebration of that feast. As they were going, St.
Anastasia saw the soldiers of Emperor Decius the infidel torturing some
Christians and dragging them. Her heart became inflamed with divine love
and she shouted At them saying, &quot;O you hard-hearted men, is that what you
do to those whom God created in His own form and image and for whom he
gave Himself?&quot; One of the soldiers seized her and brought her to the governor
who asked her saying, &quot;Is it true that you are a Christian, worshipping
Him who was crucified?&quot; And she confessed the truth and did not deny it.
He inflicted her with severe tortures, then he crucified her and had a
fire lighted under her, but it did not harm her. When she did not give
up her faith because of these pains, he commanded that her head and the
swordman cut off her neck and received the crown of martyrdom.
