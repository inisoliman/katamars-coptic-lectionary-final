 Constantine held the
same belief as Arius. He was exceedingly sorry for what Abba Paul had done
to the Arians, and asked him to stop excommunicating them, but the Patriarch
did not obey him. He became angry and exiled him from Constantinople as
he had exiled also Abba Athanasius the apostolic from Alexandria. The two
foregathered in Rome, and went to stand before Emperor Constance to inform
him of their concern. He wrote a letter for them to his brother ordering
him to accept them and threatened him if he did not receive them-there
would be no peace but war between them. When the two saints came to Constantinople,
they gave the letter to Emperor Constantine, who accepted his brother's
letter and returned them to the chairs.</p>
