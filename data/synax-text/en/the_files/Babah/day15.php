 On this day of the
year 405 A.D., St.Bandlaemon, who was from the city of Nicomedia, was martyred.
His father worshipped idols but his mother was a Christian. They educated
him well and taught him the profession of medicine. He met a priest whose
name was Armolas who taught him the facts of the faith of the Lord Christ
and baptized him. He reached a high standard of virtuous life. God wrought
great wonders through him. Once, a blind man came to him to be treated
by his medicine. He made the sign of the Cross over his eyes in the Name
of the Father and the Son and the Holy Spirit and his eyes were healed
and he regained his vision completely. When the Emperor heard the news
of his healing this blind man, he had the blind man brought to him and
asked him about how his eyes were healed. He told him St.Bandlaemon healed
them by laying his hand on them and by saying, &quot;In the Name of the Father
and the Son and the Holy Spirit.&quot; He confessed before the Emperor that
he was a Christian, so the Emperor immediately had his neck cut off. The
Emperor ordered that St.Bandlaemon be brought to him and asked him about
his belief. He confessed that he was a Christian. He tried to persuade
him by all means and promised him many things, but he would not change
his confession. Then he shouted out to him and threatened to inflict upon
him different kinds of tortures. But he did not move. The Emperor inflicted
upon him severe tortures on different days, sometimes beating and suspending
him and often times casting him into the sea or into the fire. The Lord
Christ appeared to him in the form of Armolas, the priest who baptized
him and taught him the facts of faith, to strengthen him, and walked with
him as if He was sharing with him every punishment which befell him. Later
on, the Emperor ordered to behead him. When St.Bandlaemon went to the place
of execution, he prayed to the Lord Christ and supplicated Him. He heard
a voice from heaven announcing to him what had been prepared for him from
heavenly joy. The soldiers also heard that voice and immediately believed.
They went forth to the Emperor and confessed their faith in the Lord Christ.
The Emperor ordered his men to cut off their necks, too, and they all received
the crown of martyrdom.
