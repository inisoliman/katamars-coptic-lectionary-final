 One day, a monk came
into the cell of Abba John. He found him lying down with angels waving
their wings over him. Later on, the Berbers attacked the desert of Scete
and he left it. When he was asked why he left, he replied that he did not
leave because he was afraid of death, but because he feared a Berber would
slay him and go to hell, for though he is against his worship, he is his
brother in form. Then he went to the mountain of Abba Anthony on the Red
Sea. There he dwelt by the side of a village and God sent him a believer
who served him. When the Lord wished to grant him rest and to end his strife
in this world, He sent him His two righteous saints Abba Macarius and Abba
Anthony to comfort him and to inform him about his departure. On the eve
of Sunday, he fell sick and sent his attendant to bring him something from
the village. The angels and the host of saints came and received his pure
soul and took it up to heaven. At that time, his servant came back and
saw the soul of the saint surrounded by the host of saints and angels singing
before them. Before them all, there was one shining like the sun and singing.
The servant marveled at this magnificent sight. An angel came to him and
told him the name of each one of the saints. Then the servant asked the
angel, &quot;Who is this one in front of them all, who is shining like the sun?&quot;
The angel replied, &quot;This is Abba Anthony, the father of all the monks.&quot;
When the servant went into the cell, he found the body of the saint kneeling
to the ground, as he had given up his soul while kneeling. The attendant
wept sorrowfully over him and went in a hurry to the people of the village
and told them what had happened. They came and carried his holy body with
great honor. When they brought him into the village, great wonders and
miracles were performed through his body.
