 On this
day was the departure of the great light and saint, the heguman Abba John
(Yoannis) the Short. He was a native of Betsa in upper Egypt and he had
one brother. His parents were righteous and God-fearing people, rich in
faith and good deeds. When he was 8 years old, his heart turned away from
the futility of this world, its lusts and its glory, and he desired the
monastic life. The grace of God moved him to go to the desert of Scete
and there he came upon a tried and holy man whose name was Abba Pemwah
from El-Bahnasa. John asked Abba Pemwah to allow him to stay with him.
The old man answered, trying him, &quot;My son, you cannot stay with us for
this is a very hard desert and those who dwell in it eat from the work
of their hands, besides observing many fasts, prayers, and sleeping on
the floor and many other forms of asceticism. Go back to the world and
live in the fear of God.&quot; Abba John told him, &quot;Do not send me away, for
God's sake, because I came to be in your obedience and prayers. If you
accept me, I believe that God will make your heart well-pleased with me.&quot;
Abba Pemwah was in the habit of not doing anything hastily. He asked the
Lord Christ to reveal to him the matter of this young man. The angel of
the Lord appeared to him and said, &quot;Accept him, for he shall become a chosen
vessel.&quot; Abba Pemwah brought him and he shaved the hair of his head. He
laid out the garb of the monk, and he prayed over it for three days and
three nights and when he put the garb on him, he saw an angel making the
sign of the Cross over it. Saint John started his monastic life with great
asceticism and splendid works. One day Abba Pemwah wanted to test him,
so he expelled him from his cell saying, &quot;I cannot live with you.&quot; Abba
John stayed out by the door of his cell for seven days. Every day Abba
Pemwah went out and smote him with a palm branch and Abba John bowed down
before him saying, &quot;I have sinned.&quot; On the seventh day, the old man went
out to go to the church and he saw seven angels with seven crowns placing
them on the head of Abba John. Since that day, he was held by him in honor
and reverence.</p>
