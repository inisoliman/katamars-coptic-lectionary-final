 One day Abba Pemwah found
a piece of dry wood and gave it to Abba John and said to him, &quot;Take this
wood, plant and water it.&quot; St. John obeyed and went on watering it twice
a day even though the water was about 12 miles from where they lived. After
three years, that piece of wood sprouted and grew into a fruitful tree.
Abba Pemwah took some of that fruit and went around to all the elder monks
saying, &quot;Take, eat from the fruit of obedience.&quot; This tree still exists
in its place in his monastery. Abba Pemwah fell sick for 12 years and Abba
John ministered unto him all this time during which he never heard from
his teacher that he fell short in his service. Abba Pemwah was an experienced
old man who had been tried much, and sickness had emaciated him until he
became like a piece of dry wood, so that he would be a chosen offering.
When Abba Pemwah was about to die, he gathered together the elder monks
and he held the hand of Abba John and gave him to them saying, &quot;Take him
and keep him, for he is an angel, not a man.&quot; He commanded Abba John to
stay in the place where he had planted the tree. After that Abba John's
older brother came to the monastery and was ordained a monk with him. He
also became an honorable monk. It happened when the father the Patriarch
Abba Theophilus was ordaining Abba John hegumen and abbot over his church,
and as he placed his hand over his head, a voice from heaven was heard
by the people present saying, &quot;Axios, Axios, Axios (That is to say he is
worthy).&quot; When this saint consecrated the offering, he was able to know
those who were worthy to partake of it and those who were not worthy. Abba
Theophilus the Patriarch built a church for the Three Young Men in Alexandria,
and he wished to bring their bodies and place them in it. He brought Abba
John and asked him to travel to Babylon, and to bring the holy bodies.
After much forebearing, Abba John accepted to go on this mission. When
he left the Patriarch, a cloud carried him away to Babylon. He entered
the city and saw its monuments, rivers, and palaces and found the bodies
of the saints. When he started moving them from their place, a voice came
out from the holy bodies and said to him, &quot;This is the Will of God that
we do not leave this place until the day of the Resurrection. Nevertheless,
because of the love of Abba Theophilus the Patriarch, and your labor, too,
you should inform the Patriarch to gather the people in the church and
to put oil in the lamps without lighting them and we will appear in the
church and a sign will be made manifest to you.&quot; Then Abba John left and
went back to Alexandria and told the Patriarch what the saints had said.
It happened when the Patriarch and the people were in the church, the lamps
were lit up suddenly and they all glorified the Lord.</p>
