 When they threw away his
     holy body, some Christians took it and laid it in a coffin made out of
     marbles. The body remained hidden until the end of the days of persecution,
     when the one who had hidden it revealed it. A great church was built for
     him in Thessalonica, and they laid his body therein. Many great signs were
     made by his name. Each day, sweet oil was distilled from his body which
     cured those who used it with faith, especially on the day of his feast.
     On his feast day, the oil flowed in a larger quantity than on any other
     day, and it dripped from the walls of the church and the pillars. Though
     the gathering was huge, they all received their share, from what they took
     off the walls and put in their containers. Those of the righteous priests
     who had seen this told and testified to that.
