his talents and gained. Many were the signs and wonders God did through
his hands. In the city of Edkow, every time he went up on the pulpit to
preach to the people, he wept. When one of his disciples asked him the
reason for his weeping, he answered that he saw the sins of the people
and their ungodly works. On another occasion he saw our Lord Christ at
the altar, and the angels bringing unto Him the works of the people, one
after the other. Anba Macarius heard a voice saying, &quot;Why, bishop, are
you slack in preaching to your people?&quot; He replied, &quot;My Lord, they do not
accept my words.&quot; So the Lord said to him, &quot;It is meet for the bishop to
preach to the people and if they do not accept his words, their blood be
upon their own heads.&quot; He was invited to go to the council of Chalcedon
with Abba Dioscorus. On arriving at the royal palace, the guards prevented
him from entering because of his modest clothes, until Abba Dioscorus told
them that he was the bishop of Edkow. When he had gone in and heard what
the infidels were saying about the Lord Christ, he excommunicated the Emperor
in the council. He was ready to deliver himself to death for the sake of
keeping the Orthodox faith. They exiled him with Abba Dioscorus to the
island of Gagra. From there Abba Dioscorus sent him with a believing merchant
to Alexandria saying to him, &quot;There you have a crown of martyrdom awaiting
you.&quot;</p>
