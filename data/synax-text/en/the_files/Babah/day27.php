 Shortly after, he arrived
in the city of Alexandria, the messenger of the Emperor arrived with the
new Chalcedonian creed which stated the two natures of Christ. The Emperor
had commanded him saying that, &quot;He who writes his name first on this creed
will be the Patriarch of the city.&quot; In the city, the head of the priests
was Brotarios. He took the paper to write his name first but St.Macarius
the Bishop reminded him of what Abba Dioscorus had told him before he went
to the council saying, &quot;You shall possess my church after me.&quot; Brotarios
remembered that and refrained from writing. When the Emperor's messenger
knew that the Bishop disagreed with the creed of the Emperor and did not
write his name also, he jumped over the Bishop and kicked him. St. Macarius
died on the spot and thus received the crown of martyrdom. The believers
took his holy body and buried it with the bodies of St. John the Baptist
and Elisha the Prophet. That fulfilled what these two saints had told this
father, the Bishop, in a vision, that his body would be with their bodies.
He departed to the Lord Christ winning the crown of glory.
