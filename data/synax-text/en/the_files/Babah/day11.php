 On
this day also departed St.Pelagia. This righteous woman was born in the
city of Antioch from pagan parents, and she had both a corrupt faith and
a corrupt manner of life. She met a holy bishop whose name was Paul who
preached to her. She believed in the Lord Christ through him, and confessed
to him everything which she had done. He encouraged her and taught her
not to despair but to repent with a true determination. Then he baptized
her in the Name of the Father and the Son and the Holy Spirit and she was
illuminated by the grace of baptism. She led a penitent life with a firm
heart and a pure determination, and she consumed her body with strenous
worship. Then she dressed herself in the garb of men and went to Jerusalem
and worshipped in its sanctuaries. She met Abba Alexandros the patriarch
of Jerusalem who sent her to one of the convents outside Jerusalem. She
dwelt there for forty years and departed in peace.
