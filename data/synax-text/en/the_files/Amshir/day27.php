 They condemned St. Eustathius and judged to strip
him from his episcopal rank. They informed Emperor Constantine saying:
&quot;A council of clerics judged to remove Fr. Eustathius, Patriarch of Antioch,
from his office&quot;. The Emperor believed their unfounded judgement, and he
deposed and banished St. Eustathius to Thrace where the saint remained
until his departure. The Lord God, Who loves His holy servants, did not
neglect to reveal the truth. The woman became ill with a debilitating long
illness and suffered great pain. She realized that her suffering was a
punishment for her false accusation against the Saint. She came and confessed
before the people of the city that the charge she had brought against St.
Eustathius the patriarch was untrue. She pointed at those who bribed her
with money to lie. She indicated that the Patriarch was innocent and that
the child was born to another man whose name was the same as the Patriarch.
They convinced her to swear against the Saint but at the same time to mean
in heart her friend who was the father of the child, to be saved from falsely
swearing. The priests resumed mentioning the name of St. Eustathius in
the divine liturgy after his innocence was evident. He was eulogized and
praised by St. John Chrysostom (of the Golden Mouth) on the day of his
commemoration.
