  On this day of the year 330 A.D., St. Eustathius, Patriarch
of Antioch, departed in exile. He was enthroned Patriarch of Antioch during
the reign of the righteous Emperor Constantine the Great. He was righteous
and well learned. He attended the Nicene Council, and the fathers gathered
there agreed on excommunicating Arius and exiling him and all those who
believed in his teachings. Those were Eusabius the Nicomedian; Thaoghonius,
Bishop of Nicea; and Eusabius, Bishop of Caesarea. After the council was
concluded and the fathers went back to their parishes, those who were excommunicated
pretended that they wished to go to Jerusalem, but instead they went to
Antioch. There, they enticed a harlot with money and other things in order
to accuse St. Eustathius the Patriarch that he fathered a child from her.
She took the money and went to the church and said as they had instructed
her. They pretended to disbelieve her and said, &quot;Bring forth your proof
if you are truthful in what you are saying. We will not accept your statement
unless you swear on the Bible that what you claim against this father is
true.&quot; She swore to them and they replied, &quot;We do not need any more proof.&quot;</p>
