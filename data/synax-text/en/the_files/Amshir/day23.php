 On this day, St. Eusebius, the
son of Basilides, the minister, was martyred. This Saint was one of the
soldiers who fought in the war against Persia. When Diocletian abandoned
the faith, Basilides, informed his son, Eusebius, of what Diocletian had
done. Then St. Eusebius in turn told his companions, the holy men: Abadir,
Yustos, Ecladius, and Theodore about this matter. They all agreed to shed
their blood in the Name of the Lord Christ. When the war was over, they
returned to Antioch carrying the flag of victory. The Emperor went out
to meet them, and asked them to worship his idols with him, but they all
refused. Eusebius pulled his sword out, and tried to kill Diocletian and
all who were with him, but Diocletian fled and disappeared. If not for
the presence of Basilides, Eusebius and the saints with him could have
killed all the leaders of the government. Romanus, one of the ministers
of the Emperor, advised him to exile Eusebius to Egypt to be killed there.
He sent him to the governor of Qift (Coptos), Maurianus, who inflicted
upon him many tortures from the Hinbazeen (the squeezing wheel), dismemberment,
and by severe beatings. The Lord sent to him His angel to strengthen him
in his afflictions, to comfort him and to heal his wounds. The Lord showed
him in a vision the paradise and the mansions of the saints, and the places
that had been prepared for him, his father and his brother, and his soul
exceedingly rejoiced. The Governor ordered him to be burned in a fiery
furnace outside the City of Ahnas. The angel of the Lord came and put out
the fire and took St. Eusebius out safely. Finally the Governor ordered
him beheaded and thus he received the crown of martyrdom.
