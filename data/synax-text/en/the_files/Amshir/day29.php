a dispute with Arikestus, Bishop of Rome, in regard to the Easter feast.
He shepherded his flock well and remained on his chair for a long time
until a good old age. He wrote many articles and discourses about the Holy
Advent, death, hell, torments of hell, the virgin St. Mary and many others.
He attracted many souls to the Lord with his life-giving teaching.
