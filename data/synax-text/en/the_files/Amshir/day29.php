 On this day of the year 167 A.D., St. Polycarp,
Bishop of Smyrna, was martyred. His life began at the end of the first
Christian century, and he became the disciple of St. John the Evangelist.
He was the one about whom the Lord said, &quot;And to the angel of the church
in Smyrna write, 'These things says the First and the Last, Who was dead,
and came to life: I know your works, tribulations and poverty, but you
are rich; and I know the blasphemy of those who say they are Jews and are
not, but are a synagogue of Satan. Do not fear any of those things which
you are about to suffer. Indeed, the devil is about to throw some of you
into prison, that you may be tested, and you will have tribulation ten
days. Be faithful until death, and I will give you the crown of life.'&quot;
