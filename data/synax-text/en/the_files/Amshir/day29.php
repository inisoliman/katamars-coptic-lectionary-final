 When Emperor Marcus Aurelius incited persecutions
against Christians, they strongly pressured him saying, &quot;Swear and we will
set you free; curse Christ and we will spare your life.&quot; Polycarp replied,
&quot;I have served my Lord Christ for 86 years and He never harmed me so how
can I blaspheme against my King Who saved me?&quot; The Governor said, &quot;If you
do not fear the wild beasts, I will make the fire consume you if you do
not repent.&quot; St. Polycarp said, &quot;You threatened me with fire that burns
for a while, then burns out, for you do not know the everlasting fire of
judgement and the eternal punishment that are awaiting the evil ones. Now
why are you lingering? Do whatever you want.&quot; After severe tortures and
many threats, the saint wished to shed his blood for Christ's name. He
commanded and taught his people to be steadfast in faith and told them
that they would not see his face after that day. They wept and tried to
hold him down to prevent him from leaving but they failed to stop him.
He went and confessed the Lord Christ before the Governor who ordered to
cut off his head after much torture; thus he received the crown of life.
Some of the believers took his body, shrouded and buried it with great
honor.
