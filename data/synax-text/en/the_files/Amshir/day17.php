 On this day St. Mina the monk was martyred.
This saint was born in Akhmim to Christian parents who were farmers. Since
his youth, his heart was inclined to renounce the world, so he became a
monk in one of the monasteries of Akhmim. For a period of time, he fasted
two days at a time and he was ascetic in his food and drink. Then he went
to El-Ashmounein and dwelt in a monastery there for 16 years without leaving
it. When the Arabs ruled the country, St. Mina heard that they denied that
God had a Son from His nature and essence, and equal with Him in Eternity.
This denial of faith was painful to the saint, so he took permission from
the abbot of the monastery and went to El-Ashmounein. He came before the
commander of the Arab camp and asked him, &quot;Is it true that you say that
God has no Son from His nature and essence?&quot; The commander replied saying,
&quot;We deny that saying about God and totally reject it.&quot; The saint told the
Arab commander that it should only be rejected if His Son was born through
parental procreation, but our belief is that the Lord Christ is God of
God, and Light of Light. The commander replied, &quot;In our faith, this is
blasphemy.&quot; The saint told him that the Bible says, &quot;He who believes in
the Son has everlasting life; and he who does not believe in the Son shall
not see life, but the wrath of God abides in him.&quot; <?php echo "<a $bible_links href=\"$go_bible_search=john3:36-36\">"; ?><i>(John 3:36)</i></a> The commander
became enraged at this and ordered his soldiers to cut the saint into pieces
and to throw him into the sea. The believers gathered the pieces of his
body, shrouded and buried it. They arranged a commemoration of St. Mina
the monk on this day.
