 On this day we commemorate the relocation of the
relics of St. Martianus (Martinianus) the fighter monk from Athens to Antioch.
After he led an adulterous woman to repentance and then to monasticism,
he placed her in one of the convents. Then he went to an island and visited
many countries. Finally, he came to the city of Athens where he stayed
for a short while, until he fell sick and departed in peace. St. Demetrius,
Patriarch of Antioch, took on the endeavor to relocate the relics of the
saint during the reign of Emperor Valens the Infidel. St. Demetrius sent
priests to Athens. They carried the body of St. Martianus with great honor
to Antioch. He placed the body in a sarcophagus and appointed a feast to
celebrate him on this day.
