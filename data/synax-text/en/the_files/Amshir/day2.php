 On their way back, Paul
left his brother and went on his way until he came out of the city. Paul
found a grave where he stayed for three days praying to the Lord Christ
to guide him to what pleases Him. As for his brother, he searched for Paul
diligently and when he did not find him, he was very sorry for what he
had done. God sent St. Paul an angel who took him out of this place, and
walked with him until they reached the eastern inner wilderness. He stayed
there for 70 years, during which he saw no one. He put on a tunic made
of palm tree fiber. The Lord sent him a raven every day with a half loaf
of bread. When the Lord wanted to reveal the holiness of St. Paul and his
righteousness, He sent His angel to St. Antony (Antonius) the Great, who
thought that he was the first to dwell in the wilderness. The angel told
St. Antony, &quot;There is a man who lives in the inner wilderness; the world
is not worthy of his footsteps. By his prayers, the Lord brings rain and
dew to fall on the earth, and bring the flood of the Nile in its due season.&quot;
When St. Antony heard this, he rose right away and went to the inner wilderness,
a distance of one day's walk. God guided him to the cave of St. Paul. He
entered, and they bowed to each other, and sat down talking about the greatness
of the Lord.</p>
