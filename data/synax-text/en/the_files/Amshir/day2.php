 In the evening, the raven
came bringing a whole loaf of bread. St. Paul said to St. Antony, &quot;Now,
I know that you are one of the children of God. For 70 years, the Lord
has been sending to me everyday, half a loaf of bread, but today, the Lord
is sending your food also. Now, go and bring me back in a hurry the tunic
that Emperor Constantine had given to Pope Athanasius.&quot; St. Antony went
to St. Athanasius, and brought the tunic from him and returned to St. Paul.
On his way back, he saw the soul of St. Paul carried by the angels up to
heaven. When he arrived to the cave, he found that St. Paul had departed
from this world. He kissed him, weeping, and clothed him in the tunic that
he asked for, and he took his fiber tunic. When St. Antony wanted to bury
St. Paul, he wondered how could he dig the grave? Two lions entered the
cave, bowed their heads before the body of St. Paul, and shook their heads
as if they were asking St. Anthony what to do. St. Antony knew that they
were sent from God. He marked the length and width of the body on the ground,
and they dug the grave with their claws, according to St. Antony's directions.
St. Anthony then buried the holy body, and went back to Pope Athanasius
and told him what had happened. St. Athanasius sent men to bring St. Paul's
body to him. They spent several days searching in the mountains, but they
could not find the place of his grave. St. Paul appeared to the Pope in
a vision and told him that the Lord would not allow the revelation of the
location of his body. He asked the Pope not to trouble the men, but to
have them brought back. Pope Athanasius used to put the palm fiber tunic
on three times a year during the Divine Liturgy. One time, he wanted to
let the people know about the holiness of the owner of that tunic. He put
it over a dead man, and the dead man rose up instantly. The news of this
miracle spread all around the land of Egypt.
