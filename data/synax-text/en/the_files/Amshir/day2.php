 On this day of the year
341 A.D., the great saint Anba Paul, the first hermit, departed. This Saint
was from the city of Alexandria, and had a brother whose name was Peter.
After the departure of their father, they divided the inheritance between
them. When his brother took the greater share, Paul's feelings were hurt,
by his brother's action. He said to his brother, &quot;Why don't you give me
my rightful share of the inheritance of my father?&quot; Peter responded, &quot;You
are a young man, and I am afraid that you might squander it. As for me,
I will keep it for you.&quot; When they did not agree with each other, they
went to the governor to judge between them. On their way, they saw a funeral
procession. Paul asked one of the mourners about the deceased man. Paul
was told that he was one of the noble and rich people of the city, and
that he left his riches and his wealth behind, and that they were taking
him to bury him with only his garment. St. Paul sighed in his heart and
said to himself, &quot;What do I have to do then with all the money of this
temporal world which I shall leave naked?&quot; He looked to his brother and
said to him, &quot;My brother, let us return, for I shall not ask you for anything,
not even for what is mine.&quot;</p>
