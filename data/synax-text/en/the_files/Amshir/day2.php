 On this day also, the pure
saint Anba Longinus, the abbot of the El-Zugag monastery, departed. He
was from Cilicia (in Asia Minor). He became a monk in one of the monasteries,
where his father Lucianus became a monk after his wife had died. When the
abbot of this monastery departed, the monks wanted to appoint St.Lucianus
an abbot over them, but he refused, for he shunned the vain glory of the
world. He took his son Longinus and went to Syria, where they lived in
a church. God revealed their virtues by performing many miracles through
them. For fear of the vain glory of this world, Longinus went to Egypt
with his father's permission. When he arrived, he went to the monastery
of El-Zugag, west of Alexandria. The monks received him with joy. After
the departure of the abbot, the monks appointed Anba Longinus abbot over
them, for what they saw of his virtues and his good conduct. Shortly after,
his father Lucianus came to him, and they worked together in making the
canvas sails of boats, and sold them to support themselves. God performed
many miracles and signs on their hands. Father Lucianus departed from this
world in peace, and shortly after, his son, Anba Longinus, departed also.
