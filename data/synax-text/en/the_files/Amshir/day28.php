 On this day St. Theodore (Theodoros), the Roman,
was martyred. He was from the City of Astir (Peshotep) during the reign
of the Emperors Maximianus and Diocletian. When they were informed that
the saint did not adore their idols, they brought him and asked him to
worship the idols but he refused. They promised him precious gifts but
he did not hearken to them. They tortured him by pressing his body in the
Hinbazeen, and hacking parts of his body. He was burned with fire and beat
him with whips. He endured all that because of his love for the Lord Christ
Who sent His angels to comfort and strengthen him. Finally he was beheaded
and received the crown of martyrdom.
