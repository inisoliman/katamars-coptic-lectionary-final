  On this day the church commemorates the departure of St.
Maruta (Maruthas), bishop of Marjferqat (Mia Farcane), and the relocation
of the relics of the saints who were martyred there in the days of Emperor
Diocletian. St. Maruthas was a knowledgeable and righteous man. For this
reason, Emperor Theodosius, father of Arcadius and Honorius, selected him
to serve as a good will ambassador to the king of Persia, Sapor II, to
negotiate with him the conditions of the truce that both wanted to sign.
King Shapur (Sapor) welcomed him and housed him in a royal palace. When
St. Maruthas knew that the king had a demented daughter, he asked to bring
her to him. He prayed over her and she was healed. King Shapur was overjoyed
and became more courteous to St. Maruthas. The saint asked the King for
the relics of the saints who were martyred in Persia, and the King gave
him permission to take them. The saint took the relics for which he built
a church and a great fortress around it. Later on, a city was built inside
the walls of the fortress, which was named after Maruthas. After the saint
had finished his mission, he returned to Emperor Theodosius, and stayed
in Rome until his departure.
