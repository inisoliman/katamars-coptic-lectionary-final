 <p <?php echo $text_2; ?>>Departure of St.Timothy the Third, the
Thirty-Second Pope of Alexandria</p>
<?php  if(file_exists("icons/Amshir13-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Amshir13-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also of the
year 528 A.D., the holy father Abba Timothy III, 32nd Pope of Alexandria,
departed. His enthronement on the apostolic throne was in 511 A.D. He suffered
many hardships because he was steadfast in the Orthodox faith. In his days,
St. Severus, Patriarch of Antioch, came to Egypt escaping persecution.
The two saints traveled together to Egyptian cities and monasteries confirming
the people in the Orthodox faith. Because he did not agree with Emperor
Marcion with regard to the canons of the Council of Chalcedon, he was exiled.
On the day of his exile, the faithful opposed the enforcement of the order
of his exile, and many of them were killed, about two hundred thousand,
by the order of the Emperor. The saint departed in exile together with
St. Severus of Antioch, after he had been on the apostolic throne for 17
years.
