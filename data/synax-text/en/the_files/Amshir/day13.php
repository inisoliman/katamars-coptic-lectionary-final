 On this day, St. Sergius, his father,
his mother, his sister and many others with them, were martyred. This saint
was born in the city of Atripe to a righteous father whose name was Theodore,
and a faithful mother whose name was Mary. When he was 20 years old, St.
Sergius desired to die for the Name of the Lord Christ. He presented himself
to Cyprianus (Cyprian), the governor, and confessed his faith in the Lord
Christ. The governor commanded him to be tortured with different kinds
of tortures and to cast him in prison. At night he saw in a vision as if
he was in heaven, and he saw the mansions of the saints. His soul was greatly
comforted, and the Lord Christ healed him from his afflictions. A priest
by the name of Mansoon heard about the labors of St. Sergius. Fr. Mansoon
came with two deacons to Atripe and confessed the Name of the Lord Christ
before the governor. The governor beat them with great cruelty. A multitude
of people watched the tortures, and moved with compassion toward the priest,
who could not do anything but to look at them, preach and command them
to be steadfast in their faith in the Lord Christ. He prayed and blessed
them and they all confessed the Orthodox faith. After they had been tortured,
they were all beheaded, and received the crown of life. However, the Governor
tortured the priest with fire, but the Lord saved him. The Governor sent
him to Alexandria where he received his crown of martyrdom.</p>
