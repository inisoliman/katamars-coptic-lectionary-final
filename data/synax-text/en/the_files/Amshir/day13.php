 As for St. Sergius, Governor Cyprianus
brought him and tortured him with excruciating tortures but the Lord healed,
strengthened and comforted him. They brought an idol and ordered him to
worship it. He kicked the idol with his foot and it fell and broke. Cyprianus
believed instantly and said, &quot;The god that cannot save itself, cannot save
others.&quot; The captain of the soldiers &quot;Ohios&quot; continued to torture St. Sergius,
and ordered to skin him and to rub his wounds with salt and vinegar, but
the Lord gave him strength and grace. His mother and his sister came to
visit him and saw him in this condition, they wept bitterly, until his
sister died from her extreme grief, but God raised her up by the prayers
of the saint. St. Julius of Agfahs came, wrote the biography of St. Sergius,
and promised him that he would take care of his body and his burial. The
captain &quot;Ohios&quot; ordered that St. Sergius be tortured by pressing his body
through the pressing wheel (Hinbazeen), that his nails be pulled out, that
he be placed over an iron bed, with a fire under it, and that torches of
fire be placed in his ears. The Lord strengthened him through all of this
and healed him. When &quot;Ohios&quot; the captain was tired of torturing him, he
decided to behead him.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 St. Sergius called his mother and sister
to bid them farewell. They came with the rest of his family and when they
saw him tied up with the bridle of a horse that was dragging him to the
place of his martyrdom, they protested to the Governor for his extreme
cruelty. He ordered to behead them all and they all received the crown
of life and the eternal bliss. There was a young boy among the crowd whose
eyes were opened by the Lord and he saw the souls of the saints who were
martyred carried by the angels, ascending to heaven. He cried with a loud
voice saying, &quot;O My Lord Jesus Christ, have mercy upon me.&quot; His parents
were afraid that the governor would hear him and destroy them because of
him. When they could not calm him down, they put their hands upon his mouth
to prevent him from screaming, asking the help of the Lord Christ, until
he gave up his pure soul at the hand of the Lord.
