<?php  if(file_exists("icons/Misra12-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Misra12-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, is the commemoration
of the enthronement of the Righteous Emperor Constantine the Great, over
the city of Rome. When he reigned over Byzantium, succeeding his father
Constantius Chlorus in the year 306 A.D., he abolished the injustice throughout
the kingdom. His fairness and fame spread throughout the Empire. The nobles
of Rome asked him to come and save them from the injustice of Maximianus.
He sorrowed for their misfortune, and he pondered in what way he could
deliver them. The sign of the cross appeared to him, to which he adhered.
Constantine went and fought against Maximianus and defeated him. While
Maximianus was retreating, crossing the bridge over the Tiber River, the
bridge broke and he perished, drowning along with his soldiers. That was
in the seventh year of the reign of Emperor Constantine. When Emperor Constantine
entered Rome, all its nobles and people welcomed him in a grand festival,
and with great joy. They celebrated his victory for seven successive days.
The poets of Rome and its orators praised the Honorable Cross, describing
it as the savior of their city and the supporter of their Emperor. The
account of the appearance of the Cross to Emperor Constantine and his victory
over Maximianus is written under the commemoration of the departure of
this righteous Emperor, which is on the twenty-eighth day of the month
of Baramhat.
