 On this day, St. Ari (Ori), the
priest of Shatanouf, was martyred. He was exceedingly merciful, pure in
soul and body, to the extent that he was worthy to foretell future things
by the Divine Inspiration. When the governor of Nakios, heard about him,
he had the Saint brought before him and ordered the Saint to offer incense
to the idols. When St. Ari refused, the governor tortured him much, then
sent him to Alexandria, where he was also severely tormented with excruciating
tortures. Then they cast him in prison, where God wrought many miracles
on his hands. His news spread and many came to him from everywhere. When
the governor heard this, he ordered him beheaded. Thus he received the
crown of martyrdom.
