 On this day, the nine saints:
Lazarus the Elder, his wife Salomi, and their children; Abeem (Animo),
Antonius, Hosea, Lazarus, Aniana, Semuna, and Marcolus, were martyred.
Lazarus was one of the teachers of the Jewish Law. His father was one of
the Seventy Elders who translated the Torah by the order of Ptolemy, King
of Egypt. This just man taught his children the Law of Moses. When Antiochus,
King of Rome, reigned over the Syrian land, he besieged Jerusalem and afflicted
the Jewish nation with cruelty. He compelled them to break the Law of their
fathers and to eat what was forbidden them such as pork meat and the like.
Many of them feared his might and obeyed him. Nevertheless, these righteous
persisted on keeping the Law, which had been given to them by God. Antiochus
tortured them severely, by flogging them, crucifying, burning, and plowing
their bodies with metal combs. The righteous woman Salomi, encouraged them
until they had fulfilled their martyrdom. Then, she also cast herself in
the fire without waiting for them to throw her into it. Thus, they received
the crown of martyrdom.
