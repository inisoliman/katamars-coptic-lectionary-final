 On this day, St. Julietta was martyred.
She was born in the city of Caesaria, in Cappadocia, to rich Christian
parents. She inherited great wealth from them. An oppressor defrauded her
from her wealth by bribing false witnesses against her. When that evil
man knew that she wished to inform against him, and expose his lies and
extortion, he informed the governor of Cappadocia that she was Christian.
She said within herself that the temporal wealth of this world is nothing
to make her lose herself for, but if she gain the eternal life to come,
no one would be able to take it from her. When she came before the governor,
she confessed the name of Christ. The governor cast her in fire, and she
delivered up her pure spirit in the hands of the Lord. She received instead
of her temporal possessions, the eternal life and St. Basil the Great praised
her immensely.
