 On this day also, of the
year 193 A.M. (July 31, 477 A.D.) St. Timothy II, the twenty-sixth Pope
of the See of St. Mark, departed. This father was chosen for the Patriarchate
after the departure of the striving father Pope Dioscorus on the third
of Babah, 172 A.M. (October 1, 455 A.D.). He suffered many hardships for
the sake of preserving the Orthodox faith. Emperor Leo, the Great, banished
him to the island of Gagra (Gangra), in Paphlognia (Pavlagonia), where
he was detained for seven years until he was returned by Emperor Leo, the
Less, with great honor. He spent the rest of his days in establishing the
faithful in the Orthodox faith. He departed in peace after he spent twenty-one
years and ten months on the throne of St. Mark.
