 On this day, God sent His honorable
angel Gabriel to announce to St. Joachim of the birth of the Virgin, the
mother of the incarnated God. This righteous man and his wife St. Anna
(Hannah) were stricken in years and had no children for Anna was barren.
The children of Israel used to insult him because he had not begotten a
son. Because of this, these two saints were sad, and prayed continually,
and entreated God by day and by night. They vowed that the child they would
beget would be made a steward for the temple. While St. Joachim was praying
over the mountain, he fell into a deep sleep and Gabriel, the angel of
the Lord, appeared to him and announced to him that his wife Anna would
conceive and bear a child, that would delight his eyes and please his heart;
and likewise all the world would rejoice and be glad. When he woke from
his sleep, he came to his house, and told his wife about the vision, which
she believed. Anna conceived forthwith, and brought forth our Lady, the
Virgin Mary, and St. Anna became more honorable than all the women of the
world.
