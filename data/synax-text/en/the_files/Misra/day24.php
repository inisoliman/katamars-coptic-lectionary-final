 Meanwhile the king died,
and another king reigned who worshipped the idols. The new king demolished
the churches and built pagan temples. He was unjust and he plundered and
captured women, among them &quot;Egezi-Hareya&quot;, the mother of St. Takla. Later
she returned safely to her husband and both glorified God and praised His
Holy Name. Afterwards, the angel of the Lord appeared to them in a vision
at night, and announced to them the birth of this saint. When the saint
was about one and half years old, a famine befell Ethiopia. When the twelfth
day of the blessed month of Baramhat, the commemoration of the honorable
head of the Heavenly hosts, drew near, Sarah, the mother of the child, was crying
because she was not able to celebrate this occasion. The child wiped away
her tears with his little hands and yet he was still unable to talk. He
pointed to her to carry him to where there was a plate with a little flour
in it. She took him to the plate where he dipped his hand in the flour.
The flour increased until it was pouring onto the floor. She brought baskets
and every time she emptied the plate, it became full again, until she had
filled twelve baskets. His mother then knew that God was with the child.
Then she brought to him the empty container of oil. He placed his hand
over it and it was filled with the power of God. In the same fashion, other
containers in the house were filled. When Tsega Ze-Ab, the father of the
child, returned from the church and knew what happened, he glorified God.
They celebrated the commemoration of the archangel Michael, fed the poor
and all the neighbors. God honored this saint with many miracles that he
performed during his life and also after his departure. When St. Takla
Haymanot completed his good strife, he departed in peace.
