 On this day, the great hermit and the
blessed St. Takla Haymanot, the Ethiopian, departed. He was born in a village
nearby Jerusalem which was the share of Zadok and Abia-thar the priests
during the reign of King Soliman, son of King David. Zadok begot Azariah,
Azariah begot Zadok, who was named after his grandfather, and Zadok begot
Levi, and so forth till the father of this saint was born. His name was
Tsega Ze-Ab (which means the Grace of the Father) and he married a woman
whose name was Sarah. They were righteous, God fearing and very rich. They
always celebrated the commemoration of the honorable Archangel Michael
on the twelfth day of each Coptic month, and gave alms to the poor and
the needy. Sarah, the mother of this saint, was very beautiful, meek and
adorned with many virtues, hence they called her &quot;Egezi-Hareya&quot; (i.e. God
has chosen her). However, She and her husband were bitter and sad because
they did not have any children. She went daily to the church imploring
God to give her a child that would delight her heart. Her husband also
went to the church at the time of the offering of the incense and taught
the congregation the fundamentals of faith. Every time he went to the church
he took from his own money an offering to the house of God. They both agreed
to disperse their money to the poor, the needy, the monasteries and the
churches.</p>
