 On this day also, the fighter
father, St. Thomas, Bishop of Mar'ash, departed. He was an ascetic worshipper,
who fasted and prayed continually, with many merciful deeds. Therefore,
they ordained him a bishop for the city of Mar'ash. He shepherded the flock
of Christ with the best of care. When the infidel Emperor Diocletian reigned,
he sent one of his representatives to the city of Mar'ash to torture the
Christians. He started with this saint. He ordered the saint to worship
the idols. The saint not only disobeyed him but also rebuked him on his
idolatry. He tortured the saint severely by flogging, and dismemberment,
then he cast him in an abandoned prison. From time to time, he ordered
to dismember one of his organs. First they cut his ears, then nose, lips,
his legs, then they smashed his teeth. He was left in this prison for twenty-two
years. His congregation thought that he had died, and they celebrated an
annual commemoration for him. A faithful woman came to him by night, and
threw to him provisions through a small opening.</p>
