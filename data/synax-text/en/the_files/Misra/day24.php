 The saint remained in this
condition until the righteous Emperor Constantine reigned and declared
the glory of the Christian faith, and ordered the release of the faithful
from prisons. The woman informed some priests of the whereabouts of this
saint. The priests came to the saint, carried him to the church with songs
and hymns. The people came forward for his blessing and kissed the places
where he was dismembered. When the Emperor assembled the council of Nicea,
this saint was one of those attended. As the Emperor came to the council,
he knelt before the fathers and kissed their hands. When he knew what had
happened to this father, he asked for his blessings. As the council adjourned,
he and the other bishops returned to their dioceses. He gathered his priests
and congregation, read to them the creed that was instiTutd by the council,
and also explained to them what was difficult to understand. Afterwards
the saint lived for a short period then departed in peace, when his episcopate
was about forty years.
