 On this day, the holy father Anba Moisis (Moses),
Bishop of Ouseem, departed. He was pure and chaste from a young age. He
learned the church subjects, and was ordained a deacon. Then he went to
the desert of Scetis and became a monk, under the direction of a righteous
man. Anba Moisis served him for eighteen years, devoting himself to praying
and fasting, and was adorned with humility and love. As the report of his
virtues noised throughout, he was ordained a bishop for Ouseem after Anba
Gamoul. He pursued a good, virtuous life, increased in righteousness, and
he shepherded the flock of Christ with the best of care. He was ascetic
and did not own anything all his life. He suffered, along with Pope Michael,
46th Patriarch of Alexandria, many tribulations. God wrought many signs
and miracles on his hands. Often, Anba Moisis foretold incidents before
their occurrences. For example, once he told Anba Tadros, Bishop of Misr,
that the King would not return to his kingdom, and it was so. When he completed
his strife and was in a good old age, he had a short illness. When he knew
the time of his departure, he called his congregation, blessed them, commended
them, and asked them to pray for him. They all wept and asked him to remember
them before Christ. He stretched out his hand, prayed, bid them farewell
and departed in peace. He remained in his chair for more than twenty years.
