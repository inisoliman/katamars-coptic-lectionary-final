 On this day, St. Moses (Moisees)
and his righteous sister Sarah, were martyred. They were born to rich,
Christian parents. When their parents departed, St.Moisees wanted to give
his sister in marriage, and to hand over to her all their possessions,
and to go and become a monk. She answered him and said, &quot;If you would get
married first, then I also can get married.&quot; He said, &quot;I have committed
many sins, and I want to become a monk to blot out my sins. I can not attend
to the marriage and the salvation of my soul at the same time.&quot; She answered
him saying, &quot;O my brother, how can you cast me to the snares of this transitory
world, while you seek to save your own soul?&quot; He said, &quot;Whatever you wish,
I will do.&quot; She said, &quot;What you do for your self, I likewise will do for
myself.&quot; When he saw her strong determination, he dispersed all their money
to the poor and the needy. He took his sister to a convent for virgins,
which was outside Alexandria. He also entered one of the monasteries for
men. They did not see each other for ten years. When Emperor Decius incited
persecution against the Christians, during the papacy of Pope Demetrius,
the twelfth Patriarch of Alexandria, many were martyred. St. Moses (Moisees)
sent to his sister Sarah to bid her farewell and to inform her that he
wished to shed his blood in the Name of the Lord Christ. She rose up immediately
and asked the abbess to release her. After she took the blessings
 of her sisters the nuns, she joined her brother on his way to Alexandria.
They confessed the Lord Christ before the governor. After they had been
tortured severely, their heads were cut off, and they received the crowns
of martyrdom.
