  On
this day St.Matrounah, who was a maid-servant to a Jewish lady, was martyred.
She was of Christian parents, and her mistress used to entice her to adopt
the Hebrew religion, but she refused and that is why her mistress used
to humiliate her, ill treat her, and over-burden her with servitude. On
some days she accompanied her mistress to the Hebrew Assembly, then returned
and went to the Christians' church. And when her mistress asked her where
she had been and why she did not enter their assembly, the Saint replied,
&quot;God has departed far away from the synagogue that is yours, how shall
I enter it? Whereas the place that should be entered is the church which
the Lord Christ had bought with His blood.&quot; Her mistress was angry at this
and beat her harshly, then imprisoned her in a dark place where she spent
four days without food or drink. She then took her out and beat her sorely,
then she returned her to her imprisonment where she died. After her death,
her mistress, (because she feared that the government would hold her accountable
for her blood), took her to the top of her house and threw her down so
that it would be said that she had fallen by chance. She was accursed by
God, her feet slipped and she fell down, died and went to Hell. As to the
Saint, she went to the eternal bliss.
