  On
 this day the Lord Christ had made a great miracle to the honorable Saint
 Abba Athanasius the twentieth Pope of Alexandria. When Emperor Constantius,
 the son of the saint Emperor Constantine, adopted the teachings of Arius
 who said that the Son was, after not being, and therefore not equal to
 the Father, he sent a man, whose name was Gawargios, to Alexandria. With
 him, he also sent five hundred horsemen and letters appointing Gawargios
 patriarch of Alexandria instead of Abba Athanasius the Apostolic. He ordered
 Gawargios to support the faith of Arius and slay all who would not be obedient
 to him. When this man arrived in the city, he preached the teachings of
 Arius but only a very few men of the city accepted his words. Therefore,
 he killed a large number of people, and St.Athanasius hid himself for a
 period of six years. After this time, he came forth and went to the city
 of Constantinople, and asked Emperor Constantius either to restore him
 to his see or to slay him to receive the crown of martyrdom. But the Emperor
 ordered his men to place him in a small boat and to leave him in the sea
 without food or water or a guide. The Emperor thought that he would die
 of hunger or thirst or get drowned. In this way he hoped to get rid of
 the saint and his admonition to him for his heresy, and they did with the
 saint as the Emperor had ordered them. The boat sailed along smoothly and
 in peace with the Lord's will and His care, and St.Athanasius was surrounded
 and cared for by the Angels until he arrived in Alexandria three days later.
 When the believers heard that their shepherd had arrived, they rejoiced
 and went out to him and received him with candles and songs of praise.
 Then they brought him into the church and expelled Gawargios and his followers.
 St.Athanasius set that day as a great feast to the Lord.
