 When Arbsima and the
     virgins knew this thing, they wept, and they went forth form the monastery
     entreating the Lord Christ to help them and to keep their virginity. They
     came to the country of Armenia, and entered the city of Tridatah. There
     they dwelt in a winery in a ruined garden. They had great tribulation in
     getting their food so one of them made glass and sold it, and with the
     money they paid for their food. When Diocletian sought for Arbsima, he
     did not find her. Later he heard that she was in the country of Armenia
     so he sent to Tridatah the governor to inform him about her and to keep
     her. When the virgins heard that, they left their shelter and hid themselves
     in the city. But some men told about them. Tridatah then commanded to bring
     Arbsima to him and when she did not wish to go, they abducted her and brought
     her to him. When he saw her beauty, he wanted to have her for himself,
     but she did not let him. He brought her mother to persuade her but instead
     she besought her to endure patiently, she comforted her, told her that
     she must not forsake her true Bridegroom, the Lord Jesus Christ, and that
     she must not defile her virginity. When he knew what her mother had done,
     he commanded to break her teeth, but God gave St.Arbsima power to overcome
     the governor; she pushed him forcefully and he fell on his back. She went
     away and left him lying on the floor although he was well known in war
     for his strength and bravery. He was ashamed of having been vanquished
     by a virgin damsel and ordered his men to cut off her head. The soldiers
     came and tied her, tore out her tongue, plucked out her eyes, and then
     cut her into pieces. When the governor rose up from his fall and his senses
     returned to him, he repented having killed the saint. He ordered to slay
     the rest of the virgins. The soldiers bored in the soles of their feet,
     flayed them, cut them in pieces, and then cast them out. One of them was
     sick and was lying on a bed, and she cried out to the soldiers to
     make her join her sisters. So, they cut off her head also and thus, all
     the virgins received crowns of martyrdom. The soldiers also slew all who
     had come with them from Rome. After their departure, the governor became
     mad and doctors could not help him until Saint Gregory, Bishop of Armenia,
     came to him and prayed over him. By this he was healed of his affliction
     and believed in the Lord Christ. And he took the bodies of the holy and
     pure virgins and laid them in a holy place.
