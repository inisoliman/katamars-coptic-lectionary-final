  On
     this day was the martyrdom of the holy virgins Arbsima and Agatha and their
     sisters during the reign of Emperor Diocletian. This infidel sought out
     the most beautiful damsel to marry. He sent the painters to every country
     and ordered them to paint a picture of the most beautiful damsel that their
     sights fell on and to give him an accurate description of her. When they
     arrived nearby Rome, they entered a monastery for the virgins and they
     found Saint Arbsima and thought that their was none like her in beauty.
     They painted a portrait of her and sent it to the Emperor who rejoiced
     at it. He then sent to the kings and governors to invite them to the wedding
     celebrations.</p>
