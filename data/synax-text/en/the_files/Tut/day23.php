 On
this day was the martyrdom of the righteous Saints Onanius and Andrews,
his brother. These saints were the sons of elders of the city of Led, and
from their youth they had agreed on becoming monks. They went to the holy
and honorable Abba Macarius, and they became his disciples and dwelt with
him for three years, during which they fasted and prayed continually with
love and humility, and their report was heard everywhere. They chose Onanius
to be a bishop and Andrews to be a priest. They shepherded the flock of
Christ with the best care. The conquered their souls and bodies. Julian,
the infidel emperor, heard about them, and he had them brought to him.
He commanded them to deny there faith in the Lord Christ, and to adopt
paganism. When they would not obey his commands, he tortured them severly
and they yielded up their spirits in the hand of the Lord Christ to Him
is the glory. Each received three crowns: one for monastic life, strenous
fighting and asceticism; one for priesthood and guarding of flock against
the devilish wolves; and a third one for martyrdom and the shedding of
blood for the Christian faith.
