 On this day the Church commemorates
     the departure of Abba Macarius, the sixty-ninth pope of the great city
     of Alexandria, in the year 1122 A.D. This father was an ascetic who practiced
     strenous self-denial from his earliest years, and he cared for the garb
     of monasticism. He went up to the desert of Scete and became a monk in
     the monastery of St.Macarius. He trained his soul by reading the Holy Scriptures
     and their explanations and by contemplating their significance. He excelled
     in righteousness and so was ordained a priest. When Abba Mikhail the sixty-eight
     Pope departed and his place became vacant, a group of bishops and priests
     went to the monastery of St.Macarius and assembled in the church with the
     senior monks of Scete. They sat there with them for many days, discussing
     who would best fill the position. They agreed unanimously to choose Abba
     Macarius because of his righteousness and devotion to ascetic life. They
     took him and bound him against his will, and he cried out and begged them
     to release him saying, &quot;I am not qualified to be raised to the dignity
     of the Papacy.&quot; Then they brought him bound to the city of Alexandria and
     ordained him Patriarch. The deed of his appointment was read in the Church
     of Mu'allakah (The Church of the holy Virgin) in the greek, Coptic, and
     Arabic languages. During the whole time in which he sat, he added to his
     works of righteousness and he daily taught the people and admonished them
     in fear of God. He gave alms and did works of mercy for the poor and needy.
     He never took anything from the Church, but rather, he used to give a large
     portion of the contributions which were paid to him to be spent on different
     righteous deeds. He sat as a Pope for twenty-seven years and departed in
     peace.
