  Today
we celebrate the consecration of the sanctuaries of the Resurrection in
Jerusalem in the year 326 A.D. In the twentieth year of the reign of Emperor
Constantine and after the meeting of the Holy Council at Nicea, Quee Helena
told her son Constantine that she had vowed to go to Jerusalem to get the
blessings of the holy places and to search for the wood of the life giving
Cross. He rejoiced at this and gave her much money, and he sent with her
a large number of soldiers. When she arrived there and received the blessings
of the holy places, she searched for the wood of the Cross and found it
after much toil. She praised it with great praises and paid to it much
reverance and honor. She commanded the building of the sanctuaries of the
Resurrection - the Golgotha, Bethlehem and the manger, the fortress of
Zion, Gethsemane and the sanctuaries, and other holy places - and that
they be inlaid with pearl and covered with gold and silver.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 There was in Jerusalem a
saintly bishop who advised her not to do that saying, &quot;For after a while
foreign people will come and seize this place and destroy it and take the
precious stones and the silver and the gold. But is preferable to build
good and strong buildings and the remainder of the money be given to the
poor and the needy.&quot; She accepted his words and gave him the money and
set him in charge of the work. When she returned back to her son and told
him what she had done, he rejoiced, and sent large sums of money and commanded
to pay the workers their wages in full so they would not complain. When
the building of the holy places was finished in the thirtieth year of the
reign of Emperor Constantine, he sent vessels and precious vestments for
the altars. He sent word to the Archbishop of Constantinople and to St.Athanasius,
the Pope of Alexandria to take their bishops and to go to Jerusalem where
they would meet the Archbishop of Antioch and the Bishop of Jerusalem.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 They tarried there until
the sixteenth of the month of Tut, when they consecrated all the altars
that had been built. On the seventeenth day they marched with the Honorable
Cross around all the holy places and they worshipped God therein, and gave
offerings, and they glorified the Cross and honored it. Then they returned
to their chairs.
