 On
     this day departed St. Gregory the monk. He was the son of righteous, Christian
     and exceedingly rich parents from one of the cities of Upper Egypt. They
     gave great importance to teaching their son the art of speaking and medicine
     and then they taught him the doctrine of the Church. Next, they sent him
     to the father Abba Isaac, bishop of their city who made him a deacon to
     serve the altar, and when they wanted him to get married, he refused. After
     this, the bishop promoted him to a full deacon and he kept continually
     praying as he had been inclined to solitude since his early years. He used
     to pay many visits to Abba Pachomius. He took much money from his parents
     and brought it to St.Pachomius, beseeching him to spend it on building
     monasteries. The saint accepted his alms and spent it on building the monasteries
     of the holy Cenobitism.</p>
