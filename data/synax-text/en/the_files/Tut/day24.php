  On
     this day also was the martyrdom of St. Quadratus, one of the seventy disciples
     who were chosen by the Lord. He was born in the city of Athens, and he
     was one of its wealthy and learned nobles. He believed in the Lord Christ
     and served him. Having received the grace of the Comforter on the day of
     Pentecost, he went to many countries preaching the life-giving Gospel.
     He entered the city of Magnis and preached there and the people of the
     city believed and he baptized and taught them the life-giving Commandments.
     Then he returned to Athens and preached there, but they stoned him and
     tortured him severely. Finally they cast him into the fire, and he received
     the crown of martyrdom.
