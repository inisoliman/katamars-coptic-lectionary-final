 After this, he went
     to Abba Pachomius, where he became a monk, and he struggled practicing
     all kinds of virtues. The fornicators learned purity from his appearance
     and example. He dwelt there for thirteen years. When Saint Macarius came
     to visit St. Pachomius, he asked St. Pachomius to permit him to go with
     St. Macarius. He dwelt with St. Macarius for two years, then he asked him
     if he could live alone and St. Macarius allowed him. He dug out a small
     cave for himself in the mountain where he dwelt for seven years. He used
     to come to St. Macarius twice each year, on Christmas and Easter, to be
     guided by him in his spiritual flight. When he had completed twenty-two
     years of strife, God wished him to rest. God sent to him an angel who informed
     him that after three days he would depart from the world. St. Gregory called
     the elders of the desert, and bade them farewell and asked them to remember
     him in their prayers, and after the three days, he departed in peace.
