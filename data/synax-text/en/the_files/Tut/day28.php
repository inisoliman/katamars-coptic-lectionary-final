  On
this day was the martyrdom of Saints Abadir and Irai, his sister, the children
of Wasilides, the minister of Antioch. Abadir was appointed Esfehselar
in his father's position. He had a room wherein he prayed and the Lord
Christ appeared to him in the middle of the night and told him: &quot;Rise up
and take your sister Irai and go to Egypt to receive the crown of martyrdom
and I will instruct a man whose name is Samuel to take of your bodies and
prepare them for burial, &quot; and He gave him His benediction and went up
into heaven. This vision was seen by his sister also and she heard a voice
saying, &quot;Hearken to your brother and do not transgress his command.&quot; When
she woke up, she trembled and she went to her brother and told him about
the vision, declaring that she would not disobey him. They swore to each
other to go to shed their blood in the name of the Lord Christ. When his
mother knew that, she rent her garments, she and her handmaidens and they
came to St. Abadir. His mother adjured him not to become a martyr and he
promised her that he would not go forward to Diocletian seeking martyrdom.
Her heart was soothed, not knowing his intention of going to another place
to become a martyr. Every night he used to change his apparel and go disguised
to give water to the prisoners all night, and he asked the door-keeper
not to tell anyone.</p>
