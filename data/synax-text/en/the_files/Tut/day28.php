 After this he saw
a vision to remind him of travelling. he took his sister and went to Alexandria,
then they came to Cairo and they found Saint Abekragon who recognized them
and blessed them. From there they came to Tomwah where they entered the
church and prayed; then, they went to El-Eshmunin and had a meeting with
Samuel the deacon. On the following day he went with them to Ansena, and
they confessed our Lord Christ before Arianus the governor, who tortured
them severely. Meanwhile, Saint Abadir prayed and entreated God to strengthen
his faith and the faith of his sister Irai. The Lord took their souls and
carried them up to the heavenly Jerusalem and they saw the eminent ranks
and the luminous habitations of the righteous; then he brought them back
to their bodies. The governor wrote their decree and then adjured Abadir
by his God to tell him his name and who he was. The saint replied, &quot;Swear
to me that you shall not change what you have decreed, &quot; and when the governor
swore to him, he said, &quot;I am Abadir El-Esfehselar.&quot; The governor cried
out saying, &quot;Woe to me, O my Lord why did you not let me know that you
are my Lord and let me go so far as to condemn you tpo all these severe
tortures?&quot; The saint replied, &quot;Fear not, for you are about to receive a
crown of martyrdom. The emperor will seek for me and will not find me,
and he will hear that you have killed me. Then he will call you and torture
you and you will die in the Name of our Lord Christ. And now make speed
to finish.&quot; And straightaway the governor ordered their heads be cut off.
The believers wrapped up their bodies in fine apparels and Samuel the deacon
took them to his blessed house until the days of persecution were ended
and a great church was built for them.
