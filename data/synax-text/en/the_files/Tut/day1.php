 On this day also was the
departure of the holy Apostle Bartholomew, one of the twelve disciples.
to this Apostle fell the lot that he was to go to the oasis (the great
oasis, Al-Khargah). He and Peter went together. There he proceeded and
preached to the people. He called them to the knowledge of God, after performing
before them signs and wonders that amazed their minds. He had originally
entered the city with Peter, who sold him as a slave. He worked in the
vineyards of a rich man and whenever he trimmed the vine branches, they
immediately bore fruit. It happened that the son of the governor of that
city died, and Bartholomew the Apostle raised him up from the dead. Then
all the people believed and he strengthened them in the knowledge of God.
After that, our Lord Jesus Christ commanded him to go to the land of the
Berbers and sent St.Andrew, his disciple, to help him.</p>
