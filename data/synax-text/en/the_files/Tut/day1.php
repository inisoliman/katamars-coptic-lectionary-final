 The people of that city
were exceedingly wicked, and would not accept any of the signs or wonders
the disciples performed. Yet the two disciples continued to preach and
teach them until they entered the faith of our Lord Jesus Christ. Then,
they appointed priests over them, built churches for them, and after that
they departed. St.BAtholomew left for the cities on the Mediterranean coast,
where the inhabitants knew not God, and preached unto them and converted
them to the knowledge of God and the belief in our Lord Jesus Christ. He
taught them to perform the works which were worthy of Christianity and
commanded them to be pure and chaste. When King Agrippa heard of him, he
was exceedingly enraged and commanded his servants to put him in a hair
sack, to fill the sack with sand, and cast it into the sea. And so were
consumated the struggle and martyrdom of St.Bartholomew.
