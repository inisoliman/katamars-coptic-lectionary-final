 In his days there appeared
     a man in whom there was an obstinate devil and who led many people away.
     He used to sit in the midst of church and the people would gather around
     to hear him, and they carried branches of trees. Abba Agatho sent for the
     posseddsed and had him brought to him, and he prayed over him. He cast
     out the devil who used to lead the people astray.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 Similarily, a woman claimed
     that St.Mina conversed with her and she commanded the people of her city
     to dig a well after the name of St.Mina to heal everyone who bathed therein.
     St.Agatho prayed over that woman until he cast out from her that unclean
     spirit and St.Agatho commanded the people to cover up that well with earth.
     At the hands of this holy man, St.Agatho, God worked many miracles, and
     he healed very many sick people and cast out devils. The devils appeared
     to him in the form of angels, singing sweet songs and imparting blessings
     unto him, but by the might of the Lord Christ he knew their guile, and
     he made the sign of the Cross over them, and they flew away defeated.</p>
