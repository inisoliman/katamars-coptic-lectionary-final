 When God wished to give
     him rest from the labors of this world, he fell sick shortly and delivered
     up his soul into the hand of God. All the people who had benefited from
     his sermons and teachings and gathered around him and wept bitterly. This
     holy father lived for one hundred years, of which he spent forty years
     in the world and ten years in the desert and fifty years in solitude upon
     that pillar.
