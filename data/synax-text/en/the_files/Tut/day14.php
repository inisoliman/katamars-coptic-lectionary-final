  On
     this day departed St.Agatho the Stylite. He was from the city of Tenis.
     The name of his father was Matra and his mother's name was Mariam. They
     were righteous and feared God, and they loved to give alms and gifts to
     the poor and needy. The thought of monasticism moved in his mind continually.
     When he was thirty-five years old, he was ordained priest, he devoted himself
     and served the church continually. He asked the Lord Christ by day and
     by night to facilitate for him his departure from this world, and to help
     him to depart to the desert. The Lord Christ answered his request and he
     went out from the city and came to Ternot (Mareot) and then to the desert
     where the angel of God appeared to him in the form of a monk who journeyed
     with him and brought him to the monastery of St.Macarius in Scete. He came
     to the holy old men Abba Abraham and Abba Gawargah and he became their
     disciple and lived with them for three years. After this they took him
     before the altar and in the presence of Hegomen Abba Yoanis, they remained
     three days in prayer over his garb of monasticism. Then they dressed him
     in the holy Eskeem. From that hour he exerted all his efforts in continuous
     fasting and prayer and fought a great fight. He used to sleep on the ground
     till his skin cleaved to his bones. He read continually the history of
     the striving of Abba Simon the Stylite, and he thought of leading a solitary
     life. He took counsel with the holy fathers concerning that, and they approved
     his opinion. They prayed for him and then he left and came near the city
     of Sakha where he dwelt in a little church. the believers built a place
     for him on a pillar and he went up on it and labored strenuously leading
     an ascetic life for fifty years.</p>
