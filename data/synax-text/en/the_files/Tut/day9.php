 On
     this day was the martyrdom of the holy father, the Bishop Abba Pisoura.
     He was the bishop of the city of Masil, which is beloved of God. When Diocletian
     went back to worshipping the idols and started persecuting the Christians,
     this holy man wished to shed his blood for Christ's sake. He gathered together
     all the people before the altar and advised them concerning the commandments
     of the Lord, and then informed them that he wished to obtain the crown
     of martyrdom for the sake of the Lord's name. They all wept, the young
     and the old, saying, &quot;To whom will you leave us, our father, as orphans?&quot;
     They wanted to prevent him from doing so, but when they could not, they
     let him go after he committed them to the Lord Christ. He left them bidding
     him farewell with much tears. Three bishops agreed with him; they were
     Baskos, Fenabikos, and Theodore, and they all went together to the city
     of the governor and confessed Christ before him. So he tortured them cruelly,
     especially when he knew that they were bishops and fathers to the Christians.
     The bold bishops endured the tortures with patience for the Lord Christ
     fortified them. Finally the governor ordered that the heads of the four
     be cut, and they received the crown of life in the kingdom of God. As to
     the body of Saint Pisoura, it rests at present in St.George's Church in
     Old Cairo.
