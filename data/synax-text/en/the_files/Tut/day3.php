 On this day of the year
243 A.D., a holy synod convened in the city of Alexandria in the second
year of the Papacy of St.Dionysius, the fourteenth Pope of Alexandria.
This council was made because of certain people in the Arabian countries
who believed that the soul dies with the body, and that on the day of the
resurrection, it shall be raised up with it. They composed articles on
this belief and sent them to certain people in Alexandria. When this reached
the ears of Abba Dionysius, he was exceedingly sorry, and he tried to restrain
the people from this evil, but they would not hearken unto him. Therefore,
the council assembled, confronted them, and made manifest their perversion.
As they neither repented nor turned away from their false belief, the holy
synod and the Pope excommunicated them and wrote an article for them wherein
he said, &quot;The love of God for us is exceedingly great, and the soul neither
dies nor perishes, but abideth as the angels and the devils, for it is
spiritual, immutable, and incorruptable. When the soul goeth on the day
of the resurrection, when the trumpet soundeth, the dead bodies shall rise
by the command of God. The souls go each into the body to which it belongeth,
and according to its work, it will either rejoice or suffer punishment
forever.&quot;
