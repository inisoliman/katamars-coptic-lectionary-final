 On this day St.Sophia became
a martyr. She used to go to church with her Christian neighbors and so
she became a believer of Christ the Lord. Longing to become Christian,
she went to the Bishop of Manufe. He baptized her in the name of the Father
and the Son and the Holy Spirit. Thereupon an accusation of becoming
a Chrisitan was brought against her before Claudianus, the governor. When
the governor questioned her, she did not deny it, and so he condemned her
to severe tortures. even when he cauterized her joints, she never ceased
to cry out, &quot;I am a Christian.&quot; then the governor commanded to have her
tongue cut off and sent her back to prison. He sent his wife unto her to
dissuade her, and when she would not be dissuaded, he commanded to have
her head cut off. she prayed and asked God to forgive the governor and
his soldiers. After her martyrdom, a Christian lady paid off the soldiers
and took her body, and sick people were healed by it. On her feast day,
very bright lights and incense came out of her holy body. When Constantine
heard the story of Saint Sophia during his reign, he carried her body and
placed it in a great cathedral he built for her.
