<p <?php echo $text_2; ?>>Departure of Saint Dioscorus the Twenty-Fifth
Pope of Alexandria</p>
<?php  if(file_exists("icons/Tut7-1.jpg")){ echo "<p $text_3m > <img src=\"./icons/Tut7-1.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
On
this day of the year 451 A.D., departed the blessed father and the great
hero of the Orthodox faith, Saint Discorus, the twenty-fifth Pope of Alexandria.
His departure took place on the island of Gagra, after he had fought a
good fight defending the Orthodox faith.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 When he was summoned to
the Council of Chalcedon by the order of Emperor Marcianus, he saw a great
assembly of six hundred and thirty bishops. Saint Discorus said, &quot;In whom
is faith lacking that it is necessary to gather this great assembly?&quot; They
told him, &quot;This assembly has been convened by the emperor's command.&quot; He
replied, &quot;If this assembly has been convened by the command our Lord Jesus
Christ, I may stay and say what God gives me to say; but if this assembly
has been convened by the emperor's command, let the emperor manage his
assembly as he pleases.&quot; When he saw that Leo the Archbishop of Rome was
teaching that Christ has two natures and two wills after His unity, he
spoke to confute this new belief. He stated that our Lord Jesus Christ
is one, He who was invited to the wedding as a man and changed the water
into wine as God, and that the two natures were not separate in all of
His works. Quoting Pope Cyril, he said, &quot;The union of the Word of God with
the flesh is like the union of the spirit with the body, and like the union
of fire and iron: even if they are of two different natures, by their unity
they became one. Similarly, our Lord Christ is one Messiah, one Nature,
and one Will.&quot; None of those who were gathered at that assembly dared to
contradict him. Among them were some who had attended the Council of Ephesus,
which had been convened against Nestor. They informed the Emperor Marcianus
and the Empress Belkarya that no one disobeyed their commands concerning
the faith of except Dioscorus the Patriarch of the City of Alexandria.
They brought him, and the senior bishops of the Council debated and discussed
the matter till it was evening, but St.Dioscorus would not deviate from
his Orthodox belief.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 The emperor and empress
were irritated at this, and the empress commanded to smite him on his mouth,
and to pluck out the hair of his beard, which was done. He took the hair
and the teeth that had dropped out, and sent them to Alexandria saying,
&quot;This is the fruit of Faith.&quot; When the rest of the bishops saw what had
happened to Dioscorus, they agreed with the king, being afraid of undergoing
the same fate. They signed the document of the belief that Christ has two
distinct and separate natures. When St.Dioscorus knew this, he sent for
the document pretending that he wanted to sign it too. But when he read
the document, he wrote at its foot that he excommunicated them all as well
as everyone who deviated from the Orthodox Faith. The king was enraged
and he commanded to banish him to the Island of Gagra, along with St.Macarius,
the Bishop of Edko, and two others, and the Council of Chalcedon was resumed.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 When they took St.Dioscorus
to the island of Gagra, its bishop, because he was a Nestorian, met him
with contempt and disdain. But God performed at the hands of St.Dioscorus
so that all obeyed him and magnified his greatness because God honors His
chosen ones in every place. St.Dioscorus told St.Macarius, his companion
in exile, &quot;You shall receive the crown of martyrdom in Alexandria.&quot; He
sent him with one of the believing merchants to Alexandria, where he earned
the crown of martyrdom.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 St.Dioscorus, having ended
his good fight, departed from this worthless life and received the crown
of eternal life. He departed in the island of Gagra where his body was
laid.
</p><p <?php echo $text_4; ?>>May his blessings and prayers be with us all. Amen.</p> 
<p <?php echo $text_2; ?>>Martyrdom of Saints Agathon, Peter, John,
Ammon and Ammona and their Mother, Rebecca</p>
<?php  if(file_exists("icons/Tut7-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Tut7-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also was the
martyrdom of Saints Agathon, Peter, John, Ammon, and Ammona and their mother,
Rebecca. They were from Kemola of the district of Kus. Our Lord Jesus Christ
appeared to them and informed them of what would happen to them and how
they would receive the crown of martyrdom in the city of Shoubra which
is near Alexandria, and that their bodies would be carried to the city
of Nakarha in the district of Behairah. The Saints rejoiced at this vision,
and they rose up early and gave all their possessions to the poor.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 Agathon, their eldest brother,
was a man of high position in the city and was loved by everyone. Rebecca,
their mother, encouraged them and incited them to bear the torture patiently
for the name of the Lord Christ. Then they came to the city of Kus and
confessed their belief in Christ before Dionysius, the governor, who tortured
them severely. He started with their mother who bore the torture patiently
and with joy, and then tortured her five children. When he was weary of
torturing them, he was advised to send them to Alexandria so that they
might not lead other people astray, for they were loved by everyone. Because
of them, many confessed their belief in Jesus Christ and received the crown
of martyrdom.</p>
<?php  if(file_exists("icons/Tut7-3.jpg")){ echo "<p $text_3m > <img src=\"./icons/Tut7-3.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 When they were brought before
Armenius, the governor of Alexandria who learned about their case, he tortured
them very severely. He hacked their bodies, cast them in a boiler, squeezed
them with wheels, then crucified them upside down. From all these sufferings,
our Lord Christ saved them until the governor and all his people were ashamed.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 Finally, he ordered to have
their heads cut off and to have their bodies drowned in the sea. God sent
forth an angel to a rich man from the city of Nakarha and commanded him
to take the bodies of the saints and the man was exceedingly glad for that.
He came to where the bodies were, gave the soldiers much silver and took
the holy bodies. When he laid them in the church, he heard a voice saying,
&quot;This is abode of the saints.&quot; The bodies remained there till the time
of persecutions passed, then their existence was revealed and a big church
was built for them. God made manifest from their relics, signs, and wonders.
Then they transferred the bodies to the city of Sonbat, where there is
a church known as, &quot;The Five and Their Mother&quot; or &quot;El-Sitt Refka&quot; (Lady
Rebecca). Many visit this church every year to get their blessing.
</p><p <?php echo $text_4; ?>>May their intecession be for all. Amen.</p> 
<p <?php echo $text_2; ?>>Departure of Saint Severianus, Bishop
of Gabla</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 On this day also departed
the righteous holy father, Abba Severianus, Bishop of Gabla in Greece.
The name of his father was Blaryanos. He studied the earthly wisdom of
the Athenians and then went to Caesarea for higher studies. He returned
to Rome where he studied the doctrines of the Church, and learned the Old
and New Testaments in a few years. After this his parents departed and
left him a great wealth. He wished to give it all to Christ so that he
might receive it back a hundred-fold. He built a hotel to house the strangers,
the poor, and the afflicted, and planted gardens to have the fruits distributed
to the poor. His name was given to these places after his departure from
this world. His uncle who was the governor of that city informed Emperor
Honorius that he had squandered all his money for the name of the Lord
Christ to receive from Him back a hundred-fold as He had promised in His
Holy Gospel. The emperor was pleased. He invited him and commanded him
not to leave the palace. He used to take him along to the church. In those
days Pope Yonakendios was sitting on the chair of Rome, and it was revealed
to him by God that Severianus would be in charge of a large group. The
Pope loved and honored him, and wished not to be separated from him, and
he was loved by everyone.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 When St.Severianus (Sawiros)
saw that everyone honored him, he became afraid of losing his labor, so
he decided to escape from earthly honors secretly. The angel of the Lord
appeared to him and commanded him to go to the city of Gabla and there
he would become father to many souls. After having put on the garb of the
monks, he departed by night and with him was his disciple, Theodore. God
sent to him a light to guide him to his destination. There was a monastery
led by a holy abbot who learned in a vision about the coming of St.Severianus.
He went out and welcomed him and told him about his vision. His fame reached
that region and a countless number of people came to him. The Emperor Theodosius
had one of the monasteries renewed for him to live in as the angel had
determined for him. He became the comforter of many souls. He continued
to teach and instruct the monks until they became saints like angels.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 God performed many wonders
at his hands. The daughter of the governor of Gabla had an evil spirit
dwelling in her and the spirit said to her father, &quot;If you drive away Severianus
from this place, I will get out of your daughter.&quot; When her father informed
the saint about that, he wrote him a paper saying: &quot;In the Name of the
Lord Jesus Christ, get out of her.&quot; When he returned to his daughter with
this paper, straightaway the devil screamed and left her. Once some magicians
agreed with some soldiers to break into his monastery, but they were smitten
with blindness and they remained like this for three days until the saint
prayed for them to be cured.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 Philatheus, the Bishop of
the city, learned in a vision from God that St.Severianus (Sawiros) would
succeed him on his chair and he said this to his people. When St.Severianus
was ordained, he looked after his people in the best way. There was in
that city a Jew called Sektar who was proud of his knowledge. He came to
the saint and debated with him until finally he was convinced of the correctness
of Christianity and the faith in the Lord Christ; many other magicians
also believed. During his days, Egypt became as proud of its monks as Constantinople
was of Saint John Chrysostom (of the Golden Mouth). When the Persians declared
war against Honorius and Arcadius, they sent to St.Severianus asking for
his prayers for the kingdom. He sent back to them saying, &quot;If we belong
to Christ, and our kingdom belongs to Christ, we have no need for armor
or spears or troops.&quot; And he reminded them of what the Lord had done with
those previous kings who pleased Him.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 When Empress Eudoxia was
angry with Chrysostom (of the Golden Mouth), she brought St.Severianus
with others for the trial of St.Chrysostom. He admonished her saying, &quot;John
Chrysostom (of the Golden Mouth) did nothing worthy of banishment,&quot; but
she would not hearken to him. He wrote many discourses and sermons which
still exist in the church books till now. He waxed old reaching the age
of one hundred years. Ten days before his death, the angel of God appeared
to him and informed him of the day of his departure from this world.
He gave advice to his people and then departed in peace. His pure body
was prepared as was met and was placed in the sepulchre. His departure
was two years before that of St.John Chrysostom (of the Golden Mouth).
</p><p <?php echo $text_4; ?>>May his prayers be with us all, and Glory be to God forever. Amen.</p> 
