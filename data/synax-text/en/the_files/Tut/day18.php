his mind and he perceived a divine grace coming down on the water and light
shone from it. He immersed into the water three times, then went up from
it and put on his clothes. He confessed that he became Christian. The Emperor
rebuked and threatened him. Then the emperor promised to give him many
gifts. In spite of that, the Saint went on saying, &quot;I am Christian. I am
Christian.&quot; Finally, the emperor ordered his neck to be cut off and he
earned the crown of martyrdom.
