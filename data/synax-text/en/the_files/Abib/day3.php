asking him to inform his envoys of the whereabouts of Celestine, and return
him to his See. They found him and returned him to his Chair with great
honor, and the people received him with joy and happiness. The peace and
the affairs of the church were established by his presence. When Nestorius
blasphemed and the Council assembled for him, Celestine was unable to attend
the Council, because of his illness, so he sent two priests with a letter
excommunicating Nestorius in it. The Emperor believed in what Nestorius
said, nevertheless he yielded to the decisions of the Council and exiled
Nestorius to Egypt. When the Lord willed for Celestine to depart from this
world, St. Boniface, his predecessor, and St. Athanasius, the Apostolic,
appeared to him and told him, &quot;Affirm your people in the faith, for Christ
is calling you.&quot; When he woke up he commanded his people saying, &quot;Take
heed to yourselves, for behold ravening wolves shall come into this city.&quot;
Having said this he added, &quot;I am leaving, for the saints are calling for
me.&quot; When he said that, he departed in peace.
