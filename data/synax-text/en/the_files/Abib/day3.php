 On this day, of the year 160 A.D. (June 27th, 444
A.M.), the great father, the pillar of faith and the lamp of the Orthodox
church, St. Kyrillos (Cyril) the First, the Alexandrian Pope, and the twenty-fourth
Patriarch of the See of St. Mark, departed. This saint was the son of the
sister of Pope Theophilus (23rd patriarch). He was raised by his uncle
at the school of Alexandria where he was educated in its Theological and
Philosophical subjects needed to defend Christianity and the Orthodox faith.
After he learned a great deal of these subjects, his uncle sent him to
the monastery of St. Macarius in the wilderness. There, he became a disciple
to a righteous old monk called Sarabamon. He taught him the church books,
and the sayings of the pure fathers. He trained his mind and body by practicing
the works of righteousness and virtues for a period of time. After he spent
in the wilderness five years, Pope Theophilus sent him to Abba Sarapion,
the honorable bishop, so he increased in wisdom and knowledge. Shortly
after, the bishop returned him to Alexandria. His uncle was rejoiced, ordained
him a deacon, appointed him a preacher in the cathedral and made him his
scribe. Whenever Kyrillos gave a sermon, he captured the hearts of his
listeners with his eloquence, fluency, and his strong influence.</p>
