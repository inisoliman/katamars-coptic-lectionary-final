 On this day also, the great Pope
Celestine, bishop of the city of Rome, departed (July 27th, 432 A.D.). 
 This saint was the disciple of St. Boniface, bishop of Rome. At the
time of his death, he commended that father Celestine would succeed him,
and then he cautioned him saying, &quot;Take heed O my son for there would be
ravening wolves in the city of Rome.&quot; This father was a righteous and well
learned monk. When Pope Boniface departed on September 4th, 422 A.D., they
ordained Celestine in his place on September 10th, 422 A.D., during the
reign of Emperor Honorius. This Emperor died in the city of Raffeen in
France in the year 423 A.D. One of the Emperors (Julian the Infidel) wanted
to appoint Nestorius a patriarch for Rome and expel Celestine the saintly
Pope. The people rose up and expelled Nestorius which made Emperor Julian
enraged against him. This Saint fled to one of the monasteries nearby Pentapolis
(Five cities) and dwelt there. God wrought many signs and miracles by his
hands. Then, the angel Raphael appeared to him in a dream saying: &quot;Rise
up and go to the city of Antioch to its patriarch St. Dimitrius, and abide
with him for the Emperor had decided in his heart to kill you upon his
return from the war.&quot; When he woke up, he went forth from that monastery
along with two brothers and came to the city of Antioch.</p>
