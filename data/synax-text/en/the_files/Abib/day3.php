 Since that time, he became well known for his vast
knowledge, his great righteousness, and his deep influence in his teaching.
When his uncle Pope Theophilus departed in the 18th of Babah 128 A.M. (October
15th, 412 A.M.), they enthroned this father in his place on the 20th of
Babah, 128 A.M. (Oct. 17th, 412 A.D.). The church was illumined with his
knowledge, and he gave special attention to resisting paganism and defending
the Christian faith. He started to refute the falsity of Emperor Julian
the Infidel in his ten essays that had been written after his apostasy.
These were the favorite readings of the pagan young people of Alexandria
and their pride, for they believed that it destroyed the principles of
the Christian faith. Pope Kyrillos refuted them in terms that were clear,
strong and convincing. He set out to rebut the heretics until he was able
to close their churches and seize their contents. He ordered the expulsion
of the Jews from Alexandria which led to a disturbance and confrontation
between the Jews and the Christians. This led to the widening of the contention
between the governor and this great saint. Because of his strong devotion
to the Christian ethics and teachings, he found himself compelled to ask
for reconciliation with the governor. However, the governor refused to
accept the reconciliation, and the conflict between them continued for
a period of time.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 When the heresy of Nestorius, Patriarch of Constantinople,
emerged, a Universal Council convened for him. He denied that the Virgin
was the mother of God (Theotokos). Two hundred bishops assembled in the
city of Ephesus during the reign of Emperor Theodosius II, known by Theodosius
the Less. St. Cyril (Kyrillos), Pope of Alexandria, presided over this
council. He debated Nestorius, explained to him his heretic opinion, and
threatened him with excommunication and exile from his Chair, if he did
not change his erroneous opinion. St. Kyrillos composed twelve discourses
wherein he explained the true faith, refuting the error of Nestorius. Anba
John, Patriarch of Antioch, and some of the bishops of the East disagreed
with him, taking Nestorius' side. Nevertheless, shortly after, they came
back and agreed with Kyrillos who was victorious over the enemies of the
church. He wrote many discourses and valuable epistles, confirming in them,
that God the Word is One Nature, One Will, and One Person incarnated. He
anathematized anyone who separated Christ or differed from this true faith.
The Emperor exiled Nestorius in the year 435 A.D. to the land of Egypt,
and remained in the city of Akhmim until his death in the year 440 A.D.
From the monumental works of Pope Kyrillos was the commentary of the Holy
Books. When he finished his strife, he fell sick for a short time and departed
in peace. He remained on the Alexandrian Chair for thirty-one years, eight
months, and ten days.
