 On this day, St. Bishoy, whose
memorial is honorable, the star of the desert, departed. He was born in
a town called Shansa in Egypt, and he had six brothers. His mother saw
an angel in a vision saying to her, &quot;The Lord says to you, give Me one
of your children to serve Me.&quot; She answered, &quot;Lord, take whoever you want.&quot;
The angel took the hand of Anba Bishoy, who was thin and his body was frail.
His mother told the angel, &quot;My Lord, take one who is strong to serve the
Lord.&quot; &quot;This is whom the Lord has chosen,&quot; answered the Angel. Later on,
St. Bishoy went to the wilderness of Shiheet and became a monk by the hand
of Anba Bemwah (Bamouyah), who also ordained St. John &quot;Yehness&quot; the Short
a monk. St. Bishoy struggled in much asceticism and many worships that
made him worthy to see the Lord Christ. Emperor Constantine appeared to
him in a vision, saying, &quot;Had I known how great is the honor of monks,
I would have abandoned my kingdom and became a monk.&quot; St. Bishoy told him,
&quot;You have banished the heathen worship and exalted Christianity, and has
not Christ given you anything?&quot; Emperor Constantine answered him, &quot;The
Lord has given me many gifts, but none of them is like the honor of the
monks.&quot;</p>
