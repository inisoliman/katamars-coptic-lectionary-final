 During his days, an ascetic
old man appeared in the mountain of Ansena, who was reputed for his righteousness
and to whom many people gathered. But he deviated from the true faith and
the devil lead him astray. He taught that there is no Holy Spirit, and
many were deceived by his sayings. Anba Bishoy heard about him, and he
went to him and he had with him a weaved basket with three ears. When he
visited the old man and his followers, they asked him about the reason
for making three ears for the basket. He answered, &quot;I have a Trinity, and
everything I do, is like the Trinity.&quot; They said to him, &quot;Then, Is there
a thing called the Holy Spirit?&quot; Then he started to explain to them from
the Holy Scriptures, from the Old and New Testaments. He indicated to them
that the Holy Spirit is One of the three Persons of the Trinity. He convinced
them, and they returned to the true faith. Then he returned to his monastery
in the wilderness of Scete (Shiheet). When the barbarians invaded the wilderness,
he left it and dwelt on Mount Ansena, where he departed. After the time
of persecution had ended, they brought his body with the body of St.Paul
of Tamouh to his monastery in the wilderness of Shiheet.
