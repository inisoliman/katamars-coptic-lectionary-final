 <p <?php echo $text_2; ?>>Departure of Cyrus (Karas), brother of
Emperor Theodosius</p>
<?php  if(file_exists("icons/Abib8-5.jpg")){ echo "<p $text_3m > <img src=\"./icons/Abib8-5.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 Today also, St. Cyrus (Karas)
departed. He was the brother of Emperor Theodosius the Great. This saint
knew well the vanity of the world and its temporal nature. He left all
his possessions and went out wandering without a destination. God guided
him to the inner Western Wilderness, where he lived for many years alone,
without seeing man or beast. There was in the wilderness of Shiheet (Scete)
a holy priest called Bamwa (Pimwah) who shrouded the body of St. Hilaria.
This father longed to see one of the servants of Christ, the hermits. The
Lord helped him until he came to the inner wilderness, and he saw many
of the saints. Everyone of them told him about his name, and the reason
he came to the wilderness. But St. Pimwah asked each of them, &quot;Is there
is anyone who lives further in the inner desert?&quot; They answered him, &quot;Yes.&quot;
He continued to walk until he finally arrived at St. Karas, the last one
of them. St. Karas called him from inside his cell, &quot;Welcome, Anba Pimwah,
the priest of Shiheet.&quot; Anba Pimwah entered his cell, and after the greetings,
St. Karas asked him about the news of the world, the governors and the
faithful. At night, St. Karas prayed for a long time, then he knelt to
the ground and delivered up his soul in the hands of the Lord. Anba Pimwah
buried him in his cloak, then he returned glorifying God, telling everyone
about the Saint and his strife.
