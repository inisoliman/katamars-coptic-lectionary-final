 During this, the wife of the Governor
died, and he asked the two Saints to forgive him for what he had done to
them. They prayed to God for her and God raised her from the dead. The
Governor and every one with him believed. He released the two Saints and
they returned to their town &quot;Sonbat&quot;. They gave the poor whatever was left
of their money. They gave the body of St. Noua to a righteous man called
Sarabamon. They asked him to hang an oil lamp before it at all times. Then,
they went to the Governor and confessed Christ. He ordered them beaten
and dragged in the city until their blood poured out on the ground. A deaf
and dumb woman took some of the blood and anointed her ears and tongue
with it. Instantly she was healed. She glorified the Lord Christ and confessed
Him. The Governor ordered them all to be beheaded. They all received the
crown of martyrdom. The righteous Sarabamon, and some people from Sonbat
were present. They took the bodies of the two Saints, shrouded them, and
took them to their town. A church was built for them, where their bodies
and the body of St. Noua were placed. It was said that their bodies are
now located in the church of St. Barbara in Old Cairo.
