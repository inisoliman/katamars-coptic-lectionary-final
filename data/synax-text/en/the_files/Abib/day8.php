 <p <?php echo $text_2; ?>>Martyrdom of St.Epime (Pimanon)</p>
<?php  if(file_exists("icons/Abib8-4.jpg")){ echo "<p $text_3m > <img src=\"./icons/Abib8-4.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 This day also, marks the
martyrdom of St. Epime (Pimanon) (Bima). He was the chief of the village
of &quot;Panokleus&quot; of the district of El-Bahnasa. He was rich and merciful
to the poor. The Lord Christ appeared to him in a vision and told him,
&quot;Arise, go to the Governor and confess My Name, for there you have a crown
prepared for you.&quot; When he awoke from his sleep, he distributed all his
money to the poor and the needy. Then he prayed, and went to El-Bahnasa,
and confessed the Lord Christ. When he confessed that he was the chief
of the village, the Governor asked him about the vessels of the church
in his town, and offered him the worship of the idols. St. Bima answered
him saying, &quot;I will not give you the vessels, and as for worshipping the
idols, I only worship my Lord Jesus Christ.&quot; The Governor ordered his tongue
cut off, and torture by the press and by burning. But the Lord saved and
healed him. The Governor then, sent him to Alexandria, where he was imprisoned.
Julius El-Akfahsi (the writer of the biographies of the saints) had a sister
possessed with an evil spirit. This Saint prayed for her and she was healed.
The report of this miracle spread out and many believed. The Governor became
furious and he tortured the Saint with the press and by pulling out his
nails. The Lord strengthened him and healed him. When the Governor became
weary of torturing him, he sent him to Upper Egypt. There he was beheaded,
and he received the crown of martyrdom. The servants of Julius El-Akfahsi
carried his body to his town.
