 <p <?php echo $text_2; ?>>Martyrdom of St.Piroou and St.Athom</p>
<?php  if(file_exists("icons/Abib8-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Abib8-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, St. Piroou and St.
Athom were martyred. These two Saints were born in the city of &quot;Sonbat&quot;,
of Christian parents who were righteous, loving works of righteousness
and charitable deeds. Their father's name was John and their mother's was
Mary. St. Piroou was blond with curled hair, tall in stature, with blue
eyes. St. Athom was tall in stature with white complexion, dark eyes and
black beard. When Piroou was thirty years old, and Athom was twenty-seven,
they attended church consistently during masses, and continued to give
alms and provide shelter for strangers. When persecution was incited against
the Christians, they took some goods and went to the town of El-Farma to
trade there. They found the body of a Saint called &quot;Noua&quot; with some of
the soldiers. They bought the body from them with silver, placed the body
in a marbled sarcophagus in their own home. They hung an oil lamb before
it, and many miracles appeared from the body. The two saints reflected
upon the vanity of the world, and the blessings of paradise. They distributed
their money among the poor, went to Alexandria and confessed Christ before
the Governor. He tortured them by beating and whipping them until their
blood poured out on the ground. They hanged them and put fire under them.
The Angel of the Lord came and brought them down and healed their wounds.
Then, the Governor sent them to El-Farma. When the Governor of El-Farma
saw their courage and the beauty of their appearance, he offered them the
worship of the idols. When they refused, he pulled out the nails of their
hands and feet. Then he put them on iron rods and lit fire under them.</p>
