 On this day, St. Euphemia, was martyred.
When Barsiros (Briskos), one of the deputies of Diocletian, was passing
down the road, there were with him some of the saints with iron chains
round their necks like dogs. This saint saw them and her heart waxed hot.
She was sorry for them and she wept. Then, she cursed the Emperor, his
idols, and admonished the Governor saying, &quot;O you whose heart is like a
stone, do you not have compassion on these holy men! or are you not afraid
that their God might destroy you?&quot; The Governor became enraged and informed
the Emperor about what she had done and said. The Emperor brought her and
asked her about her belief. She confessed that she was Christian. He tortured
her severely by beating and burning until she delivered up her pure soul
in the hand of the Lord.
