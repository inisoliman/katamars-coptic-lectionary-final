<?php  if(file_exists("icons/Abib12-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Abib12-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, St. Abba Hour,
was martyred. He was born in Siriakous to a father, who was an iron worker.
He wished to become a martyr, so he went to El-Farma where he confessed
the Lord Christ before its Governor. He tortured him much but the Lord
comforted him and healed his wounds. The Governor was amazed when he saw
that. That governor, his wife and his children believed in the Lord Christ.
They became martyrs by the hands of another governor, who also kept on
torturing the Saint Abba Hour. When he became weary of torturing him, he
sent him to Ansena, where he was squeezed by the wheel, crucified head
down, and burned by fire. Finally they cut off his head, and he received
the crown of martyrdom.
