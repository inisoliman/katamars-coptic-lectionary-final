 The next morning, the governor
ordered her brought to him. When he saw that she was well, he marvelled
much, and told her, &quot;Marina, your sorcery has become evident today, so
listen to me. Worship the gods and much good would be for you, and I will
give you all that I have promised you.&quot; She looked to him and to the dumb
idols with contempt and said, &quot;I worship the Lord Jesus Christ, the Son
of the Living God, the God of heavens and earth, and whatever you wish
to do with me, do, for I will not heed you.&quot; The governor ordered her hanged
on the wheel, the squeezing wheel, and squeezed very tightly. They did
so, then cast her in prison. The angel of the Lord came to her, and healed
her. Then the Devil appeared to her and said, &quot;O Marina, if you obey the
governor that would be for your good for he is merciless, and he wishes
to erase your name from the face of the earth.&quot; She realized that he was
the Devil. Straightway she caught the hair of his head, and she took an
iron rod and started to beat him, saying, &quot;Stop it O Satan.&quot; Then she bound
him with the sign of the cross, not to depart from before her until he
told her all about what he does to the human race. When she pressed him,
he told her, &quot;I am the one who makes adultery, stealing, blasphemy, and
earthly desires, good and desirable to the human. And if I do not overcome
him, I steer sleep and laziness against him, so he will not pray and ask
for the forgiveness of his sins.&quot; The Saint straightway expelled him.</p>
