 When the governor saw her
he marvelled much, then he ordered to uncover her body, and to fill a large
cauldron with melted lead, and to immerse her in it. When they did so,
she asked the Lord to make this a baptism for her. The Lord sent his angel
in the form of a dove. She immersed while saying, &quot;In the Name of the Father,
and the Son, and the Holy Spirit, one God Amen.&quot; A voice from heaven called
her and said, &quot;O Marina you have been baptized in the baptismal water.&quot;
She rejoiced exceedingly, and those who were present heard what had happened
to the saint. Many of them believed, and the governor ordered to cut off
their necks, and afterwards ordered to cut off St. Marina's holy head.
The executioner took her and went outside the city, then told her, &quot;My
lady Marina, I see the angel of the Lord and with him a crown of bright
light.&quot; She said, &quot;I ask you to tarry on me until I have prayed.&quot; She extended
her arms and prayed fervently, then told the executioner, &quot;Do what you
have been ordered to do.&quot; She bowed her neck to the executioner who told
her, &quot;I could not do so.&quot; The saint told him, &quot;If you do not do so, you
would not have a share in the Kingdom of God.&quot; When he heard what she said,
he took the sword and cut her neck off then he cut his neck also while
he was saying, &quot;I believe in the God of St. Marina.&quot; He fell down beside
her and he received the crown of martyrdom in the Kingdom of Heaven. The
Lord had manifested from her body many signs and healing miracles. Her
body is presently located in the church of the Lady the Virgin Mary in
Haret El-Roum.
</p><p <?php echo $text_4; ?>>May her prayers and intercession be with us and Glory be to God forever.
