<p <?php echo $text_2; ?>>Martyrdom of St.Longinus the Soldier</p>
<?php  if(file_exists("icons/Abib23-1.jpg")){ echo "<p $text_3m > <img src=\"./icons/Abib23-1.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day, St. Longinus
the Soldier, was martyred. He was Greek by nationality, from one of the
countries of Cappadocia. When Tiberius Caesar reigned, and appointed Pilate
governor of the land of Judah, Longinus was one of the soldiers that accompanied
him. When the time arrived that Our Lord wished to save the creation, Longinus
was one of the soldiers that were in charge of crucifying the Lord of Glory.
It happened that after the Lord had delivered up His soul, Longinus pierced
His side with a spear, and blood and water flowed from His Side. Longinus
marvelled exceedingly when he saw this, and his amazement increased when
he saw that the sun became dark, the curtain of the Temple was rent, the
rocks were split, and that the dead rose up from the tombs. He believed
and realized all the miracles which Our Lord performed from His Birth to
His Crucifixion. When the righteous Joseph took the body of the Savior,
shrouded Him, and laid it in the sepulcher, this Saint was standing there
with the guards when they sealed the tomb. When Our Lord rose from the
sealed tomb, Longinus was perplexed, and he asked God to explain to him
this mystery. Our Lord sent to him the Apostle Peter, who told him everything
which had been prophesied concerning the Redeemer. He believed, abandoned
the military service, went back to his country, and preached the Name of
Christ. When Pilate heard about this, he wrote to Tiberius about him, who
ordered his head cut off, and thus he received the crown of martyrdom.
</p><p <?php echo $text_4; ?>>May his prayers be with us, Amen.  </p>
 
  

<p <?php echo $text_2; ?>>Martyrdom of St.Marina, of Antioch</p>
<?php  if(file_exists("icons/Abib23-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Abib23-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, is the
commemoration of the martyrdom of the blessed St. Marina, who overcame
the Devil. She was one of the daughters of the nobles of Antioch. Her parents
were pagan. When her mother died, her father sent her to a nanny to raise
her, who was a Christian. She taught Marina the Faith of Christ. When Marina
reached the age of fifteen years, her father died. One day she heard her
nurse talking about the biography of the martyrs and what glory they receive
in the Kingdom of Heaven. She longed to become a martyr in the Name of
the Lord Christ. One day St. Marina went out of her house with her maiden
servants, and on her way she passed by Lopharius Ebrotus, the governor,
who admired her much when he saw her. He ordered her brought to him. When
the soldiers came to her, she told them that she was Christian. In turn,
when they told the governor this, he was distressed for he liked her, and
he had her brought to him by force. He offered her the worship of the idols
and asked her to forsake God, but she refused. Then he asked her, &quot;What
is your name? and from where are you?&quot; She told him, &quot;I am Christian. I
believe in the Lord Christ, and my name is Marina.&quot; He tried to persuade
her by many promises and promised to marry her, but she did not heed him.
When she cursed and insulted him, he ordered her body scraped with iron
combs, then rubbed with vinegar, salt and lime, which they did. Nevertheless,
she endured with patience. They cast her in prison, thinking that she was
about to die. Immediately the angel of the Lord came, and healed all her
wounds. While she was standing up praying, and her hands were extended
in the form of a cross, a huge and terrifying serpent came forth. When
she saw it she was frightened and her whole body trembled. The serpent
swallowed her up, and her soul almost departed from her. She made the sign
of the cross and prayed while she was in the belly of the serpent. It split
open and fell on the ground dead. St. Marina went out unharmed.</p>
