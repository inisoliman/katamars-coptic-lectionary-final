 On this day, the church commemorates the relocation
of the relics of the honorable Sts. Apakir and John. After they received
the crown of martyrdom as it is mentioned in the account of the sixth day
of the month of Amshir, some of the believers took their bodies. They laid
them in the church of St. Mark the Evangelist, which is to the south of
Alexandria. They remained there until the days of St. Cyril (Kyrillos),
the Pillar of Faith, the angel of the Lord appeared to him and commanded
him to relocate the relics of these two saints to the other church of St.
Mark by the seaside. He relocated them with great honor, then built a church
for them in this district. They arranged for them a feast on this day.
Beside the church there was a pagan temple wherein many heathens gathered.
When they saw the wonders that were manifested in the church of these two
saints many of them believed in the Lord Christ.
