<p <?php echo $text_2; ?>>Martyrdom of St.Quarshenoufa (Warshenofius)</p>
<?php  if(file_exists("icons/Abib29-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Abib29-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, St. Ouarshenoufa (Warshenofius)
was martyred. He was well learned, righteous, and pious. When they asked
him to become a bishop, he fled to the city of Tahmoun (Galgamoun, or Dalgamoun),
and spent the night there with two God loving, Christian brothers. The
Angel of the Lord appeared to him, and told him to go to the governor,
and confess Christ before him. When he woke up, he told the two brothers
about the vision. They all agreed to go together to go to the governor.
They came to the governor, confessed the Name of Christ before him, and
he tortured them severely. Then he took them with him to Sanhour where
he continued to torture them. Then he took them to the city of Sa, gathered
all the confessors and read to them the edict of the emperor to worship
the idols. St. Ouarshenoufa jumped and took the emperor's edict and tore
it to pieces. The governor was enraged and ordered him to be thrown in
a fiery furnace and thus he received the crown of martyrdom.
