 On this day, of the year 220 A.D., St. Theodore of Shotep
     was martyred. His father's name was John and he was from the city of Shotep
     in Upper Egypt. He went with his regiment to the city of Antioch, where
     he married the daughter of a pagan noble man, and begot by her this St.
     Theodore. When his mother wanted to present him to the house of idols to
     be educated there, his father refused. She became angry, drove him away,
     and the child remained with his mother. His father John prayed ceaselessly,
     and entreated God to guide his son Theodore to the path of salvation. The
     child grew up, and learned philosophy, wisdom, and literature. The Lord
     Christ illuminated his heart, and Theodore went to a righteous bishop who
     baptized him. When his mother heard of this she was sorrowed greatly, but
     the Saint did not mind her. He joined the army and advanced in the ranks
     until he became one of the great generals during the reign of Emperor Lucianus.
     The people of the city of Eukhitos worshipped a great serpent, and offered
     to him a human sacrifice every year. While St. Theodore was passing through
     this district, he saw a woman crying bitterly. He asked her about the reason
     for her crying. She answered him saying, &quot;I am a widow and they have taken
     my two sons to offer them as a sacrifice to the serpent, although I am
     Christian.&quot; He said to himself, &quot;They have wronged this woman, but God
     shall avenge her.&quot; He came down from his horse, and turned his face towards
     the East and prayed, then drew near the serpent. The people of the city
     were watching him from the tops of the walls of the city. The serpent was
     fourteen cubits long, but God gave him power over it, and he speared it
     with his spear and killed it, and delivered the sons of the widow. After
     this, Theodore came to Egypt to search for his father, and he stayed with
     him until he died, and then returned to Antioch. He found that the Emperor
     had apostatized the faith and started to persecute the Christians. He came
     before him and confessed the Lord Christ. The Emperor ordered him beaten
     with rods, burned, and cast into the fire. He delivered up his soul and
     received the crown of martyrdom. A Christian woman took his body - it was
     said that she was his mother - after she gave much money to the soldiers
     and hid his body until the end of the time of persecution. Churches were
     built in his name in many cities.
