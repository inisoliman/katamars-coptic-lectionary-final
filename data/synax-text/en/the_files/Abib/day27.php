 On this day also, St. Apamon (Abba
Amoun), who was from the city of Tarnut, was martyred. This saint came
to Upper Egypt, and he saw the tortures which were being inflicted by the
infidels upon the holy martyrs. He went to Arianus, the governor of Ansena
