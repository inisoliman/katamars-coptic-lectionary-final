arianus sent him to Alexandria. The angel of the Lord appeared to him,
encouraged, and strengthened him. There he was tortured much and many were
martyred because of him. Among them was a virgin, whose name was Theophila,
she came and stood up before the governor, confessed the Lord Christ, and
admonished him for his worship of the idols. He cast her in the fire but
the Lord saved her, and finally they cut off her head as they cut also
the head of St. Apamon.
