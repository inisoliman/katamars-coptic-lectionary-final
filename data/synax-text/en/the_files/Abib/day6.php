 On this day, St. Aoulimpas, who
was called Paul, one of the seventy apostles, was martyred. This Apostle
ministered to the disciples and carried the epistles of St. Peter to the
Gentiles. He went with him to the city of Rome, preached there, taught
and converted many to the Faith. When St. Peter was martyred, this Apostle
was the one to take his body off the cross, shroud him, and take him to
the house of one of the believers. Someone accused him, before the Emperor
Nero, of being one of the disciples of Peter. Nero brought him and questioned
him. The Saint confessed that the Lord Christ is the true God. Nero tortured
him severely. Then he asked him, &quot;How do you wish to die?&quot; The Saint replied
saying, &quot;I only wish to die for the Name of Christ. Kill me any way you
wish, and bring me speedily to my desire.&quot; Nero ordered to beat him and
to crucify him, head downwards, like his teacher St. Peter. They did so
and he received the crown of martyrdom.
