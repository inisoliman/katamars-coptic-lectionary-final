 On this day, Sts. John and Simon, his cousin,
who were from the city of Shoubramalas (Ziftah-Gharbiah), were martyred.
The mother of St. John was barren, and his father prayed ceaselessly to
the Lord to give him a son, whom he would vow to the Lord. He saw in a
vision St. John the Baptist, who told him that the Lord would give him
a son. When this Saint was born, his father called him John, and he built
a church in the name of St. John the Baptist. When the boy grew and was
twelve years old, his father put him in charge of tending the sheep. John
gave his food to the shepherds, and he fasted until the evening daily.
When his father heard this, he went to him to verify that. When the boy
saw him, he was afraid that his father might beat him, and he wanted to
flee. His father calmed him and asked him about his food. John replied,
&quot;It is inside the hut.&quot; When the father went inside, he found the basket
full of hot bread. He returned and told his mother what had happened and
both rejoiced for the grace that was bestowed upon their son. They prevented
their son from tending the sheep, and handed him to one who taught him
the church books. When John became eighteen years old, they ordained him
a priest. Simon, his cousin, who was also tending to the sheep of his father,
left that and became a disciple of this Saint. God wrought many signs by
the hands of St. John. When Diocletian denied Christ and worshipped idols,
Sts. John and Simon went to Alexandria. They confessed the Lord Christ
before its Governor, who tortured them much. Finally, he cut off their
heads, and they received the crown of martyrdom.
