 On this day, of the year
303 A.D. (July 8th), St. Procopius (Proconius), was martyred. He was born
in the city of Jerusalem, his father was a Christian whose name was Christophorus,
which means &quot;Bearer of Christ.&quot; His mother's name was Theodosia, and she
was a worshipper of idols. When his father died, Theodosia took her son,
and went to Antioch. She presented much money and expensive gifts to the
Emperor Diocletian, and asked him to make her son a governor for one of
the cities. He accepted her gift, answered her request, and appointed her
son the governor of the city of Alexandria. He commanded that Procopius
torture the Christians. When the Saint had gone a little way from the City
of Antioch, he heard a voice from heaven calling him by his name, and censured
his deed. The voice also threatened him by death because he dared and accepted
to do what was against the command of God. Procopius asked, &quot;Who are you,
O my Lord? I beseech you to show me yourself.&quot; A cross of light appeared
to him, and he heard a voice which said to him, &quot;I am Jesus , the Son of
the Living God, Who was crucified in Jerusalem.&quot; He was afraid and trembled,
and he turned to the city of Bit-Shaan (Bisan). He made for himself a cross
of gold like the cross that appeared to him.</p>
