 The Governor ordered the
return of the Saint to prison, until he could determine what to do with
him. He brought him back three days later and told him, &quot;Behold, I have
waited three days for you to return to your mind, to have mercy on yourself,
and to offer sacrifice for the gods.&quot; The Saint replied, &quot;The Lord Christ
is the only true God. As for these statues, which are made of stone and
wood, they are not gods and can neither harm nor help.&quot; The Governor became
angry and ordered the soldiers to cut his sides with swords. A swordsman,
whose name was Archelaus, stretched out his hand to cut the sides of the
Saint, whereupon his hand dried up, and fell down dead. The Governor ordered
to stab him with knives and pour vinegar in his wounds. Then they dragged
him by his feet to the prison, where he stayed for three days. The Governor
was wondering what he should do with him. Then he threw him into a pit
filled with fire, but the Lord delivered him and no harm came upon him.
Finally, the Governor ordered to cut off his head and he received the crown
of martyrdom.
