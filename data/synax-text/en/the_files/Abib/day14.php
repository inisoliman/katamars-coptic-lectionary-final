 On his way to Alexandria,
some of the bedouins attacked him to plunder whatever he had. But he overcame
them by the cross that he had. His mother told him, &quot;You must offer sacrifices
to the gods who delivered you from your enemies.&quot; The Saint replied, &quot;Rather,
I will offer the sacrifice to Jesus Christ, Who helped me by the power
of His cross.&quot; When his mother heard his words, she became angry, and sent
to Diocletian to inform him about that. The Emperor sent to the Governor
of Caesarea, Palestine, to investigate the matter, and to handle his torture.
When the Governor brought him, Procopius confessed his faith in the Lord
Christ. The governor beat him so severely that he was close to death, then
he cast him in prison. The Lord Christ appeared to him, surrounded by His
angels, released him from his bonds, and healed his wounds. The next morning,
the Governor asked about the Saint, and they told him that they found him
free and sound. He had him brought to the temple of the idols, where the
Governor was going to pray. When the Saint came, and the people saw him
whole, they all marvelled, and they all cried out in the name of Christ
saying, &quot;We are Christians, and we believe in the God of Procopius.&quot; Among
them were two prefects, twelve women, and St. Theodosia, mother of St.
Proconius. They cut off their heads, and they received the crown of martyrdom.
That was on the sixth day of the month of Abib.</p>
