 On this day also, of the year 1064 A.M. (July 8th,
1348 A.D.), Pope Peter the Fifth, 83rd Patriarch of Alexandria, departed.
He was known as Peter (Boutros) Ebn-dawoud. He was from St. Macarius monastery,
and was a priest in El-Shahraan monastery. He was enthroned on the 6th
of Tubah, 1056 A.M. (January 2nd, 1340 A.D.). All the days of his papacy
were peaceful and tranquil. He departed after staying in his Chair for
eight years, six months, and six days, and was buried in Old Cairo.
