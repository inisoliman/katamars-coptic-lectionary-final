 On this day, the great St. Macarius, the son
of Basilidis the Chancellor, was martyred. When the messengers reviewed
the order of Emperor Diocletian, which dictates the worship of idols, with
Macarius, he did not heed them. When the Emperor knew that, he sent Macarius
to the governor of Alexandria. He bid farewell to his mother, and asked
her to care for the poor and the needy, then he went with the envoy. The
Lord Christ appeared to him in a vision, encouraged him, and told him what
would happen to him. When he arrived to the city of Alexandria, he stood
before Armanius the governor, who deceitfully treated him well because
he knew that he was the son of Basilidis the Chancellor. When Macarius
did not change his counsel, the governor tortured him with all kinds of
torture. While he was being tortured, his soul was taken up to heaven and
he saw the habitations of the saints. Afterwards, the governor sent him
to Nikios where he was tortured again. They cut off his tongue and arms
and placed hot nails in his sides. God wrought many miracles on his hands.
Among these was a procession, in which a dead man passed by him. The saint
asked the Lord Christ to reveal His glory, and the man rose from the dead
instantly. The man told the people around him of what he saw in Hades,
and that Christ is the Lord of all. Many believed, and they were beheaded
and received the crown of martyrdom. It happened that Arianus the governor
of Antinoe (Ansena) was present in Alexandria, who took the saint with
him on his way back to Ansena. When he arrived in Shatanouf (Setnuf, Pshati),
the ship stopped and they could not move it again. The governor ordered
the soldiers to disembark the saint, where they cut-off his head. Thus,
he finished his strife and received the crown of martyrdom. When the righteous
emperor Constantine reigned, he sent the commander Eulogius with an order
to open the churches, renovate the fallen ones, and to destroy the pagan
temples. The Saint appeared to him in a vision and told him about the place
of his body. He went to the place and brought out the body, built a church
after his name, and placed the body in it. God performed many miracles
through the body of St. Macarius.
