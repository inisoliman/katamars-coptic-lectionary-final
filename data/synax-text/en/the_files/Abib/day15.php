 On this day, of the year
     379 A.D., the holy father, St. Ephraem (Ephraim) the Syrian, departed.
     He was born in the city of Nissibis, in the beginning of the fourth century
     to pagan parents, during the days of the righteous Emperor Constantine.
     It happened that he met with St. James bishop of Nissibis, who preached
     to him and taught him the particulars of the Christian Faith. Ephraem believed
     on his hands. St. James baptized him and Ephraim stayed with him. He excelled
     in his worship that surpassed his contemporaries. He debated the pagans
     and overcame them by the grace that was within him. When the council of
     Nicea convened, he went with his teacher St. James to attend the council.
     One day, it happened that while St. Ephraem was praying, he saw a pillar
     of light which extended from earth to heaven. When he marvelled at what
     he saw, he heard a voice saying to him, &quot;That what you saw is St. Basil,
     Bishop of Caesaria.&quot; St. Ephraem longed to see St. Basil and he went to
     Caesaria. He entered the church and stood in a corner of it. He saw St.
     Basil in his priestly vestments embroidered with gold. St. Ephraim doubted
     the holiness of St. Basil. The Lord showed him a white dove that alighted
     over St. Basil's head. God then inspired St. Basil of the presence of St.
     Ephraem. St. Basil called him by his name, and St. Ephraem marvelled at
     how he knew him. They greeted each other, and St. Basil ordained him a
     deacon.</p>
