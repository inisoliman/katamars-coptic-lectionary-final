     child that surpassed his age. He also tortured his mother with many kinds
     of tortures. But the Lord God delivered them safely each time. Many saw
     this and believed in the Lord Jesus Christ, and received the crown of martyrdom.
     Finally, the Governor ordered to cut the heads off of St. Cyriacus (Qyriacus)
