 St. Ephraem increased his
     asceticism, and many great virtues were manifested through him that surpass
     description. Among which was that of an honorable woman, who was ashamed
     to confess her sins orally to St. Basil. She wrote on a paper her sins
     which she had committed since her youth, and gave it to St. Basil. When
     he received it and knew what was written in it, he prayed for her. The
     piece of paper became blank except for only one great sin. The woman wept,
     and entreated him to pray for her that God might forgive this sin for her.
     St. Basil told her, &quot;Go to the wilderness where St. Ephraem is and he will
     pray for you.&quot; The woman went to him and told him what had happened. He
     said to her, &quot;I am not worthy of this honor, go back to St. Basil for he
     is a high priest. Go now quickly before he departs from this world.&quot; When
     the woman returned, she found that St. Basil had departed, and was carried
     on the heads of the priests. She wept, and threw the piece of paper on
     his coffin. She prayed to God interceding through the saint. Then, she
     took the piece of paper, and she found it completely blank. St. Ephraem
     had performed many miracles. In his days, Ebn-Disan the Infidel appeared.
     This father debated with him until he overcame his erroneous opinions.
     He wrote many articles and discourses.
      When he completed his strife, he departed to the Lord.
