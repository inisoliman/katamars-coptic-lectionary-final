 On this day, St. Titus, the Apostle, was martyred.
He was born in Crete, and he was the nephew of the governor of the island.
He learned the Greek language, its literature and wisdom, and he excelled
in it. He was meek and merciful. When the news of our Lord Jesus Christ
spread in all the land of Palestine and Syria, the governor of Crete, the
uncle of this saint, wanted to confirm what he had heard about the magnificent
signs, and eminent teachings of Christ. He sent Titus to verify that and
to bring him accurate information. When Titus arrived in the land of Judah,
he saw the signs and heard the Divine words of the Lord Christ. He compared
the words and miracles of our Lord to the words and deeds of the Greeks,
and he found a great and clear difference between them. So he believed
in the Lord Christ, and sent to his uncle telling him all that he had seen
and heard. When the Lord chose the seventy apostles, Titus was one of them.
After the ascension of our Lord Christ, Titus received the grace of the
Holy Spirit along with the disciples. He accompanied the apostle Paul to
many countries. When St. Paul went to Rome, St. Titus returned to Crete.
He built a church there, and ordained for it priests and deacons. Having
finished his apostolic strife, St. Titus departed in peace.
