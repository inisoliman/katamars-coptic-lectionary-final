 <p <?php echo $text_2; ?>>Martyrdom of St.Andrianus</p>
<?php  if(file_exists("icons/Nasie3-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Nasie3-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, St. Andrianus,
one of the commanders of the army of the emperor, was martyred. This saint,
whenever he saw a martyr he would ask him, &quot;Why do you do that to yourself?&quot;
They answered him, &quot;In the hope of the eternal life, and the everlasting
kingdom.&quot; He went to the emperor and confessed the Lord Christ. The Emperor
tortured him much then imprisoned him with many martyrs. Anatolia, the
wife of this saint, cut off her hair, and dressed in a man's apparel. She
came to the prison and ministered to the martyrs. She strengthened her
husband, comforted and consoled him. When other women heard about what
she did, they did the same. Later on the emperor ordered the legs of the
prisoners broken until they die. This saint came and encouraged her husband
until he delivered his soul to the hand of the Lord. After all the martyrs
had delivered up their souls, the emperor ordered their bodies burned,
but God brought down dew which put out the fire. Some believers carried
the bodies to Pisidia. A prince asked to marry St. Anatolia, but she refused.
When she finished her strife, she departed in peace.
</p><p <?php echo $text_4; ?>>May their prayers be with us. Amen.</p> 
 
 <p <?php echo $text_2; ?>>Departure of St.Yoannis XIV, the 96th
Pope of Alexandria</p>
