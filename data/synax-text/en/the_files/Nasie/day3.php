 On this day also, of the
year 1302 A.M. (September 6, 1586 A.D.), and during the reign of the Ottoman
Sultan Mourad III, Pope Yoannis XIV, 96th Pope of Alexandria, departed.
He was from Manfalout, and he was known by Yoannis El-Manfalouty. He became
a monk at El-Baramous monastery, in Wadi El-Natroun. He was ordained Patriarch
during the reign of the Ottoman Sultan Selim II, on the 22nd day of Baramudah,
1287 A.M. (April 17th, 1571 A.D.). During his Papacy the Christians were
forced to wear black turbans (head cover). He received a letter from the
Pope of Rome and he answered him back. Sultan Selim asked him to collect
head taxes from the Christians, and every one complied. He went to Alexandria,
and on his way back, he felt weak and ill at the city of El-Nahrawiah.
He departed there and was buried at the Church of St. George in Birma.
His body was relocated later on to El-Sourian monastery. He was on the
Chair for fifteen years, four months, and nineteen days.
