 On this day also of the
year 1168 A.M. (May 4th., 1452 A.D.) Pope Yoannis the eleventh, the 89th.
Patriarch of Alexandria, departed. He was known as Yoannis El-Maksi for
he was from El-Maksa in Cairo. His name was Farag before his ordination.
He was enthroned Patriarch on the 16th. of Bashans, 1143 A.M. (May 11th.,
1427 A.D.). He sat on the throne of St. Mark for 24 years, 11 month, and
23 days. His residence was in the patriarchal cell in Haret Zewala. When
he departed, he was buried in the tomb of the monastery of El-Khandak.
The Chair remained unoccupied after his departure, for four month and six
days. He was contemporary to the rulers El-Ashraf, El-Aziz, El-Zaher, and
El-Mansour. He encountered many hardships that required the intervention
of the kings of Ethiopia who threatened the Egyptian government to cut
the flow of the Nile because of the persecution of El-Nasara (The Copts,
the Nazarenes). The Patriarch was forbidden to communicate with the kings
of Ethiopia and Nubia without the permission and knowledge of the rulers
of the government.
</p><p <?php echo $text_4; ?>>May his prayers be with us. Amen.</p> 
 
