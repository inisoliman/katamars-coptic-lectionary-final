On this day also of the year 1319 A.M. (May 14th., 1603 A.D.), Pope Gabriel
the eighth, the 97th. Patriarch of Alexandria, departed during the reign
of Sultan Ahmad the first, the Ottoman. He was from Meer, and became a
monk in Anba Bishoy monastery in the wilderness of Sheahat (Scetis). His
name was Shenouda, and was ordained Patriarch on sunday the 16th. of Baunah
1303 A.M. (June 20th., 1587 A.D.). The enthronement celebration was headed
by Anba Zacharias, Bishop of Jerusalem, and Anba Kyrellos El-Khiami, in
the church of St. Mercurius in Old Cairo. At the time of his ordination,
the Copts were divided, and they chose for themselves four patriarchs,
and they deposed him. He returned later on to his Chair at the time of
Sultan Mourad the third, the Ottoman and his papacy was confirmed. It came
to pass (As was written in a document in St. Antonios monastery) that he
decreed that the fast of the Apostles must start on the 21st. of Baunah
until the 5th. of Abib, and that there should be no fasting during the
three days of Nineva, the Advent fast should start on the first of Kiyahk,
and that the fast of the Virgin be left optional. All the Copts at that
time approved what he had decreed. However, after his departure, they returned
back to the old tradition of fasting. He departed in the monastery of the
Virgin Mary known as El-Sourian, after he had been on the throne of St.
Mark for fifteen years, ten month, and twenty four days.
