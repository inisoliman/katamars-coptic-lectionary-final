 One of the noble women of
Rome came to visit him because she heard of his righteousness. After she
visited with him for a short while, she asked him to remember her in his
prayer. He said to her: &quot;May God erase all your memory from my mind.&quot; She
returned sorrowful and complained to the Pope in objection to this statement.
Pope Theophylus clarified to her what he meant, that he was afraid, that
the devil might use her memory to tempt him. When Arsanius started his
monastic life, he used to select for himself the white beans for his food.
When the Abbot of the monastery noticed, he gently struck the monk, who
was sitting beside Arsanius saying: &quot;It is not right that you distinguish
yourself from your brethren by selecting the white beans.&quot; Arsanius said:
&quot;This stroke is directed to you, O Arsanius!&quot; Arsanius mastered the virtue
of silence. When he was asked about that, he said: &quot;Many times I regretted
that I have spoken, but I have never regretted on being silent.&quot; He was
a very humble and modest man, who lived from selling the works of his hands
by pleating palm leaves, and giving the rest to the poor. He put down many
useful sayings and teachings. Whenever he entered the church, he hid behind
a pillar of the church so no one would see him. His appearance was good,
his face was bright and very cheerful. He was tall in stature, but he became
bowed because of his age. He visited Jerusalem when he was seventy years
old, to be blessed by the holy places, and then he returned to Sheahat.
When he departed, he was ninety-five years old: He spent forty years in
Rome, forty years in the wilderness of St. Macarius, ten years in Mount
Torah, three years in the monasteries of Alexandria, then he returned to
Mount Torah and lived there for two years.</p>
