 St. Arsanius explained this
vision to them, saying: &quot;The wood cutter was a man with a multitude of
sins. Instead of repenting, he added more and more to his sins. The man
who wanted to fill the pot with water was a charitable man who gave alms
from what he earned unjustly, and his reward was lost. The two men carrying
the pole were carrying the burden of our Lord Christ, but with great pride,
and therefore they both stayed outside the kingdom.
