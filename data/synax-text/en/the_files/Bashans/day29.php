her in a dream and told her of her conception and what he would become.
At age sixteen, he became a monk in the mountain of Antioch, and he led
a great ascetic life in worship and prayer. An angel of the Lord appeared
to him in a dream and guided him in his monastic life to the life of St.Pachomius.
He excelled in his worship to a level beyond the normal human level, so
that he lived alone on a high place like a pillar, for 45 years, during
which he ate grass. This father wrote many useful ascetic teachings, and
