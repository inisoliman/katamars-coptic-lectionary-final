 On this day of the year
403 A.D., the body of St. Epiphanius (His biography is under the 17th.
of Bashans), arrived to the island of Cyprus. The boat that carried his
body arrived to Cyprus from Constantinople on the 28th. day of Bashans.
The priests and the people came with crosses, gospels, candles and incense
and carried his body to the church. When they started to dig his tomb,
two deacons did not allow them. They were excommunicated by the saints
for their bad reputation. The body remained in the church for four days
without a change or a stench. His body looked as if he was asleep. A saintly
deacon came near the body and said: &quot;I know of your relationship with God,
and that you can restrain these evil opponents.&quot; He then took an ax and
hit the ground with it. The two opposing deacons fell on their faces immediately,
and they were carried to their homes and died on the third day. The body
of the Saint was anointed and wrapped, they buried him in a marble sarcophagus
in he church. Many miracles appeared from his body.
