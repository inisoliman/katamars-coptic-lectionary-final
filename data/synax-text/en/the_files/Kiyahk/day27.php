 On this day, the great saint Bisadi, the Bishop
of &quot;Ebsay&quot;, was martyred. When Emperor Diocletian heard that Anba Bisadi
and Anba &quot;Ghellanicus&quot; were confirming the Christians in the faith and
hampering the worship of idols, he sent to bring them before him. Anba
Bisadi asked the messenger to give him a chance for one night. He went
to the church and called his people and celebrated the divine liturgy and
administered to them the Holy Communion. He commanded them to be firm in
their Orthodox Faith, then he bade them farewell and submitted himself
to the Lord. He went with the messenger to Arianus, the Governor of Ansena,
and when the latter saw his illumined face and his reverence, he had compassion
upon him and said, &quot;You are a man of great dignity and you should have
pity upon yourself and obey the command of the Emperor.&quot; Anba Bisadi answered
and said, &quot;It is impossible for me to replace the kingdom of heaven with
this temporal life.&quot; After a lengthy negotiation with him, the Governor
ordered Anba Bisadi to be tortured and then thrown in a very hot water
bath. God preserved him and raised him unharmed and without any pain. The
Governor then ordered him beheaded. Thus, he received the crown of life
in the kingdom of heaven.
