 The Lord Christ appeared to this saint and
commanded him to make known to all the saints in prison that the Lord,
Whose Name be blessed, reckoned them among the martyrs and called them
the confessors. Emperor Constantine sent for 72 of them in order to receive
their blessings. They went to him along with St. Abanob, the confessor.
St. Poemen lived after that in a monastery outside the city of El-Ashmunein.
God granted him the gift of healing the sick and these reports spread in
all the surrounding districts. The Empress of Rome became sick with a grievous
illness which was difficult to treat. She visited many monasteries and
churches but she was not healed of her sickness. Finally she came to the
city of Ansena, and the governor of the city and his men accompanied her
to the place where St. Poemen was. When they informed him of the Empress'
presence and expressed to him her desire to see him, St.Poemen did not
go out to meet her but said, &quot;What have I to do with the kings of the earth.&quot;
When the brethren, the monks, besought him to go out to meet her, he did
so. When she saw him, she bowed down at his feet. The saint prayed over
some oil and anointed her and she was instantly healed of her sickness.
The Empress offered St. Poemen much money along with several expensive
gifts but he did not accept them, except for a few sacred vessels for the
altar, a paten, a chalice, and a cross of gold. The Empress returned to
Rome glorifying God.</p>
