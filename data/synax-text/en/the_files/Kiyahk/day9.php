 On this day St. Poemen, the confessor, departed.
He was from the village of Bani-Khaseeb, district of El-Ashmunein. He was
the steward of a rich man, whose wife trusted him greatly. Because of his
chastity and his righteousness, everybody loved him. Because of his disdain
for the vanities of this world, he left his work and went to a monastery
in this city wherein he became a monk. When the rich man, his employer,
knew about it, he and his wife went to him and asked him to come back to
his job, for they were sorrowful for his departure. When he did not go
along with them, they returned sad. The saint went on with his worship
and asceticism, but he was not satisfied with that, and longed to become
a martyr by the shedding of his blood in the Name of the Lord Christ, to
Whom is the glory. He went to Ansena and found many Christians were being
tortured for the Name of Christ. He therefore went forward and confessed
his faith. They tortured him severely by beating him, burning him, by dismemberment
of his body parts, and by squeezing him on the Hinbazeen. During all these
tortures, the Lord Christ strengthened him and raised him up whole. While
he was suffering in this manner, the era of worshipping idols came to an
end; for Constantine the Just became emperor and ordered all those in prison,
because of their faith in the Lord Christ, to be set free.</p>
