 There was a holy bishop close to St. Poemen
while he was celebrating the feast of some martyrs with several believers
in one of the monasteries. He knew that the Arian heretics took a false
bishop and lead many people astray. The bishop went to St. Poemin and told
him. St. Poemen took some monks and went where those heretics were. He
debated with them, explaining to them their evil counsel, and the Lord
dispersed them. The saint went back to his monastery, until he became an
old man. When he became sick, he gathered the brethren and advised them,
telling them that his time was drawing nigh to be with the Lord. The brethren
were sorrowful because of his approaching separation from them. When he
delivered up his soul, the brethren swathed him and prayed over him. Many
healing signs were manifested through his body.
