 This day marks the departure
of St.Peter Elrahawy Bishop of Gaza. He was born in the beginning of the
third century in the City of Raha, to a noble family. When he was
twenty years old, his parents gave him to the Emperor Theodosius, to be
in his company. He practiced asceticism and worship while living in the
king's palace because he had forsaken the world and its glories. He had
parts of the bodies of the holy martyrs of Persia with him. Abba Peter
left the royal court and became a monk in the monastery. He fought a great
spiritual fight. Shortly after, they ordained him Bishop of Gaza and its
surroundings, against his will. It was said that when he celebrated his
first liturgy, a lot of blood flowed from the Holy Body and filled the
Paten. Abba Peter took the body of St.James, the mangled, and relocated
it in a monastery in the city of Raha. When Marcian the Chalcedonian Emperor,
started persecuting the Orthodox Bishops, Abba Peter took the body of St.James
and went to Egypt where he dwelt in a monastery in El-Bahnasa. There he
met Abba Isaiah the Egyptian. At the end of Marcian's reign, Abba Peter
went back to the land of Palestine and went on confirming the believers.
One day while he was celebrating the Divine Liturgy, a few of the people
present in the church were distracted from listening to the prayers through
conversation. The angel of the Lord appeared to him and reproached him
because he did not admonish those who were talking in the church. Emperor
Zeno heard of him and longed to see him, but was not able to do so becuase
Abba Peter did not like the glory of this world. He went to the area between
Jerusalem and Damascus in Palestine, called Gawer. On the feast day of
St.Peter, the Pope of Alexandria Abba Peter celebrated the Divine Liturgy
during which St.Peter appeared and told him : &quot;Christ the lord is calling
you to be with Him.&quot; Abba Peter called the people and commanded them to
be firm in their Orthodox Faith, then he stretched out his hand and delivered
up his soul in the hands of the Lord.
