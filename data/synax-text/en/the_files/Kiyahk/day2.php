 When the time of his departure
from this futile world drew near, he saw the company of saints calling
him. He rejoiced exceedingly. He sent for his disciples, commanded
them to remain in the path of the ascetic life and told them that he was
about to depart to the Lord Christ. They were exceedingly sad because of
his his departure, and felt that they would be orphans without him. After
a short sickness, he delivered up his soul in the hands of the Lord.
