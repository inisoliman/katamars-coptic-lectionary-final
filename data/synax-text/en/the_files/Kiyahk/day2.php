 This day marks the departure
of the Saint Abba Hor, the Monk. This father was a native of the city of
Abraht in the district of Ashmoneen. He was a chosen monk that surpassed
many saints in his worship. He loved to live in seclusion, so he went to
live in the desert. Satan was envious of him, so he appeared to Abba Hor
and told him, &quot;In the desert you can conquer me because you are alone here,
but if you are brave go to Alexandria and I will tempt you there.&quot; When
saint Abba Hor heard that, he rose up and went to Alexandria. He remained
there for a while drawing water for the prisoners and the poor.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 One day horses were galloping
in the middle of the city, one of them hit a child and killed him immediately.
Saint Abba Hor was standing where the child was killed. Satan entered the
hearts of some of the people who were standing around and made them shout
saying, &quot;The killer of this child was that old monk.&quot; Several people were
passing by and heard that. They gathered around and knocked Abba Hor down.
The saint, Abba Hor, was not disturbed. He took the child in his arms,
praying to the Lord Christ in his heart, then he made the sign of the cross
over the child. The child's soul returned to him, and Abba Hor delivered
the child to his parents. The people standing around marvelled and glorified
God, and their hearts and minds turned toward Abba Hor. Being afraid of
the false honor, he escaped to the desert and stayed there in one of the
monasteries for the rest of his days.</p>
