 On this day St. John, Bishop of El-Borollos,
departed. He came from a wealthy family and from priestly ancestors. His
parents were charitable and gave generously to the poor. When they died,
St. John took the money they left and built a hostel for strangers. He
gathered the sick, served them himself, and offered them what they needed.
Once a monk visited him and saw his good deeds, he praised him and praised
monasticism in his presence, showing him its honor. The saint was attracted
to the monastic life and he had a deep love in his heart for it. After
the monk departed, the saint distributed his wealth among the poor and
went into the wilderness of &quot;Shiheet&quot; (Scetis). He became a monk under
the guidance of St. Daniel the archpriest of the wilderness. St. John was
known for his zeal for worship and for his great asceticism. He lived alone
in a secluded building. Satan and his soldiers envied his good deeds, and
they gathered against him and painfully beat him. He was sick for so many
days, after which the Lord Christ healed him. He regained his strength
and overcame the devil. God then called him to become a bishop of Borollos.
At this time, there were some heresies and he made a great effort to eradicate
them, and converted the heretics to the Orthodox Faith. Also in his
time, a monk from upper Egypt claimed that he could reveal certain things
which were imparted to him by the Archangel Michael, and he misled many
by his deception. St. John saw that the monk's deeds were from the devil.
He commanded that the monk be beaten until he confessed his sins and he
drove him out of the country. Another claimed that Habakkuk, the prophet,
appeared and revealed hidden things to him and, as a result, he was followed
by many. St. John drove him out of the country, after he had exposed his
deception. He also put an end to the use of several bad books. Every time
this saint went up to the sanctuary (Hekal) to serve the divine liturgy,
his face and all his body were flushed red, as though he came out of a
fiery furnace, and his tears poured heavily on his cheeks, for he was beholding
the heavenly hosts on the altar. Three times when he placed his finger
in the chalice to make the sign of the Cross during the fraction prayer,
he found that the cup was as hot as fire. Furthermore, in his days, some
infidels were partaking of the Holy Mysteries without having fasted. The
saint rebuked them, but since they did not hearken to him, he excommunicated
them and forbade them from the fellowship of the church. When they disobeyed
his order, he entreated God, so fire came down from heaven, and the fire
burned their leader. Fear fell upon the rest and they repented. When the
Lord wanted to repose him from the toil of this world, He sent to him St.
Antony and St. Macarius to tell him of the day of his departure. He called
his people and commended them then departed in peace.
