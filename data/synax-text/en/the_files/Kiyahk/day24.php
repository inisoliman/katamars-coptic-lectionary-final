 <p <?php echo $text_2; ?>>Departure of St.Philogonus, the Patriarch
of Antioch</p>
<?php  if(file_exists("icons/Kiyahk24-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Kiyahk24-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, St. Philogonus,
Patriarch of Antioch, departed. This saint was married and had a daughter.
When his wife died, he became a monk. For his great virtue, his bountiful
knowledge, his ascetic life, and his deep devotion, he was chosen Patriarch
over the city of Antioch. He shepherded the flock of Christ well and protected
it from the Arian wolves and the followers of Macdonius and Sabilius. As
a patriarch, he lived in piety and asceticism, renouncing the world, and
never owning one dinari or a second tunic. He completed his strife and
departed in peace. St. John Chrysostom had praised him in his sermons.
