 On this day, the relics of the
great St. Titus, the Apostle, and the disciple of St. Paul, were transferred
from Crete to Constantinople at the order of Emperor Constantine the great.
When Emperor Constantine converted to Christianity, he paid his attention
to the affairs of the churches in his empire, decorating them with the
best paintings and precious stones, especially those churches in Constantinople,
the capital of his empire. He also wanted to enrich the churches with the
precious spiritual jewels, by collecting the relics of the saintly apostles
and the honored martyrs. When he heard that the relics of St. Titus were
on the island of Crete, he sent some bishops there, and they carried the
relics with great honor and brought them to Constantinople. He built for
it a splendid sanctuary, placed the body in a coffin which was placed inside
the sanctuary. God honored this saint by manifesting many miracles and
signs from his sacred relics. Among them, when they carried the relics
to the Sanctuary (the Hekal) of the church, the stone coffer fell on and
broke the foot of one of the carriers. The man took some of the oil of
the lamp (Kandeel) that was hanging in front of the icon of the saint,
and anointed his foot with it, then wrapped it. He remained in the church
that night beside the coffer, for he could not go to his home. The following
morning, his foot was cured. What remained on it were only traces of blood.
He and all those who saw him marvelled. He washed the blood and walked
on his feet as usual without pain, glorifying the Father, the Son and the
Holy Spirit, the One God, and witnessing to this miracle.
