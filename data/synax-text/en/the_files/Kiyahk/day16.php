 Then Gideon and all the
people who were with him rose up early and encamped opposite the camp of
the Midianites. The Lord said to Gideon, &quot;The people who are with you are
too many for Me to give the Midianites into their hands, lest Israel claim
glory for itself against Me saying, 'My own hand has saved me.' Now therefore,
