 On this day, St. Mary the Ascetic,
the shut-in, departed. Her parents were among the wealthy and noble people
of Alexandria. Several of the sons of the great men in the city asked to
marry her, but she declined. When her parents departed, she distributed
all that they left among the poor, keeping just a modest part for herself.
Then she joined a convent near the City of Alexandria, and wore the monastic
garb. She exerted herself in worship for 15 years, then she put on the
holy &quot;Eskeem&quot; and put on a garb made of hair. After she took the permission
of the abbess, she shut herself in her cell, closed the door, and opened
a small window in it to receive her provisions. She spent 22 years in this
cell, fasting two days at a time. During the holy forty days fast (Lent),
she fasted for three days, and then broke her fast on some pulses moistened
with water. On the 11th day of the month of Tubah, she asked for a little
of the holy water. She washed her hands and feet, then she received the
Holy Communion, and drank from the holy water. She became sick and stayed
in her bed until the 21st of Tubah, when she received the Holy Mysteries
once more. She called upon the abbess and all the sisters, bade them farewell,
and asked them to visit her after three days. On the 24th day of Tubah,
they visited her and found that she had departed in peace. They carried
her to the church, and after praying over her, they placed her with the
bodies of the virgin saints.
