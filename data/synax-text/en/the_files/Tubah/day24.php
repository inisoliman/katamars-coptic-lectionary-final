 <p <?php echo $text_2; ?>>Martyrdom of Anba Bisada the Priest</p>
<?php  if(file_exists("icons/Tubah24-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Tubah24-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, St. Bisada
was martyred. His father was from El-Kase and his mother, who was the daughter
of one of the pagan priests, was from Ehreet. She was a believer in the
Lord Christ. When the son of a pagan priest asked her to marry him, she
took flight to El-Kase where she married a farmer, and God gave her a son
whom she called Bisada. They brought him up in the fear of the Lord and
in the keeping of His Commandments. When St. Bisada was twenty years old,
his father departed and left him a great wealth. St. Bisada increased in
the deeds of charity and righteousness. When Emperor Diocletian issued
his decree of worshipping the idols, the saint hid himself in his home,
and continued to worship God. A voice came to him from heaven saying, &quot;Why
are you delaying?&quot; Immediately, he rushed to the governor and confessed
his faith saying, &quot;I am a Christian.&quot; The Governor ordered him be tortured
by beating with whips, hitting his head with pins, pulling out his nails,
and dipping his fingers in vinegar and lime. He endured the torture for
several days with great patience, and the Lord Christ healed all his wounds.</p>
