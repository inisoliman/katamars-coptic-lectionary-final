 St. Bisada performed several
miracles, and the Governor became weary of torturing him; he chained him
and sent him to the Governor of El-Fayyoum. There St. Bisadai raised a
child from the dead. A large stone had fallen on the child while standing
beside a wall. The bishop of the City of El-Fayyoum heard about St.Bisada,
brought him and ordained him a priest. Then he went back to reappear before
the Governor of El-Fayyoum who tortured him, then sent him to Alexandria
where he received the crown of martyrdom. St. Julius El-Akfahsi (who wrote
the biographies of saints) took his body and gave it to his mother who
was present. She returned with the body to her home town, Ehreet, and all
the people of the town received the body of St. Bisada with joy, and buried
him with great honor. They built a church after his name, and the Lord
performed many miracles through his body.
