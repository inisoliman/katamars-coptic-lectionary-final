 <p <?php echo $text_2; ?>>Martyrdom of St.Lawindianus (Leontius)</p>
<?php  if(file_exists("icons/Tubah1-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Tubah1-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, St. Lawindianus
(Leontius) was martyred. He was from Syria during the time of the infidel
Emperor Maximianus. When the Emperor heard about this Saint and his worship
of Christ, he sent for him. He tried to entice him with much money to renounce
the worship of Christ and to worship the idols. The saint mocked the Emperor's
words and despised his presents, belittling his threats of tortures. The
Emperor, was enraged, ordered him to be hung on the squeezing machine (Hinbazeen)
to be pressed and then be beaten with pins, and to be cast in boiling oil.
The saint endured it all, and the Lord Christ strengthened and healed him.
When the Emperor was weary of torturing him, he ordered Lawindianus to
be beheaded, and Lawindianus received the crown of martyrdom. Many miracles
and wonders appeared through his body until he became well known in all
Syria, and several churches and monasteries were built in his name.
