 <p <?php echo $text_2; ?>>Martyrdom of St.Callinacus, Bishop of
Oseem</p>
<?php  if(file_exists("icons/Tubah2-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Tubah2-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 Also on this day, St. Callinacus,
bishop of Oseem, was martyred. When Emperor Diocletian heard the report
that St. Callinacus was teaching the people to get away from the worship
of idols, he sent envoys to seize him and torture him. When the saint heard
about the envoys of the Emperor, he called the people of his diocese to
the City of Oseem. He celebrated the Divine Liturgy and after he administered
the Body and the Blood of Christ to them, he told them, &quot;You will not see
my face again.&quot; The people wept bitterly, but they could not prevent him
from delivering himself to the Emperor's envoys. They took him and delivered
him to Arianus, Governor of Ansena (Antinoe). He tortured him, with different
kinds of tortures, but the Lord healed him and strengthened him. The Governor
took him to the city of &quot;Edku&quot;, and there he tortured him again. When the
Governor became weary of torturing the Saint, ordered that the Saint's
arm be split down to his hand.
 Subsequently, he took him in a ship to the city of &quot;Tukh&quot;. When the
saint felt, while he was on the ship, that the time of his departure from
the world had drawn near, he commanded one of the sailors who was a believer,
&quot;If I die, when we arrive ashore, cast out my body on a hill.&quot; When St.
Callinacus departed, the sailor did as he was commanded. Some believers,
through a command of God, came and took the body of the saint and shrouded
it for burial and hid it in their homes until the end of the era of persecution. 
