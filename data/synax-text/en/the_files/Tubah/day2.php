 On this day in the year
300 A.D., St. Theonas, 16th Pope of Alexandria, departed. This saint was
a righteous, meek scholar, gentle and loving to everyone. By the spirit
of friendship and gentleness with everyone, he was able to build a church
in Alexandria, dedicated to the name of the Virgin St. Mary, the Theotokos.
Until his time, the faithful were praying and performing their services
in homes and in caves for fear of the unbelievers. Pope Theonas dealt with
them wisely and gently to achieve what he wanted to do. He converted many
of them to believe in the Lord Christ and baptized them. He baptized, in
the first year of his papacy, St. Peter, who succeeded him on the apostolic
throne of St. Mark and was the 17th Pope. It was said that he ordained
St. Peter as a reader at the age of five, then he promoted him to be a
deacon at the age of twelve, then as a priest at sixteen. At the time of
this saint, a man by the name of Sabellius appeared in Alexandria who was
teaching that the Father, the Son, and the Holy Spirit are one person.
St. Theonas excommunicated him and he invalidated his heresy by convincing
proof. When he completed his course, he departed in peace, after he had
been on the throne of St. Mark for 19 years.
