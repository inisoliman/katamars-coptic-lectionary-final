 On this day of the year 338 A.D., St.
James, Bishop of Nisibis, departed. He was born in the city of Nisibis,
and was brought up there. He was Syrian by race. Early in his youth, he
chose the monastic life. He wore sackcloth made of hair to protect him
from the heat of summer and the cold of winter. His food was composed of
the vegetation of the earth, and his drink was only water. For this reason,
he was very thin, but his soul was illumined and full of grace. He was
worthy to receive the gift of prophecy and the performing of miracles.
He also was able to foretell the future and he advised the people of what
would happen to them in advance. His miracles are numerous. One day he saw some promiscuous
women jesting without shame by a spring of water, and they had let their
hair down to take a bath. He prayed to God, and the water of the spring
dried up, and the women's hair became white. When the women apologized
to him and repented for what they had done, he prayed to God, and the water
came back to the spring, but their hair remained white.</p>
