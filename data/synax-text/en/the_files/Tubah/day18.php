 Another miracle occurred when he was
passing by certain people who stretched a man on the ground and covered
him as though he was dead. They asked the saint for some money for his
burial. When they returned to the man, they found him dead. They came back
to the saint and repented for what they had done. St. James prayed to God,
and the man came back to life. When his virtues became widely known, he
was chosen to be a bishop over the city of Nisibis. He shepherded the flock
of Christ very well, and protected his people from the Arian wolves. He
was one of the bishops who attended the first Universal Council at Nicea
in 325 A.D., and agreed on the excommunication and exile of Arius. When
Shapur, the Persian King, came and surrounded the city of Nisibis with
his army, God, in answer to the prayer of St. James, brought swarms of
mosquitoes and wasps over their horses and elephants which caused a great
stampede and the animals fled away. The King of Persia then became fearful,
and he fled with his army and the siege was ended. When the saint completed
his good course, he departed in peace.
