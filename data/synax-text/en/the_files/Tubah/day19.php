 The precious relics were seen by the wife
of one of the priests. She took them joyfully, and because of her fear,
she entered the church and hid them in a side of the church and covered
them with pieces of brick. The relics remained hidden for twenty years,
for the woman forgot everything about them. But God wanted to reveal the
relics for the benefit of the faithful. The woman remembered them and she
made it known to the rest of the faithful. The priests came and carried
them while they were praying and praising God. They put them in a new coffin
in the church. Anba Gabriel, the bishop of the diocese, ordered this day
to be a feast and a memorial, and that their names be placed in the chronicle
of the feasts of the Church. Many miracles and signs were brought about
by God through these relics. One of these miracles concerns a daughter
of one of the believers who lost her sight and lost all hope for healing.
She interceded through the saints' pure relics and was instantly healed
and her sight returned. She glorified the Lord Christ Who honored His servants
with this great honor.
