 On this day, the church commemorates the discovery
of the relics of St. Abahor, St. Bisoura, and their mother Ampira. They
were from the town of Shabas, near Desouk in Egypt. They were martyred
during the era of idol worshipping, and their bodies were buried in the
church of their town. When the Europeans invaded Egypt, during the Crusades
in 1248 A.D., they gained control of Damietta (Domiat) and all the surrounding
towns. King El-Kamil, King of Egypt at that time, went out with his army
to fight the invaders. On their way, they destroyed many churches, among
which was the church of Shabas, where the relics of the saints were placed.
One soldier opened the coffin of these saints, hoping to find something
of value, rather he found these invaluable treasures that were of no value
to him. He threw their relics beside the wall of the church and took the
coffin and sold it. But the long suffering God was patient toward that
soldier, until he went back to his camp. He was the first to be killed
as witnessed by his companions on their return.</p>
