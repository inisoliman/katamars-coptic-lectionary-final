 On this day in the year 335 A.D., St.
Silvester (Sylvester), Pope of Rome, departed. He was born in Rome. For
his virtues, his ascetic life and his knowledge, he was chosen for the
pontificate of Rome in 314 A.D., after the departure of his predecessor
St. Miltiades. That was in the eleventh year of Emperor Constantine's reign
and less than a year after the issuing of the edict of Milan, which granted
freedom to Christianity. He baptized Emperor Constantine, for he was not
yet baptized. He was occupied with wars, demolishing pagan temples and
building churches. The life of this father was a bright and shining life.
He continued to teach the people, and remove all doubts from them. He explained
to them that which was difficult to understand. He frequently debated with
the heretics and converted many of them to believe in the Lord Christ,
and baptized them. He composed several discourses and he wrote several
books about the knowledge of God and the mystery of Incarnation. During
the seventh year of his papacy, the Ecumenical Council of Nicea convened,
and he excommunicated Arius and all who supported him. When he completed
his good course, he departed in peace. He occupied the Roman chair for
11 years.
