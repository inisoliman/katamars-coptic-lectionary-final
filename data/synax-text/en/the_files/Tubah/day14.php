 On this day St. Archilidis departed.
This fighter was born in the city of Rome. His father's name was &quot;John&quot;
and his mother's name was &quot;Sinclatiki&quot;. They were righteous before the
Lord and lived according to His commandments. This saint's father died
when he was 12 years old. When his mother wanted him to get married, he
declined. She advised him to go to the Emperor to take over his father's
position. She sent along with him two of their men and a precious gift
to present to the Emperor. While they were sailing, they encountered a
great tempest with high waves and strong winds, so that the ship was wrecked.
The saint hung onto one of the ship's planks, and God saved him from drowning.
When he made it to the seashore, he found a body of a dead man that was
thrown to the shore by the waves. He reflected on the transience of the
world and its temporal nature, and said to himself, &quot;What do I have to
do with this temporal world, and what would I profit when I die and become
dust?&quot; He arose and prayed to the Lord Christ to guide him to the right
way.</p>
