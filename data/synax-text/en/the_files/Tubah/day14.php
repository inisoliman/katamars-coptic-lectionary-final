 Then he walked diligently until he arrived
at the monastery of St. Romanus. He gave to the abbot of the monastery
what was left of his money. He stayed there living an ascetic life, denying
himself food and clothing, until he reached a level of perfection. The
Lord granted him the gift of healing the sick. He made an oath not to ever
see the face of any woman. When he did not return to his mother for a long
time, and she did not know his whereabouts, she thought that he died, and
she grieved much over him. She built a hostel for the poor and the strangers,
and she lived in one of its rooms. One day she heard two merchants talking
about her son and his holy monastic life and the grace of God that was
upon him. When she inquired about him, she became sure that it was him,
her own son. She arose quickly and went to that monastery. When she arrived,
she sent to inform the saint of her arrival. St. Archilidis answered her
saying that he had made an oath before God not to ever see a woman. She
repeated her request, and threatened that if he did not allow her to see
him, she would go to the wilderness to be eaten by the wild beasts. When
he learned of her persistence, and that he could not renege on his oath,
he prayed to the Lord christ to take his soul. Then he told the gate keeper
to allow her to come in while God had answered his request. When his mother
entered his cell, she found that he had given up his spirit. She cried,
wept and asked God to take her soul also, and God answered her prayer.
When they tried to separate their bodies, they heard a voice coming from
St. Archilidis' body saying, &quot;Let my body be with the body of my mother,
for I did not grant her own heart's desire to see me.&quot; They buried both
of them in one grave. God honored this saint in performing many miracles.
