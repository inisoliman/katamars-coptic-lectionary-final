 On this day, St. Babnuda (Paphnute), who was from
     Dandara (Dendereh), was martyred. This Saint was a hermit monk. The angel
     of the Lord appeared to him and told him to put on the priesthood vestments
     and go appear before Arianus, the governor. Arianus arrived with his ship
     and embarked by the city of Dandara, looking for that Saint. The Saint
     came to Arianus and cried out in his face with a loud voice, saying: &quot;I
     am Christian, and I believe in the lord Christ.&quot; When the Governor knew
     that he was the anchorite for whom he sought, he ordered him to be tortured
     severely. He chained him with iron fetters and cast him in a dark prison.
     A heavenly light shone upon him and an angel of the Lord appeared to him,
     healed his wounds, and comforted him. There was in the city a man, whose
     name was Kyrillos, with his wife, his daughter, and twelve young men. The
     Saint preached them and confirmed them in faith. They were all martyred
     by cutting of their heads, and they received the crown of martyrdom. The
     Governor was raged of him and ordered to hang a rock in his neck and cast
     him in the sea, and St.Babnuda received the crown of martyrdom.
