 On this day, St. Simeon
the Armenian, Bishop of the country of Persia, and 150 with him, were martyred.
This Bishop lived during the reign of Sapor (Shapur), the son of Hormiz,
king of Persia, who was unjust and oppressive to the Christians. This Saint
wrote a letter to king Sapor and told him: &quot;Those whom the Lord Christ
has bought with His honorable Blood had rid themselves from the servitude
of men, and it is not conceivable for them to be in servitude for those
who transgress the Law.&quot; When the king had read this letter, he became
exceedingly wrath. He brought him, bound him with chains, and cast him
into the prison. In prison, he found prisoners who worshipped the sun.
The Saint rebuked them, taught them, and they believed in the Lord Christ.
They confessed their faith before the king, who brought the Saint from
the prison, because he preached them the faith. The king ordered to cut
off the heads of the Saint and the 150 persons with him, and they received
the crown of martyrdom.
