 <p <?php echo $text_2; ?>>Martyrdom of the blessed Youhanna (John)
Abu Nagaah El-Kabeer</p>
<?php  if(file_exists("icons/Baramudah19-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baramudah19-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, of the
year 719 A.M., the blessed Youhanna (John) Abu Nagaah El-Kabeer, was martyred.
He was one of the nobel Copts in the tenth and eleventh centuries. He was
the head scribe in his time, as he was the lay leader during the reign
of Al-Hakim Be-Amr Ellah the Fatimid Caliph. This great elder was a contemporary
to Pope Philotheos, 63rd Patriarch, who was enthroned on March 28th. 979
A.D. and departed on November 8th. 1003 A.D. Youhanna was a devout Christian,
righteous, virtuous, charitable, and loving to the church. He was zealous
in the Orthodox faith. When Al-Hakim Be-Amr Ellah completed the extermination
of the people close to him and the leaders of the army, he turned to the
notables and chiefs of the scribes. He called ten of them and offered them
to adopt Islam. Youhanna, who was their head, was called first. Al-Hakim
told him: &quot;I want you to leave your faith and adopt my faith, the Islam.
I will make you my
 minister to manage the affairs of my kingdom.&quot; Youhanna replied saying:
&quot;Give me a chance until tomorrow to deliberate the matter with myself&quot;
Youhanna went to his house, called his friends, informed them with what
had happened, and told them: &quot;I am ready to die in the Name of the Lord
Christ, and my reason for asking for the delay, not to deliberate the matter
with myself but to see you and my family, to bid you and my family farewell,
and to commend you and them. Now my brothers, do not ask for this vain
glory, for you will loose the eternal glory of the Lord Christ Who satisfied
us with the richness of the world, and now with His mercy, He had called us to the Kingdom of Heaven, so strengthen your
hearts.&quot; His golden words, which were full of wisdom, influenced those
who heard them, strengthened their hearts, and they decided to die in the
Name of the Lord Christ also. He made a great feast for them, and then
they went to their homes. The next morning, Youhanna went to Al-Hakim Be-Amr
Ellah who asked him: &quot;O Nagaah, have you decided?&quot; Youhanna (John) replied
saying &quot;Yes&quot;. The Caliph asked: &quot;Which way have you decided?&quot; Youhanna answered steadfastly and with
courage: &quot;Remaining in my faith.&quot; The Governor attempted with all ways
of persuasion and threatening to make him forsake Christianity. John was
steadfast as a rock; nothing shook him away from the Christian faith, and
the Governor could not with all his powers make him renounce the faith
of his fathers.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 When the Governor failed with
Youhanna, he ordered to remove his clothes, be tied to the squeezing wheels,
and be beaten. They beat him five hundred lashes on his delicate body,
and his flesh was torn and his blood flew as water. The whips that were
used were made of cow hides; even the mighty ones could not bear one lash
from it on their bodies, much less, this gentle branch. Then the Governor
ordered to beat him up to one thousand lashes. After he was beaten three
hundred more lashes, he said as his Master: &quot;I am thirsty.&quot; They stopped
beating him and informed the Governor who told them: &quot;Water him after you
tell him forsake your faith.&quot; When they came to him with the water and
told him as the Caliph ordered, Youhanna replied with pride and dignity:
&quot;Take the water back to him, for I do not need it, because My Master Jesus
Christ had watered me and quenched my thirst.&quot; The people who were standing
around testified that they saw at this moment water dripping from his beard.
When he said that, he delivered up his soul. When they told the tyrant
Governor about his death, he ordered them to beat the dead body to complete
the one thousand lashes, and thus he was martyred, and received the crown
of martyrdom that was prepared for him by the Great King Jesus Christ.
The History of the Patriarch did not mention the day that he was martyred,
but El-Makrizi in his manuscripts said: &quot;The Vizier Fahd Ibn Ibrahim, one
of the ten men and the companion of Youhanna Ibn Nagaah, was slained in
the nineteenth of Barmoudah, 719 A.M. (April 14th., 1003 A.D.)&quot; The martyrdom
of the blessed Youhanna Ibn Nagaah was mentioned in the History of the
Patriarchs, before the mentioning of the martyrdom of the Vizier Fahd Ibn
Ibrahim. Youhanna, in the feast that he made for his friends and kinfolks
among whom were the other nine chosen ones, did not mention the account
of the martyrdom of the Vizier Fahd in what he said during the feast. Accordingly,
the martyrdom of this Saint was on the same day of the martyrdom of the
Vizier fahd.
</p><p <?php echo $text_4; ?>>May His blessings be with us. Amen</p> 
 
 <p <?php echo $text_2; ?>>Martyrdom of the Vizier Abu Elaala Fahd
Ibn Ibrahim and his companions</p>
<?php  if(file_exists("icons/Baramudah19-3.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baramudah19-3.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 This day also marks the
commemoration of the martyrdom of the Elder the Vizier Abu Elaala Fahd
Ibn Ibrahim, who was distinguished in the later half of the tenth century
and early the eleventh century. He was also contemporary to Pope Philotheos,
63rd Patriarch, and from the Fatimid Caliphs, Al Emam Al-Azeez Be Allah,
and his son Al-Hakim Be-Amr Allah. He was an Orthodox Archon, adhered to
his faith, faithful to his church, and charitable. During his life, he
never turned down anyone who asked him. Whenever he went through the streets
riding and one asked him, he would extend the sleeve of his cloak and the
one asking would find much good in it, and that to hide his virtue of giving.
This vizier was one of the powerful and influential men of the government
during the Fatimid Rule. Al-Hakim Be-Amr Allah appointed him head of all
the scribes and department heads. He built the church of the martyr St.
Mercurius in the present monastery of Anba Rowais, which was known then
by Dair El-Khandaq.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 It is documented in the
History of the Patriarchs that when Al-Hakim Be-Amr Allah wanted to make
the notable Coptic scribes apostatize their faith, the Vizier Fahd was
one of the ten that was chosen for that purpose. He brought him and told
him: &quot;You know that I have chosen and appointed you ahead of all the men
in my government, then listen to me and be with me in my religion, so I
will promote you more than what you are in now and be like a brother to
me.&quot; When he did not answer him, he ordered his neck to be cut off and
to burn his body. The fire remained burning for three days and the body
did not burn, and his right hand that he extended to give alms, was sound
at all the time as the fire never touched it. It was mentioned also in
the book of El-Khetat El-Tawfikiah that the Vizier Abu Elaala Fahd Ibn
Ibrahim was discussing the affairs of the government with the head of the
army, El-Housain Ibn Gawhar, and El-Hakim was luring him to apostatize
his faith with many promises. When Fahd refused, he ordered his head to
be cut off and to burn his body but God protected his body from burning.
He was buried in the southern corner of the church of St. Mercurius, which
he built in Dair El-khandaq. El-Makrizi wrote in his manuscripts: &quot;Fahd
Ibn Ibrahim was killed after he had remained as a chief minister of the
government for five years, nine months and twelve days.&quot; God had took revenge
severely from the wicked people that discredited Abu Elaala Fahd before
the Caliph and changed his heart against him. Twenty-nine days after the
departure of Fahd, the wicked man, Aly Ibn Omar Ibn El-addas, was killed,
then his companion, Taher Mahmoud Ibn El-Nahawy, was killed. The church
also commemorates the rest of the ten chief ministers that the Governor
asked them to apostatize their faith. When they refused and disobeyed him,
he ordered to torture them. They were beaten with whips, and when the beating
became cruel, four of them became Muslims, one of them died the same night,
and the other three returned to their Christian Faith after the end of
the time of persecution. The rest departed while they were being tortured
and received the crown of martyrdom and acquired the eternal life.
</p> 
