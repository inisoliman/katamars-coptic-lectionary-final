 After the departure of St. Narcissus, he continued
to shepherd the people of Jerusalem with the best of care, until Maximianus,
the infidel, seized him, inflicted him with severe tortures of every kind,
and then imprisoned him. When Gordianus reigned, he released him, and when
he died and Philip reigned, he released the rest of the confessors. This
father sat in quietness and peace until Decius rose, killed Philip, and
reigned in his stead. Decius afflicted the Christians exceedingly; he seized
this holy father and many others, and tortured them, especially this father.
He beat him cruelly with sharp pins until he broke his ribs, then commanded
to drag him by his feet and throw him in prison. He remained there until
he delivered his pure soul in the hand of the Lord, and received the kingdom
which is prepared for the saints.
