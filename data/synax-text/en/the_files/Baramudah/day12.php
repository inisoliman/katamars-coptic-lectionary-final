 On this day, the holy father Anba Alexander,
Bishop of Jerusalem, departed. This holy father was Bishop of Cappadocia,
and he came to the city of Jerusalem to receive the blessing of the holy
places and then return to his country. St. Narcissus, who was the Bishop
of Jerusalem at that time (Second century - his departure on the first
day of Baramhat), was advanced in age and had reached over 110 years. He
often asked his people that he wished to retire from his See, but they
refused. When St. Alexander finished his visit and decided to return to
his Chair in Cappadocia, the people of Jerusalem heard a voice from heaven
saying: &quot;Go to the gate of the city, and the first one to enter it, seize
him and make him stay with Narcissus to assist him.&quot; When they went to
the gate they met the Bishop Alexander, and they pleaded with him to stay
with Abba Narcissus to assist him. He refused because he could not leave
his flock that the Lord Christ had entrusted him with. They told him about
the voice which they had heard from heaven and that it was God's Will.
He accepted and wrote to the people of his parish what had happened, apologized,
and allowed them to appoint another bishop in his place. He remained in
Jerusalem, assisting its bishop Anba Narcissus, for about 5 years.</p>
