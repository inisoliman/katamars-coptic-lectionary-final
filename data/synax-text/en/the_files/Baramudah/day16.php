 On this day, St. Antipas, bishop of Pergamos,
was martyred. He was a disciple of St. John the evangelist (Rev. 2). Domitianus
started persecuting and killing the Christians because he heard, that they
were saying, that Christ was their God and King. This Saint was one of
them. He was tortured severely, but adhered more to the faith. During his
imprisonment, St. John the evangelist sent him a message to comfort and
strengthen him. In his message, he called him faithful priest and good
shepherd. Finally, the Emperor placed him in a bull of brass and lighted
fire under him until he delivered up his soul in the hand of the Lord.
The believers took his body and placed it with great honor in the church.
