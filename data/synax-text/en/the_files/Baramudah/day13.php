 <p <?php echo $text_2; ?>>Departure of Pope Yoannis the Seventeenth,
the 105th Patriarch of Alexandria</p>
<?php  if(file_exists("icons/Baramudah13-3.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baramudah13-3.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, the distinguished
Pope and prudent pontiff, Anba Yoannis the seventeenth, 105th Patriarch
of Alexandria, departed. The parents of this father were pious Christians
from the city of Mallawy, in Upper Egypt. When he was 25 years old, he
left this futile world and went to the monastery of St. Antonios. He became a monk there and his name was Abdel Sayed. Then he went to the
monastery of Anba Paula, after its renovation. He exerted himself in worship,
and educated himself. He learned reading and writing, for he was illiterate,
then he thoroughly studied the holy books. After he exerted himself in
asceticism and a virtuous life, studying the church subjects and its books,
the fathers the monks chose him as a priest for them. Pope Yoannis, 103rd
Patriarch ordained him along with his fellow Mourgan El-Assuity, who became,
later on, Pope Petros VI, 104th Patriarch. When Pope Petros VI, 104th Patriarch
departed, the fathers the bishops, priests, and lay leaders discussed who
would be fit for the Patriarchal Chair. They chose this father among others,
and brought them from the monasteries to Cairo. After they prayed the Divine
Liturgy for three days, they cast the lot, which fell on this father.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 He was ordained a Patriarch
in the church of the martyr Mercurius Abu Saifain, in Old Cairo, on Sunday,
the sixth of Tubah, 1443 A.M. (January 12th., 1727 A.D.). After his ordination
and before the reading of the Gospel, they opened the door to the tomb
of the fathers the Patriarchs, as the custom, for the newly elected Pope
to go down and take the cross and staff from the hand of his departed predecessor.
After he went down and took the cross, the bones in the tomb crepitated,
and he was terrified, so he ordered to stop this practice, saying that
the crosses and staffs were in abundance. The purpose of this custom was
that the successor will take a lesson from his departed predecessor, so
he would not be deceived by the position and become arrogant, and seeing
the fate of his predecessor would be a lesson and example before him always.
The Pope stayed after his enthronement a week in Old Cairo, then went to
the Patriarchal residence in Haret El-Rum.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 This Pope dedicated himself
to building churches and monasteries, their renovation and consecration.
During his Papacy, a wonderful church was built in the monastery of Anba
Paula, the first hermit in the Nemr Mount, and consecrated it himself.
He was accompanied by Anba Ebraam, Bishop of El-Bahnasa, and an assembly
of the notables. Among them was the archon Girgis El-Sourogy, who paid
for the building of this church. After that, Pope Youannis built a church,
refectory, and other buildings in the monastery of the honorable saint
Anba Antonios, the father of all monks. He consecrated it by his blessed
hands and ordained there hegumens, priests, and deacons. The honorable
archon Girgis El-Sourogy also paid for these buildings. In the ninth year
of his Papacy, in 1451 A.M., the Sultan ordered to raise the taxes for
the Christians and Jews three folds. Later, these taxes were raised more
and imposed over the monks, priests, children, poor, and beggars without
exempting anyone, so the time of this father was difficult and sorrowful
for the poor, professionals and trade workers.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 During his time, there was
also a great increase in prices and a severe earthquake shook Cairo in
the middle of the night, which lasted for about an hour. The foundation
of the earth violently shook, houses were destroyed, and people trembled
then God Had mercy on his people and removed from them these bitter tribulations.
When Anba Khristozolo III, 102nd Metropolitan of the Chair of Ethiopia,
departed, a group of Ethiopian lay leaders came to Pope Yoannis, in the
17th year of his Papacy, in 1460 A.M. (1744 AD.), and asked him to ordain
for them a Metropolitan. He ordained for them the monk John (Youhanna),
one of the priests of the monastery of our great father Anba Antonios,
and called him Youannis XIV, and returned with joy with him. This Pope
lived long and lived until a good old age shepherding his flock with the
best of care. When he finished his strife, he fell sick for a short illness
and then departed in peace on the Monday of the Paschal week, the thirteenth
of Baramudah, year 1461 A.M. (April 20th., 1745 A.D.). He sat on the Chair
18 years, 3 months, and 8 days, and was buried in the tomb of the Patriarchs
in the church of St.Mercurius Abu-Saifain in Old Cairo. He was contemporary
to the Sultan Ahmed III and the Sultan Mahmoud I. The Chair remained vacant
one month and ten days after his departure.
