Once Aristopolus and his son Mark were
     walking near the Jordan river, close by the desert, they encountered a
     raving lion and a lioness. It was evident to Aristopolus that it would
     be his end and the end of his Son, Mark. His compassion for his son compelled
     him to order him to escape to save himself. Mark answered, &quot;Christ, in
     whose hands our lives are committed, will not let them prey on us.&quot; Saying
     this, he prayed, &quot;O, Christ, Son of God protect us from the evil of these
     two beasts and terminate their offspring from this wilderness.&quot; Immediately,
     God granted this prayer, and the two beasts fell dead. His father marvelled
     and asked his son to tell him about the Lord Christ. He believed in the
     Lord Christ at the hands of his son who baptized him. After the ascension
     of the Lord Christ, he accompanied Paul and Barnabas to preach the Gospel
     in Antioch, Seleucia, Cyprus, Salamis, and Perga Pamphylia where he left
     them and returned to Jerusalem. After the Apostolic Council in Jerusalem,
     he went with Barnabas to Cyprus. After the departure of Barnabas, with
     the order of the Lord Christ, St. Mark went to Afrikia, Berka, and the
     Five Western cities. He preached the Gospel in these parts, and believed
     on his hands most of its people. From there, he went to Alexandria in the
     1st. of Bashans 61 A.D.</p>
     <?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
When he entered the city, his shoe was
     torn because of the much walking in preaching and evangelism. He went to
     a cobbler in the city, called Anianus, to repair it. While he was repairing
     it the awl pierced his finger. Anianus shouted in Greek saying &quot;EIS THEOS&quot;
     which means &quot;O, ONE GOD&quot;. When St.Mark heard these words his heart rejoiced
     exceedingly. He found it suitable to talk to him about the One God. The
     Apostle took some clay, spat on it and applied it to Anianus' finger, saying
     in the Name of Jesus Christ the Son of God, and the wound healed immediately,
     as if nothing happened to it. Anianus was exceedingly amazed from this
     miracle that happened in the Name of Jesus Christ, and his heart opened
     to the word of God. The Apostle asked him about who was the only God that
     he cried for when he was injured. Anianus replied &quot;I heard about him, but
     I do not know him.&quot; St. Mark started explaining to him from the beginning,
     the creation of heaven and earth, the transgression and fall of Adam, the
     flood, how God sent Moses, who brought the children of Israel out of Egypt,
     and gave them the Law, the captivity of the children of Israel to Babylon,
     and the prophecies that foretold the coming of Christ.</p>
    <?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 Anianus invited him to go to his
     house and brought to him his children. The Saint preached and baptized
     them in the Name of the Father and the Son and the Holy Spirit. When the
     believers in the Name of Christ increased and the pagan people of the city
     heard that, they were raged with anger and thought of slaying St. Mark.
     The faithful advised him to get away for a short while for the sake of
     the safety of the church and its care. St. Mark ordained St. Anianus a
     Bishop for Alexandria, three priests and seven deacons. He went to the
     Five Western Cities, remained there for two years preaching, and ordained
     bishops, priests, and deacons. He returned to Alexandria where he found
     the believers had increased in number, and built a church for them in the
     place known as Bokalia (The place of cows), east of Alexandria on the sea
     shore. It came to pass, when he was celebrating the feast of the Resurrection
     on the 29th day of Baramudah, year 68 A.D., the same day coincided with
     the great pagan Celebration for the feast of the god Syrabis, a multitude
     of them assembled and attacked the church at Bokalia and forced their way
     in. They seized St. Mark, bound him with a thick rope and dragged him in
     the roads and streets crying, &quot;Drag the dragon to the place of Cows.&quot; They
     continued dragging him with severe cruelty. His flesh was torn and scattered
     everywhere, and the ground of the city was covered with his blood. They
     cast him that night into a dark prison.</p>
     <?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 The angel of the Lord appeared
     to him and told him: &quot;O Mark, the good servant, rejoice for your name has
     been written in the book of life, and you have been counted among the congregation
     of the saints.&quot; The angel disappeared, then the Lord Christ appeared to
     him, and gave him peace. His soul rejoiced and was glad. The next morning
     (30th of Baramudah), the pagans took St. Mark from the prison. They tied
     his neck with a thick rope and did the same as the day before, dragging
     him over the rocks and stones. Finally, St. Mark delivered up his pure
     soul in the hand of God, and received the crown of martyrdom, the apostolic
     crown, the crown of evangelism, and the crown of virginity. Nevertheless,
     St. Mark's death did not satisfy the rage of the pagans and their hatred.
     They gathered much firewood and prepared an inferno to burn him. A severe
     storm blew and heavy rains fell. The pagans became frightened, and they
     fled away in fear. The believers came and took the holy body, carried it
     to the church they built at Bokalia, wrapped it up, prayed over him and
     place it in a coffin. They laid it in a secret place in this church.
