 On this day, the pure and holy mother Theodora,
departed. This holy woman was the only daughter of noble and Christian
parents of Alexandria. Her parents Provided for her costly apparels and
many gold and silver accessories, for they wished to give her in marriage.
This Saint refused that, for she desired in her heart the worship of God
and the strife for His Name's sake. She sold all what her father bought
her, gave to the needy, and then built a church outside the city of Alexandria,
towards the west. Then she went to the holy father Abba Athanasius, the
apostolic (Fourth century), who shaved her hair and made her a nun in one
of the convents outside the city of Alexandria. She devoted herself to
the ascetic life, fought the spiritual fight, and became worthy to see
divine visions, distinguish angels from satan, and know the thoughts of
the minds. Pope Athanasius visited her often and instructed her with his
teachings. When he was exiled, he sent her many letters full of valuable
sermons, and she was steadfast in her strife until the end of her life.
She was contemporary to five Patriarchs: Alexandros, Athanasius, Petros,
Timotheos and Theophilos. She put down many useful sayings, some of them
by the grace that was in her; the others were from what she learned from
those fathers. Once she was asked: &quot;If a man talked to another evil words,
would he silence him, or rebuke him, or close the ears and not listen to
him?&quot; She replied saying: &quot;If a man put in front of you a table with good
and bad foods, you can not say to him &quot;Take this or that for it is harmful
for me,' but you overlook it and eat what you desired, so nothing should
be said to who speak bad words to others but it is enough that the man
does not let his ears enjoy what he is hearing.&quot; She was also asked: &quot;How
can the human overcome his enemy Satan?&quot; She answered saying: &quot;With fasting,
prayer, and humility.&quot; When she finished her strife, she departed in peace
and was one hundred years old.
