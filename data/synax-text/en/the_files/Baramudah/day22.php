 In his days, the Muslim
Arabs conquered the Greek Isles, captured many of their women and children,
brought them to Alexandria, and started to sell them. The Pope gathered
money from the believers, and beside the funds of the monasteries that
he had, he was able to pay three thousand Dinars to save and free them.
He wrote for them bills of manumission and set them free. He provided those
who wished to return to their country with whatever they needed, and those
who wished to stay, he gave them in marriage and protected them. He took
thought for the church of the Redeemer in Alexandria and restored it, but
some evil men burned it, so he restored it again. When the Lord willed
to give him rest, he became sick. He prayed the Divine Liturgy and partook
of the Holy Mysteries. He bade the bishops that were present farewell and
departed in peace after staying on the Chair 20 years, 2 months and 21
days.
