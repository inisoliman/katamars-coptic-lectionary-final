 On this day also, of the
year 535 A.M. (April 17th., 819 A.D.), the blessed father Pope Mark (Marcus),
49th Pope of the See of St. Mark, departed. This Pope was from Alexandria,
and he a was chaste, learned, and honorable man. Pope John ordained him
a deacon, and he was an eloquent speaker. His voice was sweet and all those
who heard him rejoiced in him. The Pope handed him the administration of
the papal place, and he did nothing without his advice. When Pope John
put on him the garb of monks in the monastery, one of the elder monks shouted
saying: &quot;This deacon whose name is Mark shall, rightly and fittingly sit
upon the throne of his father Mark, the Evangelist.&quot; When Pope John departed,
the bishops unanimously agreed to choose him Patriarch. He fled to the
desert, but they caught up with him, brought him back, and enthroned him
Patriarch on the second of Amshir, 515 A.M. (January 26th., 799 A.D.).
He tended to the churches needs, and restored those that were in a ruinous
state. He returned many of the heretics to the Orthodox faith, healed many
of the sick, and cast out, of many of them, devils. He told them: &quot;What
had happened to you was because you dared to partake of the Holy Mysteries
with irreverence, so keep yourselves henceforward from the evil words that
come out of your mouth.&quot;</p>
