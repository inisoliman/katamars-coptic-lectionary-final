 Pope Alexander expelled
Arius from the country. Arius went to Emperor Constantine and complained
of the unjust treatment of this Pope. Emperor Constantine assembled the
Ecumenical Council of the Three Hundred and Eighteen in the city of Nicea.
The council was presided by Pope Alexander. He debated with Arius and revealed
his denial of Christ, then excommunicated him and those who follow his
belief. Alexander, along with the rest of the fathers, uttered the Creed,
and drew up the Canon, the Law, and the StaTuts that are still in the
hands of Christians until this day. After he put down regulations for Lent
and the feast of Easter, he returned to his Chair, victorious and triumphant.
He shepherded his flock with the best of care. He sat on the throne of
the See of St. Mark for 15 years, 9 months and 20 days, then departed in
peace.
