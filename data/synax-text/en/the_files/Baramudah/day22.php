 On this day also, of the
year 567 A.M. (April 17th., 851 A.D.), the holy father Pope Michael (Khail),
53rd Pope of Alexandria, departed. This father was a righteous monk, and
he was ordained hegumen for the monastery of the saint Abba John. Because
of his good conduct, they chose him Patriarch, and he was enthroned in
the 24th. of Hatur 566 A.M. (November 20th., 849 A.D.). When the
Holy Fast came, he went to the desert of Scetis to keep the fast there.
He remembered his earlier life in the wilderness, so he asked God with
tears and supplication saying: &quot;O God, you know how much I love solitary
life and I have no aptitude for the position that I am in.&quot; The Lord accepted
his petition and he departed in peace after the feast of Passover. He stayed
on the Chair one year, four months and twenty-eight days.
