 On this day also of the
year 44 A.M. (April 17th., 328 A.D.) the holy father Pope Alexander (Alexandros),
19th Pope of the See of St. Mark, departed. This Pope was born in the city
of Alexandria from Christian parents, and he grew up in serving the church.
Pope Maximus ordained him a reader, Pope Theonas ordained him a deacon.
Pope Peter (Petros the Seal of the Martyrs) ordained him a priest, and
he was virgin and chaste. When the time of Pope Petros (Peter) martyrdom
drew near, Alexander and father Archelaus, who became Patriarch before
him, went to him in prison, and asked him to lift the excommunication from
 Arius. Anba Petros excommunicated Arius again in their presence, and
informed them that the Lord Christ had appeared to him and ordered him
not to receive him again and that father Archelaus will be Patriarch after
him and after Abba Archelaus, Pope Alexander will be ordained. He commanded
that to the priests of Alexandria and ordered them not to accept Arius,
and to have no fellowship with him. When Pope Archelaus sat on the Chair
and received Arius, he only lived for six months and died. When Pope Alexandros
sat, the lay leaders came and asked him to receive Arius, but he refused
and added curses to what were already upon him. He told them: &quot;Pope Petros
had commanded Pope Archelaus and myself to do that, and when Pope Archelaus
had received Arius, God speedily removed him from his office.&quot;</p>
