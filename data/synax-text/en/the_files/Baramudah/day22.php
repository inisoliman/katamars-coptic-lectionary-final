 On this day the holy father Anba
Isaac (Ishaq) departed. He was born in the city of Hourin - Shabas, from
unblemished parents. His father's name was Abraham, and his mother's name
was Susannah. His mother departed when he was a child, and his father,
shortly after, married another wife. In those days there was a famine,
and his step-mother hated him. She only gave him a little bread, which
he gave to the shepherds that he worked with. He fasted until sunset, although
he was only five years old. When his father knew that, he went to see him
to inquire into that. Knowing the matter, before his father came to him,
he tied up three pieces of mud in his cloak, so that his father might think
when he saw them from far that they were bread. When his father came and
unrolled the cloak, he found three pieces of bread. The shepherds who were
present testified that the boy had given them all what he had of bread,
and others saw him tieing the pieces of mud in his cloak. His father marvelled
and glorified God. When Isaac grew up, he went and became a monk with a
righteous man whose name was Elias, and he lived with him for many years.
After the departure of Anba Elias, he went to the mount of Barnug and lived
with an old man whose name was Anba Zacharias. His father went about everywhere
trying to find him. When he found his son living with St. Zacharias, he
asked him to return with him. His teacher Anba Zacharias advised him to
obey his father and return with him. He returned and stayed until his father's
departure. He distributed all what his father left him to the poor and
needy. He then built for himself a place out side the city, where he dwelt
there alone. He went on asceticism and worship until he departed in peace.
They buried him in his place of worship, and the place was forgotten. After
many years, God willed to reveal his body, and a great light appeared above
his grave, which was seen by reapers for three consecutive days. The believers
came, took his body, laid it on a camel, and journeyed with it until they
came to a place between Horein and Nashrat. The camel stopped, knelt down,
and would not get up again. They knew that this was the Lord's Will and
they built a church for him in that place where they placed the body with
great honor.
