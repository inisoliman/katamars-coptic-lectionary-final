 On this day the holy father
Abba Silvanus the monk departed. This blessed man became a monk in the
monastery of St. Macarius, and he strove in every narrow path. He fasted
for long periods with prayers and many vigils in humility and love and
he became a great father. God had granted him to see Divine visions. He
commanded his disciples never to cease working with their hands, and to
give alms with what surpassed their needs. One day a lazy monk saw him
with his disciple absorbed in working with their hands, and he said to
them: &quot;Do not labor for the food which perishes&quot; for it is written: &quot;Mary
has chosen that good part, which will not be taken away from her.&quot; When
the old man Abba Silvanus heard that, he told his disciple: &quot;Give the father
a book, take him to the church to read, and shut the door on him without
leaving with him any thing to eat;&quot; and the disciple did as he was commanded.
When the ninth hour came the old man and his disciples ate and did not
invite the monk. During that time the monk was gazing with his eyes toward
the door waiting for someone to invite him to eat.</p>
