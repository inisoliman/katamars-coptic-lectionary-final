 When he became very hungry,
he left the church and asked the old man: &quot;Have the brethren eaten to day?&quot;
and St. Silvanus replied &quot;Yes&quot;. The monk asked: &quot;Why you did not call me
to eat with them?&quot; He replied: &quot;You are a spiritual man has no need for
food for the body. You have chosen the good part, but we are humans in
need of food for the body, for this reason we need the work of our hands.&quot;
The monk knew that he had transgressed with his words and he bowed before
the holy man asking for his forgiveness. The holy man told the monk: &quot;O
my son we need to work, for Mary needs Martha, and through Martha, Mary
was praised.&quot; Thus the monk was rebuked by the teaching of this father,
and he worked with his hands continually, and he gave alms with what remained
over. This father wrote many helpful discourses about the spiritual strife.
When he finished his strife in a good old age, God made him know the time
of his departure. He called the monks that were near by, he was blessed
by them, and he asked them to remember him in their prayers, then departed
in peace. 
