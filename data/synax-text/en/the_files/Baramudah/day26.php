 <p <?php echo $text_2; ?>>Departure of Pope Youannis VII, 78th
Patriarch</p>
<?php  if(file_exists("icons/Baramudah26-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baramudah26-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, of the
year 1009 A.M. (April 21st, 1293 A.D.), Pope Youannis VII, 78th Patriarch,
departed. After the lay leaders of Cairo had nominated Pope Gabriel III
for the Papacy, some of the lay leaders of Egypt agreed to choose Youannis
Ebn Abi-Saaid El-Soukary. They threw an altar lot which fell on Gabriel,
but Youannis, the above mentioned, along with his supporters, quarreled
with Gabriel. Youannis nullified the result of the lot and was enthroned
in the 6th. of Tubah 978 A.M. (January 15th., 1262 A.D.), after the departure
of Pope Athanasius III, his predecessor. He remained on the Patriarchal
Chair six years, nine months, and nineteen days, then he was dismissed.
Pope Gabriel took over his place from the 24th. of Babah 985 A.M. to the
6th. of Tubah 987 A.M., then he was dismissed. Youannis was reinstated
by the order of El-Sultan on the 7th. of Tubah. During Pope Youannis' days,
in the year 980 A.M., El-Sultan ordered to dig a huge pit and throw the
Christians in it, to be burned. He brought the Patriarch and mandated him
to pay fifty thousand Dinars, which took two years to collect. Consequently,
they released the Christians who suffered much tribulations in his time,
and the bishops suffered much afflictions. Pope Gabriel, his predecessor,
departed during Pope Youannis second period of heading the church, so he
was listed in the list of the Patriarchs before Youannis. Pope Youannis
remained on the Chair in his second time of heading the church 22 years,
3 months, and 19 days, and departed in peace in the 26th. of Baramudah
1009 A.M. He was buried in the gardens of El-Nastour monastery.
