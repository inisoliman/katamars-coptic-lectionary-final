 On this day, St. Sousenyos
was martyred. This Saint was the son of one of the friends of Emperor Diocletian.
The angel of the Lord appeared to him and strengthened his heart on receiving
the crown of martyrdom, and he kept this in his heart. The Emperor sent
him to the city of Nicomedia to restore the worship of idols. This Saint
sorrowed exceedingly. He sent and brought a priest who taught him the doctrine
of the church, the facts of the faith and baptized him. When his father
knew that, he accused him to the Emperor that he did not worship the idols.
The Emperor ordered to torture him with severe tortures, but the Lord strengthened
and comforted him. Finally, they cut off his head, and he received the
crown of martyrdom. The number of those who had seen him during his torture
and believed because of him, were eleven hundred and seventy. They were
