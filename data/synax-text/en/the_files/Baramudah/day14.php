 On this day, that coincides with the ninth
of April, 282 A.D., the holy father Anba Maximus, 15th Pope of Alexandria,
departed. This father was born in Alexandria from Christian parents who
raised and educated him well. He excelled in the Greek language. Then he
learned the doctrine of the church and was a man that feared God. Pope
Heraclas, 13th Pope, ordained him deacon on the church of Alexandria. Then
Pope Dionysius, 14th Pope, ordained him priest. Because of his advancement
in virtues and knowledge, the fathers the bishops chose him for the Episcopal
Chair after the departure of Pope Dionysius, and he was ordained
 on the twelfth of Hatur (November 9th., 264 A.D.). Shortly after his
enthronement, he received a letter from the council of Antioch, which included
the grounds for excommunicating Paul of Samosata and his followers. He
read it to the priests of Alexandria and issued a letter and sent it along
with the letter of the council to all the cities of Egypt, Ethiopia, and
Nuba. This was to warn them from the heresy of Paul of Samosata, which
was abolished by the death of this heretic. Pope Maximus fought and guarded
his flock, confirmed them in the faith with sermons and admonitions for
seventeen years and five days, then departed in peace.
