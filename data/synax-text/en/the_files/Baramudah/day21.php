<?php  if(file_exists("icons/Baramudah21-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baramudah21-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, St. Hierotheos
(Berutawos) of Athens, departed. This father was one of the learned men
in the city of Athens. He met the Apostle St. Paul, and many discussions
took place between them which led to his belief on the Apostle's hand.
He baptized him, taught him the Ordinances and Law of the church, and then
ordained him a priest for this city. He frequently visited St. Dionysius
the Areopagite, who was also one of the learned men in Athens. This Saint
was present at the time of the departure of the Lady Virgin Mary, and he
stood in the midst of the apostles and comforted them with spiritual songs
and hymns which he sang accompanied with musical instruments. He converted
many Jews and Gentiles to the knowledge of the Lord Christ. When the people
wished to ordain him a bishop, he refused saying: &quot;I just wish to be able
to perform the duties of a priest.&quot; Having finished his good strife, he
went to the Lord Whom he loved.
