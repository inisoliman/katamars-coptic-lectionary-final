 On this day, the ascetic father,
Abba Nofer the Anchorite, departed at a good old age, and of a glorious
memory, in the desert of Upper Egypt. The grace of God had moved St. Paphnoute
(Paphnutius), and he longed to see the servants of God, the Anchorites.
He saw many of them, among them St. Abba Nofer, and wrote their biographies.
He said that once he went into the desert and found a well of water and
a palm tree. Then he saw the saint coming to him, naked, and the hair of
his head and beard covered his body. When St.Paphnutius saw him, he was
afraid and thought that he was a spirit. Saint Abba Nofer encouraged him,
made the sign of the cross, and prayed the Lord's prayer, then said to
him, &quot;Welcome O Paphnoute.&quot; When he called him by his name, St. Paphnutius
calmed down. They prayed together, then sat, and talked about the greatness
and goodness of God. St. Paphnutius asked Abba Nofer to tell him about
his life and how he came to that place. Abba Nofer replied, &quot;I was in a
monastery wherein lived holy and righteous monks. I heard them talking
about the greatness of those anchorites who dwelled in the desert and their
good virtues. I said to them, 'Are there any who are better than you?'
They said to me, 'Yes, those anchorites who dwell in the wilderness. We
live near the world, if we are sorrowful or sad, we find someone to console
us; if we are sick, we find someone to visit and treat us; if we are naked,
we find someone to clothe us. Those who live in the wilderness lack all
these things.' When I heard that from them, my heart became anxious. &quot;When
the night came, I took a little bread and I went out from the monastery.
Then I prayed to the Lord Christ and asked Him to guide me to the place
where I was to live. The Lord facilitated my way and I found a holy and
righteous man. I dwelt with him, and he taught me all about the life and
the ways of the hermits and the anchorites. After I came to this place,
I found a palm tree, and a well. The tree bore twelve clusters of dates
each year. One cluster of dates is enough food for me for a month, and
I drink water from this well. I have lived here for sixty years during
which I have never seen the face of a man except yours.&quot; While they were
talking together the angel of the Lord came down, and told St. Abba Nofer
that his departure was near. Straightway, his color changed and became
like fire, then he bowed his knees and worshipped God. After he embraced
St. Paphnutius, he delivered up his pure soul. St.Paphnutius wrapped him,
and buried him in his cave. St. Paphnutius wished to live in the place
of Abba Nofer. But after he had buried him, the palm tree dried and fell
down and the water of the well dried up. That happened by the Will of God,
so St. Paphnoute would return to the world and tell us about the holy hermits
that he had seen.
