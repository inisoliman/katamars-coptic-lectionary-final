 <p <?php echo $text_2; ?>>Departure of Pope Yoannis the Eighth,
the 80th Patriarch</p>
<?php  if(file_exists("icons/Baunah4-5.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baunah4-5.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day
also, of the year 1036 A.M. (May 29th, 1320 A.D.) Pope Yoannis the Eighth
(80th Patriarch), departed. He was from Meniat Bani-Khosaim, and was known
as El Mo'ataman Ebn El-Kedees, and his name was Yohanna Ben-Ebsal. He became
a monk in the monastery of El-Shahran, and was ordained Patriarch on the
nineteenth of Amshir, 1016 A.M. (February 14th, 1300 A.D.). During his
days severe tribulations befell the Christians. They forced them to tinge
their turbans with the color blue. Churches were closed in old Cairo, Cairo,
and then in different parts of the country except the monasteries in Alexandria,
and some churches in other cities. An envoy from the king of Spain came
to intercede on behalf of the Christians. Two churches were opened, one
of them was the Coptic church of the Virgin Lady in Haret Zeewailah and
the other was the Malachite church of St.Nicholas in Elhamzawe. He was
a contemporary of the Saint Anba Barsouma known as El-Erian Ebn-Eltaban,
who departed during his days. The Patriarch prayed over him on the 5th
of Nasie 1021 A.M. This Patriarch was the last to reside in the church
of Abu-Saifain in Cairo. He was the first to relocate the patriarchal chair
to the church of the Virgin Lady in Haret Zeewailah. He was residing there
in the year 1303 A.D. when a severe earthquake took place that destroyed
a large part of Syria and Egypt. Ebn-kabre indicated that this Patriarch
had made some changes in the Liturgy. He departed after remaining on the
chair for twenty years, three months, and fifteen days and was buried in
the monastery of El-Shahran.  
</p><p <?php echo $text_4; ?>>May his prayers be with us and Glory be to God forever. Amen.</p> 
