 On this day, St. Sanusi (Shenousi), who was
from Balkim, was martyred. When he was a young man, he tended the sheep.
He used to give his food to the young shepherds, and spend his day fasting.
He visited the sick and those who were in prison. One night, the angel
of the Lord appeared to him in a vision and told him, &quot;Rise up, and go
before the governor and confess your God to receive the crown of martyrdom.&quot;
When he woke up from his sleep, he told that to his mother. She was sorry
and wept for she was unable to prevent him. He had heard about a righteous
holy woman, in the city of Shoubra, whose name was Mariam. She received
the poor and the sojourners and did many good deeds. He went to her, and
both agreed on receiving the crown of martyrdom. They went to Arsanos,
the governor, who was residing in a ship anchored on the bank of the river
Nile. They cried out before him saying, &quot;We are Christians.&quot; He ordered
that they be tortured. While they were torturing them, St. Mariam delivered
up her soul in the hand of the Lord. The Lord Christ comforted and strengthened
St. Sanusi. When the Governor failed to change his conviction, he sent
him with many others to the Governor of Ansena (Antinoe), who tortured
him severely. Then, he brought a sorcerer from Akhmeem, who gave the Saint
a drink mixed with poison. The Saint having made over it the sign of the
Cross, drank it, and no harm came to him. When the governor was tired of
torturing him, he ordered him put to death. They cut off his head with
the sword. The sorcerer believed when he saw that, so they cut off his
head also. Both received the crown of martyrdom.
