 On this day, the church celebrates the consecration
of the church of St. Cosmas (Kozman), Damian, their brothers, Anthimus,
Londius, and Abrabius and their mother Theodata. They were from one of
the Arab countries. Their mother feared God and was compassionate and merciful
towards strangers and the needy. She became a widow, while her children
were young. She raised them and taught them the fear of God. Cosmas and
Damian studied medicine, and they treated the sick freely. As for their
brothers, they went to the desert and became monks. When Diocletian renegaded
the faith and ordered the worship of idols, he was told that Cosmas and
Damian were preaching in the Name of the Lord Christ in every city and
urging others not to worship the idols. He commanded them brought and delivered
to the governor of the city, who tortured them with different kinds of
tortures. Then he asked them the whereabouts of their brothers. Upon finding
out, he brought the brothers and their mother. He ordered them to raise
incense for the idols, but they refused. Then he ordered the five to be
squeezed through the wheel.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 When they experienced no harm, he took them
out and cast them in red-hot fire for three days and three nights then
cast them in a hot steaming room. Finally, he placed them on red-hot iron
beds. Through all this, the Lord strengthened and healed them. When the
governor became weary of torturing them, he sent them to the Emperor who
also tortured them. Their mother constantly encouraged them and comforted
them. The Emperor rebuked her, and she cursed him in his presence and also
cursed his idols. He ordered her head cut off, and she received the crown
of martyrdom. Her body remained on the ground, no one dared to bury it,
because of their fear of the Emperor. St. Cosmas screamed at those present
saying, &quot;Men of the city, is there not one merciful person among you who
will cover the body of this poor old widow and bury her?&quot; Straightway,
Victor, Ebn-Romanus, came forward and took the body, shrouded it, then
buried it. When the Emperor heard what Victor had done, he ordered him
to be exiled to Egypt where he received the crown of martyrdom. The next
day, the Emperor ordered the beheading of Sts.Cosmas, Damian, and their
brothers. They received the crown of life in the Kingdom of Heaven. After
the time of persecution was over, many churches were built for them, where
God manifested many signs and wonders.
