 Empress Theodora, she sent
a letter to the church in Alexandria to ask about the legitimacy of the
ordination of Pope Theodosius, for if it was according to the canon of
the church he should be reinstated on his chair. A council of lay people
and one hundred twenty priests convened and unanimously agreed that Theodosius
was ordained with the consent of the bishops and the people and according
to the canons of the church. Acacius was present in this council; he rose
up confessing that he had transgressed. He asked for forgiveness and to
remain as archdeacon as he was before. They sent these facts to the Empress.
Since the Emperor was in agreement with the faith of the council of Chalcedon,
he wanted to attract the Pope to this erroneous faith. He wrote to his
representative in Alexandria saying, &quot;If the Patriarch Theodosius agreed
with us in faith, along with his papacy, add the governorship of the city
of Alexandria, but if he did not agree, he should be expelled from the
city.&quot; When the Patriarch heard that, he said, &quot;That what the devil had
told the Lord Christ after he showed him all the kingdoms of the world
and their glory, 'All these things will I give you, if you will fall down
and worship me'&quot;. The Patriarch then left the city and went to Upper Egypt
and stayed there confirming the believers.</p>
