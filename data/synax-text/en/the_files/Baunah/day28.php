 On this day, of the year
283 A.M. (June 22nd, 567 A.D.) St. Theodosius, the thirty-third Pope of
Alexandria, departed. After the departure of Pope Timothy, the bishops
and the Orthodox Christians gathered and ordained this father a patriarch.
He was a learned man, and well rehearsed in the church books. Soon after,
the enemy of the good enticed some evil men from the city of Alexandria,
to take Acacius, Archdeacon of the churches of the city of Alexandria,
and appoint him a patriarch. That happened with the help of Julian, who
was excommunicated by Pope Timothy for his approval of the council of Chalcedon.
When they appointed Acacius, they exiled Pope Theodosius to the city of
Germanos. St. Severus, the Antiochian Patriarch, who was residing in Sakha,
in the Egyptian land, comforted and strengthened him. He reminded him of
the tribulation that came upon the apostles, and John Chrysostom (of the
golden mouth). Six month after the exile of Pope Theodosius, he went to
the city of Malig, and dwelt there for two years. Afterwards, the people
of the city of Alexandria went to the governor and demanded from him the
return of their legitimate shepherd, and the expulsion of Acacius the Fraudulent.
When the news reached Emperor Justinian and the God-loving</p>
