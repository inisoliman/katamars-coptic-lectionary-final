 Later on, the Emperor
called St. Theodosius to Constantinople, so he went with some of the learned
priests. The Emperor received him with great honor, and seated him in a
distinguished place. He tried to flatter him, and talk gently to him, to
persuade him to agree on the faith of the council of Chalcedon. When he
did not yield, he exiled him to Upper Egypt, and appointed in his place
a person called Paul. When this Paul arrived to Alexandria, its people
did not receive him. He remained there for a year and only few followed
him. When the Emperor heard of this, he commanded to shut the churches
until the people submitted to the patriarch he appointed. The believers
built a church in the name of St. Mark and another on the name of Sts.
Cosmas and Damian outside the city where they were able to receive the
Holy Mysteries and baptize their children. When the Emperor heard that,
he had the churches opened. Pope Theodosius, when he heard this, feared
that the Emperor might have intended to lure the people by that act. He
wrote a letter to the believers to confirm them in the Orthodox faith and
to warn them from the deception of this infidel. He lived four years in
Alexandria, and remained in exile in Upper Egypt for twenty-eight years.
He spent thirty-one years, four months, and fifteen days in the patriarchate.
This Pope wrote many discourses and useful teachings.
