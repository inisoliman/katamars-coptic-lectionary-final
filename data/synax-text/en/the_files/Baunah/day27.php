 On this day, St. Ananias, the
apostle, departed. The apostles ordained this saint bishop for the city
of Damascus. He preached therein with the life-giving gospel, as he preached
also in the city of Beth-Gabriel and converted many of its people to the
faith, and baptized them and their children. St. Ananias was the one to
baptize the apostle Paul when the Lord sent him to him. When he baptized
St. Paul, something like scales fell from his eyes, and he received his
sight at once. God wrought many great miracles by his hands; and many of
the Jews and Gentiles believed through his preaching. Afterwards, Lucianus
the governor seized St. Ananias, and tortured him with sever tortures,
such as burning his sides with fiery torches. Finally, Lucianus took him
outside the city, and commanded him stoned until St. Ananias delivered
up his pure soul in the hand of the Lord.
