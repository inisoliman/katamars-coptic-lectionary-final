 On this day also, St. Thomas of
Shentalet (Sandalat) was martyred. Michael, the angel of the Lord, appeared
to this Saint when he was twenty-one years old, while he was sleeping in
the field tending the pigs. The angel Michael commanded him to go and confess
the Lord Christ. St.Thomas went to Alexandria and confessed his faith before
the governor who tortured him with different kinds of tortures. There were
with him under the torture St. Babnuda, of the city of El-Bandara, and
Anba Shenousy, from the city of Balkim, and they encouraged each other
to endure. After many tortures, the governor sent St. Thomas to Arianus,
the governor of Ansena, where he was beheaded and received the crown of
martyrdom. There were seven hundred men and nine women martyred during
his days.
