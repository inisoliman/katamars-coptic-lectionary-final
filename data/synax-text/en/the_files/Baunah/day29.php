 On this day, the seven ascetic saints in Tounar Mount
(Tona), were martyred. These were: Basadi, Cotolus, Ardama, Moses, Esey,
Parkalas (Mikalas), and a monk called Cotolus. The angel of the Lord had
appeared to Sts. Basadi and Cotolus and commanded them to confess the name
of the Lord Christ. They rose up straightway to go to the governor. They
met the five saints embarking a ship going to the governor to also confess
the Lord Christ. They all agreed together on receiving the crown of martyrdom.
They went to the governor and confessed the Lord Christ. He tortured them
excessively, then hung stones from their necks, and shut them up in prison.
The Lord appeared to them, comforted, strengthened, and promised them the
kingdom. The governor then sent them to Alexandria, where they were tortured
severely. He threw them into cauldrons full of sulphur and pitch, and lighted
a great fire under them, then he took them out and threw them away. The
Lord sent His angel who healed them. They came back to the governor and
confessed the Lord Christ before him. One hundred thirty persons witnessed
that. They confessed the Lord Christ, were martyred, and they received
the crown of martyrdom. The Governor intensified the torture on the seven
saints, and finally cut off their heads with the sword, and they received
the crown of martyrdom.
