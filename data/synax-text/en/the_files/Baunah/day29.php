 <p <?php echo $text_2; ?>>Martyrdom of Saints Abba Hour and his
Mother Theodora</p>
<?php  if(file_exists("icons/Baunah29-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baunah29-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also, Sts. Abba Hour and his mother
Theodora, were martyred. Abba Hour was a soldier in the army of Antioch.
He came to Alexandria, and confessed the Lord Christ before its governor.
He commanded that Abba Hour's hands be cut off, that he be tied to the
tail of an ox and dragged through the city. Then he was thrown into a pit
filled with snakes which did not harm him. During all that torture, he
cried out to the Lord Christ, who healed and strengthened him. His mother
came to see him and she rejoiced in his strife. They told the governor
about her, and he had her brought to him. He asked her to sacrifice to
the idols but when she refused he became enraged at her, and frightened
her but she was not afraid of his raging. He commanded to put red-hot iron
rods in her sides. When they did so she rejoiced and sang hymns to venerate
the Lord for He made her worthy to suffer for His Holy Name. Later on she
delivered up her soul and received the crown of martyrdom. As for St. Abba
Hour (Hor), they placed him in a cauldron of boiling oil and tar, and he
praised God until he delivered up his soul and received the crown of martyrdom.
His brother Abba Bishai (Pishai) was martyred on the first day of Nasie
(Intercalary days).
