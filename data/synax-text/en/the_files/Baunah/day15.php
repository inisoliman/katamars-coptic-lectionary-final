 On this day also, is the commemoration
     of the appearance of the body of the honorable saint, and great martyr
     Mari Mina, and the consecration of his church at Maryut (Mareotis). Now,
     the body of this saint was hidden, and the Lord wished to reveal it. It
     came to pass that there was a shepherd, who pastured his sheep near the
     place where the body of the saint was buried. One day, one of his sheep,
     which was sick of a skin disease (mangy), dipped itself in the water of
     a pond which was near that place. It then went out of the water, and rolled
     itself in the sand of that place, and it was healed straightway. When the
     shepherd saw this wonder, he marvelled, and took the sand of that place
     and mixed it with the water of the pond. He smeared every mangy sheep,
     or any that had a deformity, and they were healed immediately. The report
     of this shepherd became widespread in all the regions of the empire, until
     the emperor of Constantinople heard of it. He had an only daughter who
     was leprous. Her father sent her there. She questioned the shepherd about
     how she could get rid of her illness, and he told her. She took some of
     that sand and mixed it with the water. She retired to her quarters and
     smeared her body with the mixture and slept that night in that place. She
     saw in a dream St. Mina and he told her, &quot;Rise up early and dig in this
     place and you shall find my body.&quot; When she woke up from her sleep, she
     found herself healed. She dug in that place, and she found the holy body.
     She sent to her father to inform him about what had happened. He rejoiced
     exceedingly, thanked God and praised His Holy Name. He sent men and money
     and built a church in that place which was consecrated on this day. When
     Arcadius and Honorius reigned they ordered a city to be built there which
     was called Maryut. The masses came to this church interceding with the
     blessed Mari Mina. God had honored him by the miracles and wonders that
     were manifested from his pure body, until the Moslems occupied the city
     and destroyed it. The biography of this saint is mentioned under the fifteenth
     day of Hatur.
