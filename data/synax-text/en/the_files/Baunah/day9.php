  On this day also, St. Lucilianus
and four others with him, were martyred. He was a priest for the idols
during the reign of Emperor Aurelianus Caesar. He witnessed the torturing
of the martyrs, their beating, burning, and being hacked to pieces. He
also witnessed many being thrown into the fire without being harmed. He
marvelled and realized that his idols did not posses the power to do likewise
and the God that does these signs is the true God. Straightway, he cried
saying, &quot;I am Christian, I am Christian.&quot; They seized him, and brought
him before the Emperor who rebuked him for that. He promised him many gifts,
then threatened him. Since he did not return from his firm intention, he
tortured him severely then cast him into prison. Then the Emperor brought
him again with the other four Christians and threw them into the fire.
God sent heavy rain and it quenched the fire. Finally, they hung him upon
a wooden cross and nailed his body with long nails. Thus he delivered up
his soul in the hand of the Lord. As for the other four, they cut off their
heads and they all received the crown of martyrdom.</p>
