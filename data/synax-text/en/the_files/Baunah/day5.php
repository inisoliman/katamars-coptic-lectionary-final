 The Emperor went on to fight his
     enemies. When the two armies faced each other, the Lord forsake him, so
     he was defeated before his enemies. They pursued him until he came to a
     certain village to which they set fire. Its people escaped, but he and
     some of his men remained and they were burned. Those of his soldiers who
     returned to the city of Constantinia told the believers what had happened.
     Thus the prophecy of the holy man was fulfilled. The believers assembled,
     and brought him out of prison with great honor. The Arians knew that the
     divine grace and the spirit of prophecy dwelt in him, as they believed
     in the accuracy of his faith. Many turned from their error, confessing
     that the Son of God is equal with the Father in essence. This saint spent
     the rest of the days of his life in devotion to the ascetic life, and in
     fighting the spiritual fight until he departed in peace.
