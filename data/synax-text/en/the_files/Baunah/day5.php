 On this day, St. James of the East (Oriental),
     the confessor, departed. He lived and worshipped in one of the monasteries
     of the East. He was a contemporary of Emperor Constantine the Great, Julian
     the Infidel, and Jovianus the Believer. When the latter was killed, Valens,
     his brother, reigned in his stead. He was an arian and he closed the Orthodox
     churches and allowed the Arians to open their churches. The grace of God
     moved this Saint and he went to the city of Constantinia. He met the Emperor
     on his way to war. He stood before the Emperor and said, &quot;I ask you to
     open the churches of the believers, that they may pray for you, so may
     God make you victorious against your enemies, otherwise God will forsake
     you and you will be defeated before your enemies.&quot; The Emperor became angry
     at what St. James said and commanded to beat and imprison him. The Saint
     told him; &quot;Know that you shall be defeated before your enemies, and you
     shall die by burning.&quot; The Emperor became enraged and ordered to keep him
     under guard until he should return from war. The Saint told him, &quot;If you
     return safely, then God has not spoken by my mouth.&quot;</p>
