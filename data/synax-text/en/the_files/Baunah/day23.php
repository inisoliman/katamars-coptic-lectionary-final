The holy father Abba Noub
returned from the five cities (Pentapolis) and lived in mount Beshla (Sebla)
near his hometown. The envoy of the Emperor met Abba Noub, and took him
with him to Ansena. There he met the Christians and the bishops who ordained
him a priest. While he was consecrating the Offering and as he said, &quot;Hollies
for the Holy,&quot; he saw the Lord Christ, to Him is the Glory, in His heavenly
splendor, in the altar forgiving the sins of the people who were repentant.
The envoy traveled back to the Emperor along with the holy fathers who
were seventy two in number. Every two of them rode a chariot. They passed
by a city, where there were convents for the virgins. Seven hundred virgins
went out to meet them with songs and hymns and they sang to them until
they were out of their sight. When the holy fathers arrived and came before
the Emperor, he asked them to change their clothes with new ones, but they
refused. He was blessed by them, kissed their wounds and honored them.
He offered them money, but they refused to take any except what the churches
needed for vestments and vessels. The Emperor then embraced them and bid
them farewell, and they returned to their countries. St. Abba Noub went
back to his monastery and when he finished his strife he departed in peace.
