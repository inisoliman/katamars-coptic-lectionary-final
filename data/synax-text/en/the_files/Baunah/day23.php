On this day, the holy and
pure father Abba Noub the confessor, departed. This Saint was a devoted
monk in one of the monasteries of Upper Egypt. That was during the time
of Diocletian, who tortured the martyrs severely and shed their blood.
One day, someone mentioned the name of the saint Abba Noub before Arianus,
governor of Ansena. Arianus brought him and asked him to worship the idols.
The Saint replied, &quot;How can I abandon my Lord Jesus Christ and worship
the idols that are made of stones?&quot; Arianus tortured Abba Noub much then
exiled him to the five western cities (Pentapolis). Abba Noub stayed in
prison there for seven years, until God had perished Diocletian. When the
righteous emperor Constantine reigned, he ordered the release of all those
who were in prison for the Name of Christ. Constantine also asked that
they be brought to him, so that he might be blessed by them, especially
the honored ones as Zacharia El-Ahnasy, Maximus El-Fayyumy, Agabius from
the city of Dakhnin, and Abba Noub from the city of Balaos. The envoy of
the Emperor went to all the countries releasing the prisoners, who left
singing and praising God.</p>
