 The Emperor brought St. Claudius and proposed to
him the worship of the idols, and promised to give him his father's position.
Claudius neither accepted his promise, nor submitted to his order. He spoke
to him boldly and fearlessly reviling him for worshipping the idols. The
Emperor did not dare to harm him for the people of Antioch loved him. Romanus,
St. Victor's father, advised the Emperor to send him to Egypt to be killed
there. He sent him with a letter to the Governor of Ansena (Antinoe) stating
in it: &quot;Claudius neither obeyed our orders, nor hearkened our words. Persuade
him with all your power first, and if he does not return on his counsel,
cut off his head.&quot; When the Saint heard that, he called Sidrakhos, his
sister's husband, asked him to care for his sister, his possessions and
bid him farewell. The Saint went with the soldiers to Egypt. When he arrived
to Arianus, the governor of Ansena, he received him standing, kissed his
hand, and said, &quot;O my master Claudius, do not transgress the command of
the Emperor.&quot; The Saint replied, &quot;I was not sent to you for you to lead
me astray by your words, but that you might fulfil what the emperor commanded.&quot;
They argued with each other till Arianus became enraged with the answers
of the Saint, and he drove the spear into the Saint. He delivered up his
pure spirit and received the crown of martyrdom. Some of the believers,
took his body and shrouded it. They placed it with the body of St. Victor
who was martyred shortly before that. After the end of the time of persecution,
Victor's mother came, and took their bodies to Antioch.
