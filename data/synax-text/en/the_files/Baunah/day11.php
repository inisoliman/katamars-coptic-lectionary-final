 On this day, the honorable St. Claudius, was
martyred. He was the son of Ptolemy (Abtelmawos), who was Emperor Numerianus'
brother. He was loved by the people of Antioch for his courage and good
appearance. Because they loved him so greatly, they painted a picture of
him on the doors of the city of Antioch. When Diocletian reneged the faith
and incited the persecution against the Christians, this Saint agreed with
St. Boctor (Victor) Ebn Romanus to be martyred for the sake of the Name
of Christ. Satan appeared to them in the form of an old man and told them,
&quot;O my sons, you are young men, the sons of nobility, and I am afraid for
you from this infidel Emperor; so if he asked you to worship the idols,
accept his command, and in your houses you can worship Christ in secret.&quot;
They realized that he was satan disguised as an old man and told him, &quot;O
you who are filled with all evil, go away from us.&quot; Straightway the old
man changed his appearance and became like a black slave and told them,
&quot;Behold, I will go before you to the Emperor and instigate him to shed
your blood.&quot;</p>
