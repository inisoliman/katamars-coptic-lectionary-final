 On this day, of the year 2570
of the world, the great prophet Joshua Son of Nun, departed. He was born,
in the year 2460 of the world, in Egypt (Fifty three years before the deliverance
of the people of Israel from the bondage of Pharaoh). He was a disciple
and servant to Moses. Moses, after leading the people of Israel out of
Egypt with the might of the Divine arm and the extraordinary wonders, brought
them to the nearby mount of Sinai. He went up the mount taking with him
Joshua, his minister, to receive the commandments. During the war of Israel
against Am-a-lek, Joshua was the leader of the soldiers. When Moses chose
twelve men to spy out the promised land, one from each tribe, Joshua was
one of them. He completed this mission with honesty. He and Caleb alone
brought forth the true and accurate information about the promised land.
Therefore they alone entered this land without the people of Israel that
came out of the land of Egypt. Because they had murmured and doubted in
the sincerity of the promises of God, God swore in His anger that they
would not enter to His rest. Their children that they begot after their
deliverance from Egypt, entered this land along with Joshua and Caleb.</p>
