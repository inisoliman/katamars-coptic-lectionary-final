 Many spiritual signs appeared
before, during, and after the apparition of the Virgin the mother of the
Lord's transfiguration. The appearance of tongues of yellowish flame would
flash over the church and then subside and that repeated several times.
Another form of the signs were the spiritual beings formed like doves,
larger than the doves that we know, appear about midnight or after, flying
in the middle of darkness illuminating in a fast speed, appeared suddenly
from no where, and also disappeared suddenly. These spiritual beings appeared
in different formations and in varying numbers. A fact we should be aware
of that pigeons do not fly during the night. Another sign was the shooting
stars which were constantly falling and were seen very close to the apparition
on many occasions as if coming down to glorify her from heaven. Another
sign was the fragrance of incense. The smoke of the incense poured out
of the domes in large quantities. Substance resembling clouds, thick fog
or smoke would roll in toward the church and completely cover the church.
Also the illuminated cloud that appeared over the domes of the church in
large volume and often proceeded the transfiguration of the Virgin or at
times the cloud slowly formed in the shape of the virgin. Sometimes the
apparition of the Virgin would appear from the clouds. This transfiguration
and all the spiritual signs were a forerunner and announcement for serious
or important events to come in the near and far future. Or it might be
a spiritual gesture from heaven to indicate the Lord's caring for His church
and His people and our country.  
