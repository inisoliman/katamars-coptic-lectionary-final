 On this day also of the
year 668 A.M. (May 20th. 952 A.D.) St. Macarius the fifty ninth Pope of
Alexandria, departed. He was born in the city of Shoubra. He rejected the
world since his youth and he desired the monastic life. He went to the
monastery of St. Macarius at the wilderness of Sheahat (Scetis). He lived
in virtues and good conduct made him worthy to be chosen a Patriarch, and
a successor for Pope Cosma. He was enthroned on the first of Baramouda
648 A.M. (March 27th. 932 A.D.). When he went forth from Alexandria going
to visit the monasteries in the desert of Scetis according to the custom
of his predecessors, he passed by his home town to visit his mother who
was a righteous woman. When his mother heard that he had arrived she did
not go out to meet him. When he had come to the house, he found her sitting
down weaving and she did not greet him or paid attention to him. He thought
that she did not know him. He told her: &quot;Don't you know that I am your
son Macarius who was elevated to a great position and became a head for
a great nation?&quot; She answered him with tears in her eyes: &quot;I did not ignore
you and I know what became of you, but I would have rather seen you dead
than seen you as a Patriarch. Before, you were responsible only for your
own soul but now your are responsible about the souls of all your flock:
Now remember you are in danger and it is difficult to escape it.&quot; She said
that and went on weaving as she did before. The father the Patriarch left
her sad, and attended to his office with delegant and care. He instructed
his people with preaching and sermons. He did not touch any of the church
revenue, and did not lay his hand on any one without people consent. He
commanded the bishops and the priests to watch their flock and to protect
them with homilies and admonitions. He sat on the throne of St. Mark twenty
years in peace and tranquility, then departed in peace.
