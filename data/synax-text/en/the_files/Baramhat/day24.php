 Since that night the pure
Virgin had transfigured in different spiritual views in front of thousands
and ten of thousands of masses, Egyptian and foreigners, Christians and
non-christians, men, women and children. Spiritual beings formed like doves
would appear before, during and after the transfiguration zooming through
the sky in a way raising the human from a materialistic to a heavenly atmosphere.
This transfiguration was in different forms. One of the most significant
ways this apparition took place was that; the head of St. Mary under the
vail looking down as in the picture of the sad Virgin and she was looking
toward the Cross and that view would stay like this at times or slowly
bow before the Cross at other times. The Cross itself will shine and illuminate
although it was made of concrete. And some times an angel would appear
standing behind her spreading his wings. That view might stay as long as
many hours. Another view was the view of the Mother of Light standing as
a great Queen in a beautiful spiritual portrait radiating dignity, elegance
and beauty. On her head was a crown of a queen as if it were made of diamonds
and some times there appeared on the top of the crown a small luminous
cross. And some times she appeared in the same way but carrying Christ,
to Him is the Glory, in the form of a child on her hand and on His head
a crown. And on other times she raised her both hands as She was blessing
the world moving to the right, to the front, and to the left in a dignified
way.</p>
