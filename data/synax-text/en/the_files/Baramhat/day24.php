 On the eve of this day of the
year 1684 A.M. which coincide with tuesday the 2nd. of April 1968 A.D.,
during the papacy of Pope Kyrellos VI, the hundred sixteenth Pope of Alexandria,
our Lady and the pride of our faith started to transfigure in luminous
spiritual forms in and around the domes of the church dedicated to her
immaculate name in Zeiton, a suburb of Cairo. This transfiguration continued
in following nights in a manner that was never known in the East or the
West. This transfiguration in some nights was as long as many hours, without
stop, in front of tens of thousands of people from every race and religion,
with every one seeing her, pointing at her and interceding to her with
songs, hymns, tears, prayers and hails and She was looking to them in a
compassionate way raising her hand at times to bless them in all directions.
The first one to notice this transfiguration was the workmen at the garage
of the Public Transit System which was across the street from the church.
The watchman Abdel-Aziz Aly, who was in charge of guarding the garage at
that night, saw a luminous body over the dome of the church. He started
shouting: &quot;light over the dome&quot; and he called the other workers in the
garage. They all came and saw the bright light over the large dome of the
church. When they looked closely, they saw a young lady in white, kneeling
by the cross at the top of the dome. Because the dome had a round, smooth,
and very sloping surface, it held the men as though they were nailed in
their places watching the fate of the lady. Few seconds passed then they
saw the kneeling lady as she stood over the dome. They gave out a cry of
fear that she might fall down. They thought she was a girl in despair trying
to commit suicide and they cried warning that person not to jump down and
some of them called the police. The pedestrians, men and women started
to gather around. The view of the lady was getting more clear and she appeared
as a beautiful girl in a bright gown of light and had branches of olive
tree in her hand, and around her flew white doves. Then they realized that
they were seeing a heavenly spiritual view. They directed flood light to
the luminous picture to remove all doubt from their minds, but instead
it became more clear and bright. They cut the electricity off all the area
but the lady remained in her heavenly illumination and her bright gown
of light became more clear. She started moving around in a circle of light
radiating from her body to all the directions around her. All the people
then realized that this lady in front of them, without no doubt is the
Virgin Mary. They started to shout and cry saying: &quot;She is the Virgin ...
She is the Mother of Light ... &quot; They prayed with songs, hymns and hails
all the night until the next morning.</p>
