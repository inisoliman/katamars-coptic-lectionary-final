 On this day also is the commemoration of Anba Sarapamon,
known as &quot;The Veiled&quot; Bishop of El-Monofia. This blessed and great Saint
was contemporary of Pope Petros El-Gawly and one of his famous bishops.
God had granted him the gift to heal the sick, and to cast out evil spirits.
He was called Salib. When he was a young man, some evil women seized him
and accused him of murdering a young man they had killed in the market.
In the court, he lifted up his heart to God and with tears he asked the
help of St. Mary and other saints. He looked to the slain person and asked
him to confess before the judge who killed him. The slain person rose up
and told the judge about the murderesses. The judge was astonished and
set Salib free. Salib left the court and went immediately to St. Antonios
monastery to become a monk, and later on, the Pope chose him a Bishop for
El-Monofia. When Mohammed Ali Basha asked the Pope's help concerning his
daughter Zahra Hanem who was possessed by evil spirit, he sent Anba Sarapamon
who healed her by praying over her. Mohammed Ali offered him money, but
he refused saying that God's gifts are free. When the Governor insisted
he asked for supplies and clothes for the monks in the monasteries, and
to reinstate the Copts to their jobs in the government.
