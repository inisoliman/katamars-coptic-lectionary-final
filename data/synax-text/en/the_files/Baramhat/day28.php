 On this day of the year 53 A.M. (337 A.D.) the righteous
Emperor Constantine the great departed. His father's name was Constantius
I Chlorus which means (Green), and his mother's name was Helena. Constantius
reigned over Byzantium, Maximianus reigned over Rome, and Diocletian reigned
over Antioch and Egypt. Constantius was pagan, but he was honorable, loved
to do good, compassionate and merciful. He went to the city of El-Ruha
(Urfa - Gr. Edessa) and there he saw Helena, liked her and he married her.
She was a Christian, and she conceived Constantine. Constantius left her
in El-Ruha and returned to Byzantium. She brought forth Constantine and
raised him up very piously, taught him every kind of learning, sowed in
his heart mercy and compassion for the Christians, but she did not dare
to have him baptized. Constantine grew up, and he was a bold and skilful
horseman. He went to his father who rejoiced in him when he saw that he
was full of wisdom, knowledge, and he was a skilful horseman. After his
father's death he received the kingdom and he reigned with justice and
integrity, and stopped all unfair practices. All the people were subject
to him and they loved him and his righteous judgement spread throughout
the Empire. The nobles of Rome sent asking him to come and save them from
the injustice of Maximianus. Constantine marched with his army toward Rome
to save them.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 During the war he saw in the heaven, in the middle
of the day, a Cross made of stars, and on it was written in Greek words
which being interpreted as &quot;With this you shall conquer.&quot; The light of
the Cross was more shinning than the sun, and he shewed it to his ministers
and the nobles of his kingdom. They read what was written, marvelled and
they did not know for what reason that cross had appeared. That night the
angel of the Lord appeared to him in a vision and told him: &quot;Make a sign
for yourself like that sign which you had seen, and with it you shall conquer
your enemies.&quot; The next morning, he prepared a large flag with the sign
of the cross on it, and made the sign of the cross on all the armaments.
He engaged with Maximianus in a battle and fought. Constantine overcame
Maximianus who withdrew with his army, and while crossing the bridge over
the Tiber river, the bridge broke and he and most of his men perished.
Constantine entered Rome and its people welcomed him with joy and gladness,
and its learned men praised the Honorable Cross and called it the Savior
of their city. Then they celebrated for the Cross seven days and Constantine
became the Emperor of the East and the West. When Constantine established
himself in Rome, he and most of his soldiers were baptized by the Pope
of Rome, in the eleventh year of his reign, which is the fourth year after
the appearance of the Honorable Cross. He sent throughout the kingdom and
commanded to set free all those who were imprisoned for the sake of faith,
and that they should not work during the Passion week as the Apostles commanded.</p>
