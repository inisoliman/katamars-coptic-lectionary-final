 <p <?php echo $text_2; ?>>Departure of Pope Peter (Petros) VII,
the One Hundred and Ninth Patriarch</p>
<?php  if(file_exists("icons/Baramhat28-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baramhat28-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also of the year 1568 A.M. (April 5th.,
year 1852 A.D. the holy father Pope Peter (Petros) VII, the 109th. Pope
of Alexandria, departed. This father was born in the village of Gawli -
Manfalout, and his name was Mankarius. He forsake the world since his young
age, and the Divine grace led him to the monastery of the great St. Antonios
where he became a monk. He immersed in worship, asceticism and purity as
he occupied himself by reading the ecclesiastic books and learned the theological
and liturgical subjects. He was ordained priest for the monastery, he surpassed
his fellows in the practice of virtues and performing the religious duties,
and was called Fr. Marcurius. Then he was promoted to archpriest (Hegumen)
for his asceticism, zeal, and the purity of his heart. When his news reached
Pope Marcus (Mark) VIII, he called him. A group of the Ethiopians had come,
delegated from the king of Ethiopia asking for a Metropolitan instead of
Anba Yousab their predecessor one who had departed. The Pope searched for
an honorable, learned and just man, and he found these virtues in the Archpriest
Marcurius, so he chose him to be a Metropolitan for Ethiopia. During the
ordination, instead he ordained him a bishop without a parish and called
him Theophilus and ordained Anba Macarius II a Metropolitan for the kingdom
of Ethiopia in the year 1808 A.D.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 After ordaining Anba Theophilus a bishop at large
the Pope kept him with him in the patriarchate to help him in managing
the church business and the affairs of the Coptic people. When Pope Marcus
VIII departed on the 13th. day of Kiyahk year 526 A.M. (December 21st.,
year 1809), the bishops were present in Cairo met with the notables of
the people and unanimously agreed to chose Anba Theophilus to be his successor.
They ordained him Patriarch in St. Mark church in El-Azbakiah three days
after the departure of Pope Marcus, on sunday the 16th. of Kiyahk, year
1526 A.M. (December 24th., year 1809), and they called him Peter VIII and
he was known by Petros El-Gawly. He was a gentle, meek, wise, greatly intelligent,
outstandingly smart father with a nobel policy in caring for the people.
He devoted himself to studying, reading and learning the ecclesiastic subjects
and the holy books. He wrote a valuable text to defend the church and its
teachings, and he provided the patriarchal library with valuable and rare
texts. His era was a peaceful time in the land, so the church had a complete
serenity and total freedom in worship, and the churches were renovated
in Upper and Lower Egypt.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 During his Papacy the Chair of El-Nuba and Sudan
returned to the Chair of Alexandria after separation for five hundred years.
The governor of Egypt Muhammad Ali Basha conquered Sudan and took over
its land and consolidated it to the land of Egypt. Many of the people of
Sudan returned to the Christian faith and many of the christian government
employees and army men lived in Sudan. They built churches, then they asked
Pope Petros to send them a bishop to shepherd the Christian people in these
countries. He ordained for them a bishop who was nominated by the people
of Sudan from among the monks called Damianus. This bishop departed during
the days of Pope Petros so he ordained for them another. This Pope, during
his papacy, ordained twenty five bishops for the different parishes of
Egypt and Nuba, and he ordained two Metropolitans For Ethiopia, the first
was Anba Kyrellos IV in the year 1820, and the second in the year 1833
A.D. God had performed many wonders through the hands of Pope Peter VII
the most famous of them is the incident of the Nile Inundation. One year
the flood of the Nile was not enough to water people, land and animals.
The masses were worried about famine, inflation and high prices if the
land could not be cultivated. They went to the Governor of Egypt asking
to order the clergy to pray and supplicate God almighty that He might bless
the water of the Nile and increase the flood water to be able to water
the land to bring forth a plenteous crop and to avoid a famine that might
befall the people. Pope Peter VII called the bishops and the clergy and
went with them to the banks of the river where he celebrated the Divine
Liturgy and after the service he washed the Holy Service utensils with
water from the river, then he threw the water and the blessed Kourbana
(Blessed Bread) in the river. The waves of the river roared, the water
was disturbed and flooded, the deacons in haste removed all the elements
used in the celebration, fearing of drowning. This incident glorified the
Patriarch position before the Basha the Governor who made him close to
him, and honor the men of his nation, and increased their authority and
grace.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 From these remarkable wonders also was the incident
of the Holy Sepulcher light in Jerusalem. After prince Ibrahim Basha, Mohammed
Ali Basha's son, had conquered Jerusalem and Syria year 1832 A.D., he invited
Pope Peter VII to visit Jerusalem and attend to the service of the appearance
of the light on Bright Saturday from the Sepulcher of the Lord Christ in
Jerusalem as the Greek Orthodox Patriarchs did every year. The Pope accepted
the invitation, and when he arrived, he was received with honor and reverence and he entered Jerusalem
with a great procession and a splendid celebration, in which the governor,
the rulers and the heads of the different Christian denominations participated.
He realized with his wisdom that if he minister alone in the Holy sepulcher
that would cause animosity between the Copts and the Greeks. The Pope asked
the Basha to relieve him from this service, but he asked him to participate
with the Greek Patriarch on the condition that he will be their third,
for he doubted the authenticity of the light. On Bright Saturday the church
of the holy sepulcher was crowded with the worshipers, the Basha ordered
the people to evacuate the church to the spacious outer courtyard. When
the time to start the service came the two Patriarchs and the Basha entered
the Holy Sepulcher to pray the customary prayers. In the specific time,
the light burst out of the Sepulcher in a way that terrified the Basha,
who became in a daze and confusion, and the Pope attended to him until
he recovered. The people outside in the courtyard were not deprived from
the blessing of the light since one of the pillars of the western gate
of the church split and the light appeared to them from the pillar.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 This incident increased the reverence and respect
of the Pope before the Basha. His holiness the Pope made many repairs and
renovations in the church of Resurrection. During the days of this Pope,
Mohammed Ali Basha wanted to join the Coptic church with the church of
Rome because of the efforts of one of his catholic army generals, in return
of the services of the French scientists and army leaders who offered the
Governor to organize the Egyptian government. The Governor (Basha) called
the master Ghali and his son Basilius and presented the subject to them,
and they replied saying that this merge would cause revolt and unrest among the Coptic people so to avoid shedding of blood and to
encourage the topic of unity, his family and himself would join the Catholic
church, on a condition that they would not be forced to change their rituals
or Eastern custom. The Basha accepted that solution and accordingly they
declared their joining the Catholic faith, and only few followed them,
nevertheless they all continued to worship in Coptic churches. During his
time, the monk Daoud (David) excelled among the monks of St. Antonios monastery,
and was promoted to be the head of the monastery. The fruits of his effort
became obvious, in organizing the monastery and improving the condition
of the monks. Pope Peter chose him for his intelligence and good management
and sent him to Ethiopia in an official church duty which he
 took care of it well, and his return to Egypt was after the departure
of Pope Peter.</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 History will exalt the memory of Pope Peter (Petros),
because the Russian Caesar sent his delegates to offer putting the Coptic
Church under the protection of Caesar. The Pope refused the proposal graciously
by asking: &quot;Does your Caesar live forever?&quot; When the envoy answered that
he would die like all human beings, the Pope told him that he preferred
the protector of the church would be her true shepherd, the King that does
not die. The prince admired the Pope's faith and patriotism, and he left after taking the blessings from the Pope stating
that he is truly the good successor for the Eternal King, Christ the Savior.
When this Pope finished his course and completed his strife, he departed
in peace. They prayed over him in a great celebration on Paschal Monday,
participated in it all the heads of the Christian denominations in St.
Mark church in El-Azbakiah. He was buried beside his predecessor Pope Marcus,
and Anba Sarapamon bishop of El-Menofia in the eastern side of the great
cathedral in El-Azbakiah. He stayed on the Patriarchal Chair for 42 years,
3 month, and 12 days and the Chair remained vacant after him one year and
12 days.
