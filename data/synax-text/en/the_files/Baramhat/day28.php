 Then he sent his mother Helena to Jerusalem where
she discovered the Holy Cross of Our Lord Christ. In the seventeenth year
of his reign the Holy Council of the Three Hundred and Eighteen bishops
assembled at Nicea in the year 325 A.D. which arranged the affairs of the
Christians and put down the cannons of the church. He rebuilt the city
of Byzantium and called it after his name &quot;Constantinia&quot; and he brought
to it many of the bodies of the apostles and holy martyrs. He departed in the city of Nicomedia, they laid him in a gold sarcophagus,
carried him and brought him to Constantinia. The Patriarch, bishops, priests,
and all the people received him with prayers, psalms, and spiritual hymns,
and laid him in the sanctuary of the holy apostles. All the days of his
life were seventy five years.
