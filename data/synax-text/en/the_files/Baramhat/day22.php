  On this day of the year 386 A.D. the holy father Anba
Kyrellos (Cyril), Bishop of Jerusalem, departed. This father was chosen
in the year 348 A.D. as a successor for Anba Maximus, Bishop of Jerusalem,
for his knowledge and righteousness. He did not stay long on his Chair,
until a contention arose between him and Acacius Bishop of Caesarea about
who had the right to be in primacy over the other. Kyrellos argument in
that he was the successor of St. James, one of the Twelve Disciples. Anba
Kyrellos had sold some of the church vessels and distributed the money
on the needy because of a famine that befell the land of Palestine. Acacius
took this chance and made an effort to obtain an order to exile him from
the country. Anba Kyrellos was exiled without any one listening to his
case. In the year 359 A.D., he appealed his case before the council of
Seleucia. The council called Acacius to hear from him his argument, but
he did not attend, so they judged by removing him from his office, and
the return of Kyrellos to his Chair (Parish). He did not stay long for
Acacius went and enticed emperor Constans to assemble a council at Constantinople
and the Arian bishops agreed with him. This council convened in the year
360 A.D. and ordered to exile this saint once more. When Constans died,
and was succeeded by Julian who ordered the return of all the exiled bishops
to their chairs. This saint returned to his chair in the year 362 A.D.
and shepherded his people faithfully and honestly, but he resisted the
Arians. They went to emperor Valens the Arian who invalidated the order
of his predecessor Julian stating the return of the exiled bishops to their
chairs. This way St. Kyrellos was exiled for the third time, where he remained
until the death of Valens in the year 379 A.D. When Theodosius the great
reigned and assembled the one hundred fifty in a council against Macedonius
(The second universal council), this father attended, and opposed Macedonius,
Sabilius and other heretics. This Saint composed many Homilies and Exhortations,
exceedingly profitable, in the Doctrines of faith and old traditions then
departed in peace.
