 <p <?php echo $text_2; ?>>Martyrdom of St.Mary the Israelite</p>
<?php  if(file_exists("icons/Baramhat7-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baramhat7-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also St. Mary
the Israelite was martyred. This Saint did not know the Lord Christ and
she lived an evil life. When she wished to repent and to return to the
righteous life, the Lord sent to her a holy man who preached her, and revealed
to her the way of salvation by believing in the Lord Christ. He told her
that the soul has to give an answer about all her deeds on the day of Resurrection.
After death and departing of this world every one will be rewarded according
to his deeds and explained to her the fearful punishments for the evil
doers. She asked him: &quot;What are the proofs on what you said, since the
Torah that God gave to Moses the prophet and also my fathers did not mention
this? so confirm to me the truth of what you said with biblical and logical
proofs&quot;. After he explained and confirmed to her all these facts she became
convinced in her heart and mind. She asked him: &quot;If I repent on my evil
works would God accept me?&quot; He replied: &quot; If you believed that Christ had
come to the world for the salvation of the human race, and walked in the
way of repentance, God will accept you&quot; and she believed and repented.
When the Governor knew about her, he brought her before him. When she insisted
on her Christianity, he ordered her beheaded by the sword and she received
the crown of martyrdom.
