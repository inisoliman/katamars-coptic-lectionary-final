 On this day Sts. Philemon and Apollonius
were martyred. Philemon was the jester and singer, and Apollonius was the
musician for Arianus the governor of Ansena (Antinoe). They were very close
friends and they wished to receive the crown of martyrdom. One day, Philemon
went to the Governor and confessed the Lord Christ before him, so he ordered
to shoot him with arrows. After that, Apollonius came before the Governor
and he also confessed the Lord Christ. When the Governor recognized him
he became angry and ordered to shoot him also with arrows. While they were
shooting Apollonius, one of the arrows glanced back and struck the Governor's
eye and destroyed it. Sts. Philemon and Apollonius completed their strife
and received the crown of martyrdom.
