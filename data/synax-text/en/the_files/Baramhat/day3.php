 On this day also St. Porphyry (Porphorius) was martyred.
He was one of the most nobles of Banias, most charitable and caring for
the poor. He visited those in prison because of their debts and paid off
their obligations. When the era of persecution started, it was called in
every place to worship the idols. The Saint heard that the prince was passing
by, he stood in front of his house and shouted in his face, saying: &quot;I
am Christian.&quot; After many failed trials from the prince to dissuade him
on changing his faith, the prince ordered his neck to be cut off. The Saint
received the crown of life, and the people of his town took his body, and
shrouded it with expensive shrouds.
