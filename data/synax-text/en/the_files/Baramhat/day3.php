 On this day of the year 648 A.M. (27th of
February 932 A.D.) the blessed father Anba Cosmas, the Fifty-Eighth Pope
of Alexandria, departed. This father was righteous, pure, merciful, chaste,
and knowledgeable of the books of the church and in the interpretations
thereof. When he was chosen Patriarch, on the 4th of Baramhat 636 A.M.
(28th of February 920 A.D.), he shepherded his flock in the fear of God
and with wisdom. He distributed to the poor, the needy and to building
churches, all of the church revenue after the little he used. The evil
one, however, did not leave St. Cosmas without grief when he saw his pure
life. He ordained a Metropolitan for Ethiopia from the monks, whose name
was Peter, and sent him there. The king received him with great joy. A
short while later, the king fell sick and felt that his end was near, so
he brought his two sons and asked the Metropolitan to come to him. The
king took off his crown and handed it to the Metropolitan saying: &quot;I am
going to my Lord Christ and whomever you see fit from my sons to rule the
kingdom enthrone him.&quot;</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 When the King departed to the Lord, the Metropolitan
and the Cabinet saw that the younger son was more suitable for ruling the
kingdom, so they crowned him. Shortly afterwards, a monk from the monastery
of Anba Antonius called Victor and along with him a companion named Mina
came to Ethiopia. They asked the Metropolitan for money; but he refused
to give it to them. The devil enticed them to scheme against him. One of
them put on the garb of the bishops and the other one as his disciple.
They falsified a letter from the father, the Patriarch, to the nobles of
the government saying in it: &quot;We have been informed that a deceptive man
called Peter came to you claiming that we have sent him as a Metropolitan
for you and he is lying in that. The one who is carrying this massage to
you is the legitimate Metropolitan Mina. We have been informed also that
Peter has enthroned the younger son of the king instead of his older brother,
against the church and civic laws. On the arrival of this message, you
should exile both the Metropolitan and the king, consider Abba Mina the
carrier of our message to be your legitimate metropolitan and to allow
him to enthrone the older son a king.&quot;</p>
<?php echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";?>
 The two monks handed the forged letter to the older
son of the king. When he read the letter he gathered the cabinet and the
nobles of the government and read it to them. They ordered the exile of
Metropolitan Peter and seated Mina in his place. They then took away the
crown from the younger son and crowned his older brother. Nevertheless,
a dispute occurred between the false Metropolitan and his assistant, who
took the liberties of the absence of his Metropolitan and expelled the
servants, plundered all what he found, returned to Egypt, and became a
Moslem. When the news reached Pope Cosmas, he grieved exceedingly. He sent
a letter to Ethiopia excommunicating Mina the liar. The King of Ethiopia
was outraged from Mina's actions and slew him. He asked for the return
of Metropolitan Peter from his exile but found that he had departed to
his Lord and Savior. The father, the Patriarch, refused to ordain for them
another Metropolitan and so the four Patriarchs that followed him. The
days of this father were peaceful and tranquil, if not for this accident.
He occupied the throne of St. Mark for twelve years and departed in peace.
