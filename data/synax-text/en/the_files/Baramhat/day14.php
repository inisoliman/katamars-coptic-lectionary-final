 <p <?php echo $text_2; ?>>Martyrdom of St.Shenouda (Sinouti) El
Bahnasawy</p>
<?php  if(file_exists("icons/Baramhat14-2.jpg")){ echo "<p $text_3m > <img src=\"./icons/Baramhat14-2.jpg\" style=\"float:left;margin:10px; max-width:100px;\" alt=\"icon\" /><br /><br />"; } else {echo "<p $text_3>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; ";}?>
 On this day also St. Shenouda
(Sinouti) El Bahnasawy was martyred. Certain men laid accusations against
him before Maximianus, a governor appointed by Diocletian, that he was
Christian. The Governor brought him, and asked him about his faith, and
the Saint confessed his faith in the Lord Christ and that He was the True
God. He ordered the soldiers to throw him on the ground, to beat him with
hammers until his flesh was torn, and his blood flew on the ground, then
they casted him into a prison with repulsive odor. The Lord sent Michael
the Archangel to him, healed his wounds, encouraged and strengthened him.
He told him that he will receive the crown of glory after he had endured
what would befall him from severe tortures. On the next morning the
Governor ordered his soldiers to go and look at him, and they found him
standing up praying. When they told the Governor about him and when he
saw him whole and un-harmed, he was amazed and said: &quot;He is a sorcerer.&quot;
Then he ordered to crucify him with his head downwards, and to light fire
under him, but it did not harm him. They squeezed him with the wheel and
finally they beheaded him and hacked his body into pieces with swords and
casted him to the dogs which did not come near him. During the night the
believers took him and poured over him expensive perfumes, shrouded him
in costly wrappings, laid him in a coffin and buried him.
</p><p <?php echo $text_4; ?>>May his prayers be with us. Amen. .</p>
 
