 On this day of the year 959 A.M. (Marsh
10, 1243 A.D.) departed the holy father Anba Kyrellos, the seventy fifth
Pope of Alexandria, who was known as Ebn-Loqloq. This father was enthroned
on the twenty third of the month of Baunah, 951 A.M. (June 17th., 1235
A.D.). There were objections at first in choosing him but finally they
unanimously agreed on him. During the days of this father a holy council
convened, which was attended by all the bishops of the See of St. Mark,
and they put down a comprehensive cannons for the church. The honorable
scholar El-Safy Ebn El-Assal was the secretary of this council. This father
sat on the Patriarchal Chair for seven years, eight month and twenty three
days. He departed in El-Shamaa (Wax) monastery in the year 959 A.M. (March
10, 1243 A.D.)
