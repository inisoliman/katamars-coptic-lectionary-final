 When Armenius heard what this
Saint was performing signs and wonders, he ordered him to be tortured with
different kinds of tortures: to be squeezed with the wheel, to cut off
his members, to cast him to ferocious lions, to throw him into the sea,
and to cast him into hot fire. The Lord strengthened him and all these
tortures did not harm him. This Saint had a virgin sister called Mariam
who served the church and two brothers named Yoannis and Isaac. They came
to him while he was in prison and wept before him saying: &quot;You have been
a father to us, after our father; so how can you depart and leave us orphans?&quot;
He comforted, encouraged, consoled, and asked them to leave in peace. Finally,
not wanting to see the Saint tortured any more, Julius EL-Akfahsi advised
the governor saying: &quot;Write the decree of this old man and get rid of him&quot;
The Governor listened to him and ordered his head to be cut off. Julius
took his body and swathed it in wrappings embroidered in gold. He placed
a golden cross on his chest and sent the body with his men in a ship to
his Episcopal seat in Nikiu. The ship sailed until it arrived to the city
of Ashmun Grais (Ashmun Kharirat). It stopped as if it had been tied with
chains and all attempts to move it failed. While they were trying to do
that, a voice came out of the body saying: &quot;This is the place wherein God
is pleased that my body shall rest.&quot; When they told the people of the city,
they came out to the ship carrying palm branches. They carried the body
with great honor to their city. He lived for one-hundred thirty one years;
thirty of them as a priest, thirty nine as a bishop, and he completed his
good strife and received the crown of life.
