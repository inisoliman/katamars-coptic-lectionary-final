 On this day the blessed Saint
Anba Makrawy (Macrobius) the bishop was martyred. This father was of the
nobles of Ashmun Grais (Ashmun Kharirat) and he was ordained bishop for
Nikiu (Nakiyos). When persecution against Christians started, Youfanyous,
the Governor, sent for the Saint to appear before him. Before he went to
the Governor, he went before the Holy Altar, lifted up his hands and prayed.
He hid the Altar accessories (Utensils) and the service vestments in a
place in the altar. He prayed again to the Lord Christ to guard His church.
Then he went with the messengers to the Governor who asked him about his
name and his hometown. When the Governor realized that he was the Bishop
of the city, he ordered him to be beaten and humiliated. They mixed lime
with vinegar and poured it down his throat. Nevertheless, God guarded him
and he was unharmed. Later, the Governor sent him to Armenius, the Governor
of Alexandria, who casted him into prison. The Lord made, through his hands,
many signs. Eucharistos, the son of Julius EL-Akfahsi, the writers of the
biography of the martyrs, was paralytic. St.Macrobius prayed over him and
God healed him through his prayers. He celebrated the Divine Liturgy in
Julius home, administered the Holy Mysteries to them, and asked Julius
to care for his body and to write his biography.</p>
