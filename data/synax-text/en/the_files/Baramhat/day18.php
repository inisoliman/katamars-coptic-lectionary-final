 On this day St. Isidore the companion of Sina the
soldier was martyred. Sina, who was a native of the city of Deknash, was
one of the soldiers who accompanied the Governor of Farma. St. Isidore
was his friend and he was working as wool maker. Both of them gave alms
to the poor and needy with what they earned. One night both saw a vision
and it seemed to them that a virgin came to them with crowns which she
placed on their heads. When they woke up from their sleep they told each
other about what they had seen, and they rejoiced greatly as they believed
that the Lord had called them to receive the crown of martyrdom. They went
to the Governor and sina unbound the soldier's girdle and cast it down
before him and they both confessed the Lord Christ. He ordered their detention
but God sent His angel and comforted them. The Governor sent St. Sina to
Alexandria and St. Isidore remained prisoner alone. After a short period
St. Sina was returned back to the Farma and St. Isidore rejoiced at meeting
his friend, and they told each other what had happened to them. The Governor
tortured them severely and ordered St. Isidore to be cast into a pit with
fire therein. St. Isidore asked the soldier to wait and he prayed asking
our Lord Christ to accept his soul and to care for his body. He gave himself
to the soldiers and they threw him into the pit but his body was not harmed
in any way by the fire. The mother of St. Sina was weeping for her son
because of his separation from his friend. After a short while St. Isidore
delivered up his soul and at that time the mother of St. Sina saw a multitude
of angels carrying away St. Isidore's soul.
