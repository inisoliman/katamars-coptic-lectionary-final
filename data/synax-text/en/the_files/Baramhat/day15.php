 On this day departed the righteous and
     ascetic St. Sarah the nun who was a native of Upper Egypt. Her parents,
     who were exceedingly rich, were Christians and had no other children. They
     raised her in a christian manner and taught her reading and writing. She
     was always reading the books of the church and especially the biography
     and sayings of the fathers the monks. She was influenced by their lives
     and desired the ascetic life. She went to one of the convents of Upper
     Egypt and dwelt there for many years serving the virgins. Then she put
     on the monastic garb, persisting on fighting the lust of Satan for thirteen
     years until Satan was weary of her. When Satan was exasperated from her
     steadfastness and purity, he wished to overthrow her by the sin of pride.
     He appeared to her while she was standing praying on the roof of her cell
     and said to her: &quot;Rejoice for you have overcome Satan.&quot; She replied: &quot;I
     am a feeble woman, and I can not conquer you except by the power of the
     Lord Christ&quot; and then Satan vanished.</p>
