This Saint had many useful sayings that
     she used to say to the nuns. One of her sayings: &quot;I never set my foot upon
     the step of the ladder, and I never go up to the next step without thinking
     I may die before I raise my leg so that the enemy might not entice me with
     the hope of a long life.&quot; And she also said: &quot; IT is better for a man to
     show mercy even to satisfy men for the time will come that it will be to
     satisfy God.&quot; She also had many other sayings written in the Paradise of
     the Fathers. She stayed on the banks of the river in a cave for sixty years
     fighting a great fight and no one saw her until she departed to the eternal
     bless and she was eighty years old.
