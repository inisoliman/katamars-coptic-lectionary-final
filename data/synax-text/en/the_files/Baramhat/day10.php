 The church celebrates the appearance of the
     glorious Cross of Our Lord and Saviour Jesus Christ twice: <b>The First</b>
     on the sixteenth day of the month of Tut, 326 A.D. by the hands of the
     righteous Empress St. Helen, the mother of Constantine the great, the righteous
     Emperor. This Saint when her son Constantine accepted the Faith in the
     Lord Christ, she vowed to go to Jerusalem. Her righteous son prepared everything
     needed to fulfill this holy visit. When she arrived to Jerusalem with multitude
     of soldiers, she asked about the place of the Cross but no one would tell
     her. She took one of the jewish elders and pressured him by hunger and
     thirst until he was forced to direct them to the place where they might
     find the Cross at the hill of Golgotha. She ordered them to clear out the
     site of Golgotha where they found three crosses and that was in the year
     326 A.D. However, they did not know the cross upon which Our Lord Christ
     was crucified, they brought a dead man and they laid upon him one of the
     crosses and then the other but he did not rise up but when they laid the
     third cross upon him he rose up immediately, then they realized that this
     was the Cross of Our Lord Christ. The Empress and all the believers kneeled
     down before the Holy Cross, and she sent a piece of it with the nails to
     her son Constantine. Immediately after, she built the churches that were
     mentioned on the Sixteenth day of the blessed month of Tut.</p>
