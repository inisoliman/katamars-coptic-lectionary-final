 <b>The Second</b> celebration that the church
     commemorates the Cross is on the Tenth day of the month of Baramhat by
     the hands of Emperor Heraclius, in 627 A.D. When the Persians were defeated
     by Heraclius they retreated from Egypt to their country. On their way back
     they passed through Jerusalem, a persian prince entered the church of the
     Cross which was built by Empress Helen. He saw a great light shinning from
     a piece of wood located on a place decorated with gold. He thrust his hand
     to it and there went forth from it fire which burned his fingers. The Christians
     told him that this is the base of the Holy Cross and they told him how
     it was discovered and no one was able to touch it except a Christian. He
     deceived the two deacons who were standing to guard it and gave them much
     money so they would carry this piece and go with it with him to his country.
     They took it and put it in a box and went with him to his country along
     with those who were captured from the city of Jerusalem. When Emperor Heraclius
     heard that, he went with his army to Persia, fought with them and slew
     many of them. He traveled about this country searching for this piece of
     the Holy Cross but he could not find it, for the Persian prince had dug
     a hole in his garden and ordered the two deacons to put the box in it and
     buried it and then he killed them. One of the captives of that Persian
     prince which was the daughter of one of the priests, was looking out of
     the window by chance and saw what happened. She went to Heraclius the Emperor
     and told him what she saw. He went with the bishops, priests and the soldiers
     to the place. They dug there and found the box, they took the piece of
     the Holy Cross out, in 628 A.D., wrapped it in magnificent apparel and
     Heraclius took it to the city of Constantinople and kept it there.
